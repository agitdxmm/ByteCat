# ═══════════ 第 1 题 ═══════════
# 代码:
#     def f(x):
#         print(x * 2)
#
#     def g(x):
#         return x * 2
#
#     r1 = f(3)
#     r2 = g(3)
#     print("r1 =", r1)
#     print("r2 =", r2)
#
# 预测:（一共打印几行？r1 和 r2 分别是什么？）
#
# 实际:
#
# 差在哪:
#
def f(x):
    print(x * 2)


def g(x):
    return x * 2


r1 = f(3)
r2 = g(3)
print("r1 =", r1)
print("r2 =", r2)


# ═══════════ 第 2 题 ═══════════
# 代码:
#     def 加一(n):
#         n = n + 1
#         return n
#
#     a = 10
#     加一(a)
#     print(a)
#
# 预测:（print 出来是 10 还是 11？）
#
# 实际:
#
# 差在哪:（函数里改了 n，为什么外面的 a 没变？）
