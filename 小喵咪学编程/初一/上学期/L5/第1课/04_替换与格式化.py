    def 补齐(s, 宽, 对齐="<"):
        """按显示宽度补齐。"""
        差 = 宽 - 显示宽度(s)
        if 差 <= 0:
            return s
        if 对齐 == "<":
            return s + " " * 差
        if 对齐 == ">":
            return " " * 差 + s
        左 = 差 // 2
        return " " * 左 + s + " " * (差 - 左)


