    def 解析配置(文本):
        """返回 (配置, 错误列表, 重复键列表)。"""
        配置 = {}
        错误 = []
        重复 = []

        for 行号, 行 in enumerate(文本.splitlines(), 1):
            行 = 行.strip()

            # 跳过空行和注释
            if 行 == "" or 行.startswith("#"):
                continue

            # 用第一个 = 切
            键, 分隔符, 值 = 行.partition("=")

            if 分隔符 == "":
                错误.append(f"第 {行号} 行没有等号：{行}")
                continue

            键 = 键.strip()
            值 = 值.strip()

            if 键 == "":
                错误.append(f"第 {行号} 行键为空：{行}")
                continue

            if 键 in 配置:
                重复.append(f"第 {行号} 行键「{键}」重复，已覆盖")

            配置[键] = 值

        return 配置, 错误, 重复


