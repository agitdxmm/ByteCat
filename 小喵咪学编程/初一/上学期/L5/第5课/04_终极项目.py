    def 预算检查(账本, 预算, 年月=None):
        """检查当月支出是否超预算。"""
        from datetime import datetime as dt
        if 年月 is None:
            年月 = dt.now().strftime("%Y-%m")

        统计 = 月度统计(账本, 年月)
        支出 = 统计["支出"]

        if 支出 > 预算:
            return False, f"⚠ {年月} 支出 {支出:.2f} 已超预算 {预算:.2f}（超 {支出 - 预算:.2f}）"
        elif 支出 > 预算 * 0.8:
            return True, f"注意：{年月} 支出 {支出:.2f}，已用掉预算的 {支出 / 预算 * 100:.0f}%"
        else:
            return True, f"{年月} 支出 {支出:.2f}，预算还剩 {预算 - 支出:.2f}"


