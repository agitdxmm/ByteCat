import json
import os
from datetime import datetime

数据文件 = "记账数据.json"


# ══════ 数据层 ══════


def 读账本(路径=数据文件):
    """读账本。文件不存在或损坏时返回空列表。"""
    if not os.path.isfile(路径):
        return []

    try:
        with open(路径, "r", encoding="utf-8") as f:
            数据 = json.load(f)
        if not isinstance(数据, list):
            print("  ⚠ 数据格式不对，从空账本开始")
            return []
        return 数据
    except (json.JSONDecodeError, UnicodeDecodeError) as e:
        print(f"  ⚠ 账本文件损坏（{e}），从空账本开始")
        return []


def 写账本(账本, 路径=数据文件):
    """保存账本。"""
    try:
        with open(路径, "w", encoding="utf-8") as f:
            json.dump(账本, f, ensure_ascii=False, indent=2)
        return True
    except OSError as e:
        print(f"  ⚠ 保存失败：{e}")
        return False


def 下一个编号(账本):
    """生成下一个可用编号。"""
    if len(账本) == 0:
        return 1
    最大 = 0
    for 条 in 账本:
        if 条["编号"] > 最大:
            最大 = 条["编号"]
    return 最大 + 1


# ══════ 校验层 ══════


def 是正数(s):
    """判断字符串是不是正数（允许小数）。"""
    try:
        值 = float(s)
        return 值 > 0
    except (ValueError, TypeError):
        return False


def 校验金额(s):
    """返回 (金额, 错误信息)。"""
    s = s.strip()
    if not s:
        return None, "金额不能为空"
    try:
        金额 = float(s)
    except ValueError:
        return None, f"「{s}」不是数字"
    if 金额 <= 0:
        return None, "金额必须大于 0"
    if 金额 > 1000000:
        return None, "金额太大了"
    return round(金额, 2), None


def 校验类型(s):
    """返回 (类型, 错误信息)。"""
    s = s.strip().lower()
    映射 = {
        "收": "收入", "收入": "收入", "s": "收入", "+": "收入",
        "支": "支出", "支出": "支出", "z": "支出", "-": "支出",
    }
    if s in 映射:
        return 映射[s], None
    return None, "只能输入「收」或「支」"


# ══════ 操作层 ══════


def 添加(账本, 类型, 金额, 分类, 备注=""):
    """添加一条记录，返回 (新记录, 错误信息)。"""
    if 类型 not in ("收入", "支出"):
        return None, "类型只能是「收入」或「支出」"
    if not isinstance(金额, (int, float)) or 金额 <= 0:
        return None, "金额必须是正数"

    记录 = {
        "编号": 下一个编号(账本),
        "日期": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "类型": 类型,
        "金额": round(float(金额), 2),
        "分类": 分类.strip() or "未分类",
        "备注": 备注.strip(),
    }
    账本.append(记录)
    return 记录, None


def 删除(账本, 编号):
    """按编号删除，返回 (是否成功, 说明)。"""
    for i, 条 in enumerate(账本):
        if 条["编号"] == 编号:
            删掉的 = 账本.pop(i)
            return True, f"已删除 #{编号}（{删掉的['分类']} {删掉的['金额']}）"
    return False, f"找不到编号 {编号}"


def 按分类查(账本, 分类):
    """返回该分类的所有记录。"""
    return [条 for 条 in 账本 if 条["分类"] == 分类]


def 排序_按日期倒序(账本):
    """按日期倒序（最新的在前）。"""
    return sorted(账本, key=lambda x: x["日期"], reverse=True)


# ══════ 统计层 ══════


def 汇总(账本):
    """返回 (总收入, 总支出, 结余)。"""
    收入 = sum(条["金额"] for 条 in 账本 if 条["类型"] == "收入")
    支出 = sum(条["金额"] for 条 in 账本 if 条["类型"] == "支出")
    return round(收入, 2), round(支出, 2), round(收入 - 支出, 2)


def 分类汇总(账本):
    """返回 {分类: {"收入": x, "支出": y, "笔数": n}}。"""
    结果 = {}
    for 条 in 账本:
        类 = 条["分类"]
        if 类 not in 结果:
            结果[类] = {"收入": 0, "支出": 0, "笔数": 0}
        结果[类][条["类型"]] += 条["金额"]
        结果[类]["笔数"] += 1

    for 数据 in 结果.values():
        数据["收入"] = round(数据["收入"], 2)
        数据["支出"] = round(数据["支出"], 2)
    return 结果


# ══════ 显示层 ══════


def 分隔线(字符="-", 宽=52):
    print(字符 * 宽)


def 打印账本(账本):
    if len(账本) == 0:
        print("  （账本是空的）")
        return

    分隔线()
    print(f"  {'编号':<6}{'日期':<18}{'类型':<6}{'金额':>10}{'分类':<8}")
    分隔线("-")

    for 条 in 排序_按日期倒序(账本):
        符号 = "+" if 条["类型"] == "收入" else "-"
        print(f"  {条['编号']:<6}{条['日期']:<18}{条['类型']:<6}"
              f"{符号}{条['金额']:>9.2f}{条['分类']:<8}")

    分隔线("-")
    收入, 支出, 结余 = 汇总(账本)
    print(f"  收入 {收入:.2f}　支出 {支出:.2f}　结余 {结余:.2f}")
    分隔线()


def 打印统计(账本):
    if len(账本) == 0:
        print("  （还没有记录）")
        return

    收入, 支出, 结余 = 汇总(账本)

    分隔线("=")
    print("  收支统计".center(48))
    分隔线("=")
    print(f"  总收入：{收入:>10.2f}")
    print(f"  总支出：{支出:>10.2f}")
    print(f"  结余：  {结余:>10.2f}")

    分隔线("-")
    print("  按分类：")
    print(f"    {'分类':<10}{'笔数':>6}{'收入':>10}{'支出':>10}")

    for 类, 数据 in sorted(分类汇总(账本).items(),
                           key=lambda x: -(x[1]["收入"] + x[1]["支出"])):
        print(f"    {类:<10}{数据['笔数']:>6}"
              f"{数据['收入']:>10.2f}{数据['支出']:>10.2f}")

    分隔线("=")


def 打印菜单():
    print()
    分隔线("=")
    print("  我的记账本".center(48))
    分隔线("=")
    print("  1. 记一笔")
    print("  2. 查看全部")
    print("  3. 查看统计")
    print("  4. 按分类查")
    print("  5. 删除一笔")
    print("  0. 退出")
    分隔线("-")


# ══════ 主流程 ══════


def 主循环(账本, 模拟输入=None):
    """菜单驱动的主循环。模拟输入用于测试。"""

    def 读(提示=""):
        if 模拟输入 is not None:
            if len(模拟输入) == 0:
                return ""
            值 = 模拟输入.pop(0)
            print(f"  {提示}{值}")
            return 值
        return input(提示)

    while True:
        打印菜单()
        选择 = 读("请选择：").strip()

        if 选择 == "0":
            print("  再见")
            break

        elif 选择 == "1":
            print("\n  【记一笔】")
            类型文本 = 读("  收入还是支出（收/支）：")
            类型, 错误 = 校验类型(类型文本)
            if 错误:
                print(f"  ⚠ {错误}")
                continue

            金额文本 = 读("  金额：")
            金额, 错误 = 校验金额(金额文本)
            if 错误:
                print(f"  ⚠ {错误}")
                continue

            分类 = 读("  分类（餐饮/交通/工资…）：") or "未分类"
            备注 = 读("  备注（可空）：")

            记录, 错误 = 添加(账本, 类型, 金额, 分类, 备注)
            if 错误:
                print(f"  ⚠ {错误}")
            else:
                print(f"  ✓ 已记录 #{记录['编号']}")

        elif 选择 == "2":
            print("\n  【全部记录】")
            打印账本(账本)

        elif 选择 == "3":
            print("\n  【统计】")
            打印统计(账本)

        elif 选择 == "4":
            分类 = 读("\n  要查哪个分类：").strip()
            if not 分类:
                print("  ⚠ 分类不能为空")
                continue
            结果 = 按分类查(账本, 分类)
            if len(结果) == 0:
                print(f"  没有「{分类}」的记录")
            else:
                print(f"\n  【{分类}】共 {len(结果)} 笔")
                打印账本(结果)

        elif 选择 == "5":
            print("\n  【删除】")
            打印账本(账本)
            编号文本 = 读("  要删除哪一笔（输入编号）：").strip()

            try:
                编号 = int(编号文本)
            except ValueError:
                print(f"  ⚠ 「{编号文本}」不是编号")
                continue

            成功, 说明 = 删除(账本, 编号)
            print(("  ✓ " if 成功 else "  ⚠ ") + 说明)

        else:
            print(f"  ⚠ 「{选择}」不是有效选择")


