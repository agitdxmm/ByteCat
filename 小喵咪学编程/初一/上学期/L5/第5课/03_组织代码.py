r'''
════════════════════════════════════════════════════════
  L5 · 第 5 课 · 用法 3        组织自己的代码
════════════════════════════════════════════════════════

一个文件写到 500 行，就该考虑拆了。

这一节讲：**怎么拆、拆成什么样。**

────────────────────────────────────────────────────────
【什么时候该拆文件】
════════════════════════════════════════════════════════

    ── 信号一：文件超过 400 行 ──

        不是硬规定，但超过这个数，找东西开始变难。

    ── 信号二：文件里明显分成几块 ──

        比如一个程序里有：

            · 处理日期的函数
            · 处理字符串的函数
            · 处理文件的函数
            · 主流程

        这四块天然可以分开。

    ── 信号三：有些代码想给别的项目用 ──

        如果一个函数写得好、通用，想复用，
        拆成单独模块最方便（复制一个文件就行）。

    ── 信号四：多人协作 ──

        两个人改同一个文件容易冲突。

    ── 不该拆的时候 ──

        ❌ 只有 100 行，拆成 5 个文件 —— 找起来更累
        ❌ 拆完之后「每个文件都要 import 另外四个」—— 耦合太紧
        ❌ 为了「看起来专业」而拆

    **拆分的目的是「让相关的东西在一起，不相关的分开」。**

────────────────────────────────────────────────────────
【一个项目的典型结构】
════════════════════════════════════════════════════════

    小型项目：

        我的工具/
        ├── main.py          主程序
        ├── 文本工具.py
        ├── 数据工具.py
        └── 配置.json

    ── 每个文件的职责 ──

        `main.py`      只负责「流程」：读配置 → 处理 → 输出
        `文本工具.py` 只放和字符串有关的函数
        `数据工具.py` 只放和数据转换有关的函数

        工具模块里**不应该有主流程**。

    ── 中型项目 ──

        我的项目/
        ├── main.py
        ├── 工具/
        │   ├── __init__.py
        │   ├── 文本.py
        │   └── 数据.py
        ├── 数据/
        │   └── config.json
        └── 输出/
            └── report.txt

        子目录叫「包」（package），里面要有一个 `__init__.py`。

        （Python 3.3+ 可以没有，但加上更规范，
          而且可以在这里写「包的说明」或者「导出哪些名字」。）

    ── 导入子目录里的模块 ──

        from 工具 import 文本
        文本.切词(...)

        或者：

        from 工具.文本 import 切词
        切词(...)

────────────────────────────────────────────────────────
【拆分的核心原则：依赖方向】
════════════════════════════════════════════════════════

    ── 好的结构 ──

        main.py  ──→  文本工具.py
                 ──→  数据工具.py

        工具模块之间**互不依赖**，都只被 main 用。

    ── 坏的结构 ──

        文本工具.py  ──→  数据工具.py
                     ←──

        互相导入 → 循环依赖 → Python 会报错或行为诡异。

        ImportError: cannot import name 'xxx' from partially
                     initialized module

    ── 怎么避免循环依赖 ──

        ① 把「两个模块都要用的东西」抽到第三个模块

               main.py
                  ↓
               ├── 文本工具.py
               ├── 数据工具.py
               └── 公共.py          ← 两边都用它

        ② 只在函数内部 import（延迟导入）

               def 需要时才用():
                   import 数据工具
                   ...

           能解决循环，但会让代码变难读，是最后手段。

    ── 一个判断方法 ──

        **画一个箭头图：谁用谁。**

        如果箭头成环，结构就有问题。

────────────────────────────────────────────────────────
【`__init__.py` 能做什么】
════════════════════════════════════════════════════════

    ── ① 标记这是个包 ──

        空的就行。

    ── ② 控制 `from 包 import *` 导入什么 ──

        在 `__init__.py` 里写：

            __all__ = ["文本", "数据"]

    ── ③ 让导入更短 ──

        假设 `工具/文本.py` 里有 `切词` 函数。

        没有 `__init__.py` 的内容时：

            from 工具.文本 import 切词

        在 `工具/__init__.py` 里写：

            from .文本 import 切词

        之后就能：

            from 工具 import 切词

        （`.文本` 前面的点表示「当前包」—— 这是相对导入。）

    ── ④ 写包的说明 ──

            """工具包：处理文本和数据。"""

        这样 `help(工具)` 能看到。

────────────────────────────────────────────────────────
【一个完整的拆分示例】
════════════════════════════════════════════════════════

    ── 拆分前：一个 300 行的文件 ──

        def 切词(文本): ...
        def 统计词频(文本): ...
        def 读文件(路径): ...
        def 写文件(路径, 内容): ...
        def 算平均(列表): ...
        def 算中位数(列表): ...
        def 主程序(): ...

    ── 拆分后 ──

        `文本工具.py`：
            """文本处理工具。"""
            def 切词(文本): ...
            def 统计词频(文本): ...

        `文件工具.py`：
            """文件读写工具。"""
            def 读文件(路径): ...
            def 写文件(路径, 内容): ...

        `统计工具.py`：
            """统计计算工具。"""
            def 算平均(列表): ...
            def 算中位数(列表): ...

        `main.py`：
            """主程序。"""
            from 文本工具 import 切词, 统计词频
            from 文件工具 import 读文件, 写文件
            from 统计工具 import 算平均

            def 主程序():
                内容 = 读文件("data.txt")
                词们 = 切词(内容)
                ...
                write("report.txt", ...)

            if __name__ == "__main__":
                主程序()

    ── 拆完之后的好处 ──

        ① 想知道「有哪些文本函数」，打开 `文本工具.py` 就够了
        ② 想改「算平均」，不会碰到文件读写的代码
        ③ `统计工具.py` 可以直接复制到别的项目
        ④ 每个文件都不超过 100 行

    ── 一个代价 ──

        要多写几行 import。

        **这个代价很小，收益很大。**

────────────────────────────────────────────────────────
【给文件起名】
────────────────────────────────────────────────────────

    ── 规矩 ──

        ✅ 小写 + 下划线：`text_tools.py`
        ✅ 中文也可以：`文本工具.py`
        ❌ 大写开头：`TextTools.py`（那是类名）
        ❌ 和标准库重名：`random.py`、`json.py`

    ── 名字要能说明职责 ──

        ✅ `文本工具.py`、`data_utils.py`
        ❌ `工具1.py`、`helper.py`、`misc.py`

        「helper」这种名字等于没起 ——
        你永远不知道里面是什么。

    ── 一个约定 ──

        `main.py`、`__main__.py` 通常表示「程序入口」。

        别人拿到你的项目，第一眼就知道从哪运行。

────────────────────────────────────────────────────────
【关于「包」的进一步】
════════════════════════════════════════════════════════

    这一节讲的「包」只是最基础的用法。

    真实项目还会涉及：

        · `setup.py` / `pyproject.toml`（打包发布）
        · 相对导入的坑（`from . import x` 在直接运行时失效）
        · 命名空间包
        · 虚拟环境（每个项目独立的依赖）

    这些等你要「发布自己的库」时再学。

    **现在掌握「拆文件 + 加 __init__.py + 正确导入」就够了。**
'''

