import os
import sys
import importlib

print("① 演示：动态创建一个模块文件")

模块目录 = "演示模块"
if not os.path.isdir(模块目录):
    os.makedirs(模块目录)

# 写一个模块文件
模块路径 = os.path.join(模块目录, "文本工具.py")
with open(模块路径, "w", encoding="utf-8") as f:
    f.write('''"""文本处理工具（演示用）。"""

标点 = ".,!?;:"


def 切词(文本):
    """切词并去标点。"""
    词们 = []
    for 词 in 文本.split():
        干净 = 词.strip(标点).lower()
        if 干净:
            词们.append(干净)
    return 词们


def 词数(文本):
    return len(切词(文本))


if __name__ == "__main__":
    print("这是直接运行 文本工具.py 时才会打印的")
''')

print("  已创建：", 模块路径)

print("\n② 导入这个模块")
# 把目录加到 sys.path，这样能 import
if 模块目录 not in sys.path:
    sys.path.insert(0, 模块目录)

import 文本工具

print("  模块的 __name__ =", repr(文本工具.__name__))
print("  模块的文档：", 文本工具.__doc__)
print("  切词结果：", 文本工具.切词("Hello, World! This is 文本"))
print("  词数：", 文本工具.词数("Hello, World! This is 文本"))

print("\n③ 只导入特定名字")
from 文本工具 import 切词

print("  直接调用 切词('a, b, c') =", 切词("a, b, c"))

print("\n④ 用别名")
import 文本工具 as 工具

print("  工具.词数('a b c') =", 工具.词数("a b c"))

print("\n⑤ dir 看模块里有什么")
名字们 = [n for n in dir(文本工具) if not n.startswith("_")]
print("  ", 名字们)

print("\n⑥ 模块的常量也能用")
print("  文本工具.标点 =", repr(文本工具.标点))

print("\n⑦ 对比：直接运行模块文件")
print("  如果运行 `python 文本工具.py`，")
print("  会打印「这是直接运行 文本工具.py 时才会打印的」")
print("  但通过 import 导入时不会 —— 因为 __name__ 不是 '__main__'")

print("\n⑧ 演示包结构")
包目录 = os.path.join(模块目录, "工具包")
if not os.path.isdir(包目录):
    os.makedirs(包目录)

with open(os.path.join(包目录, "__init__.py"), "w", encoding="utf-8") as f:
    f.write('''"""工具包。"""

from .文本 import 切词

__all__ = ["切词"]
''')

with open(os.path.join(包目录, "文本.py"), "w", encoding="utf-8") as f:
    f.write('''"""包内的文本模块。"""


def 切词(文本):
    return 文本.split()
''')

print("  创建的结构：")
print("    演示模块/")
print("    ├── 文本工具.py")
print("    └── 工具包/")
print("        ├── __init__.py")
print("        └── 文本.py")

if 模块目录 not in sys.path:
    sys.path.insert(0, 模块目录)

print("\n  （这里不实际 import，因为要处理 sys.path 的细节）")
print("  真实项目里目录结构固定，不会有这个问题。")

print("\n⑨ 清理演示文件")
import shutil

shutil.rmtree(模块目录)
if 模块目录 in sys.path:
    sys.path.remove(模块目录)
print("  已清理")

print("\n⑩ 总结：组织代码的三条原则")
print("  1. 相关的放一起，不相关的分开")
print("  2. 依赖方向单一（main → 工具），不能成环")
print("  3. 工具模块不做主流程，只提供函数")


