r'''
════════════════════════════════════════════════════════
  L5 · 第 2 课 · 用法 1        编码与进制
════════════════════════════════════════════════════════

字符在计算机里怎么存？数字的进制怎么换？

这一节讲「底层」一点的东西 —— 但都是能立刻用上的。

────────────────────────────────────────────────────────
【每个字符都有一个编号】
════════════════════════════════════════════════════════

    Python 里可以用 `ord()` 查字符的编号：

        ord("A")        → 65
        ord("a")        → 97
        ord("0")        → 48
        ord("中")       → 20013

    反过来，用 `chr()` 从编号得到字符：

        chr(65)         → "A"
        chr(97)         → "a"
        chr(20013)      → "中"

    ── 这个编号叫「码点」（code point）──

        它是 Unicode 标准里的位置编号，全世界通用。

        `ord` = ordinal（序数），`chr` = character。
        名字有点怪，记住功能就行：**ord 字符→数字，chr 数字→字符**。

────────────────────────────────────────────────────────
【几个要记住的码点】
════════════════════════════════════════════════════════

    ── 字母 ──

        A~Z     65 ~ 90
        a~z     97 ~ 122

        大写和小写差 **32**：

            chr(ord("A") + 32)      → "a"
            chr(ord("a") - 32)      → "A"

        所以「转大小写」也可以这样写（虽然不推荐，有现成方法）：

            def 转大写(s):
                return "".join(chr(ord(c) - 32) if "a" <= c <= "z" else c
                               for c in s)

    ── 数字 ──

        0~9     48 ~ 57

        `chr(ord("0") + 5)`     → "5"

    ── 空白 ──

        空格    32
        \t      9
        \n      10
        \r      13

    ── 中文 ──

        常用汉字（基本区）：19968 ~ 40959
        也就是 `\u4e00` ~ `\u9fff`

        这就是 L5 第 1 课判断中文用的那个范围。

    ── 记住这个规律的用处 ──

        判断「是不是数字字符」，不用 isdigit 也能写：

            def 是数字字符(c):
                return "0" <= c <= "9"

        —— 因为字符的码点顺序和数字顺序一致。

        同理 `"a" <= c <= "z"` 判断小写字母。

────────────────────────────────────────────────────────
【进制转换】
════════════════════════════════════════════════════════

    ── 十进制 → 其他进制 ──

        bin(255)        → "0b11111111"      二进制（binary）
        oct(255)        → "0o377"           八进制（octal）
        hex(255)        → "0xff"            十六进制（hexadecimal）

        ⚠ 结果带前缀 `0b`、`0o`、`0x`。

        去掉前缀：

            bin(255)[2:]        → "11111111"
            format(255, "b")    → "11111111"      推荐

    ── 其他进制 → 十进制 ──

        int("11111111", 2)      → 255
        int("377", 8)           → 255
        int("ff", 16)           → 255

        第 2 个参数是「按几进制解析」。

        `int("ff", 16)` 里的 "ff" 不用带 0x 前缀，
        但带了也能认：`int("0xff", 16)` → 255。

    ── 十六进制的字母不区分大小写 ──

        int("FF", 16)       → 255
        int("ff", 16)       → 255

    ── 各进制对照 ──

        十进制    二进制      八进制   十六进制
          0        0           0        0
          1        1           1        1
          8        1000        10        8
         10        1010        12        a
         15        1111        17        f
         16       10000        20       10
        255    11111111      377       ff
        256  100000000       400      100

    ── 为什么十六进制常用 ──

        因为 1 位十六进制 = 4 位二进制，正好对齐字节（8 位 = 2 位十六进制）。

        所以内存地址、颜色值、哈希值都用十六进制：

            #FF8000     颜色的 RGB（红 255，绿 128，蓝 0）
            0x7fff...   内存地址

────────────────────────────────────────────────────────
【编码：字符串 → 字节】
════════════════════════════════════════════════════════

    码点是「编号」，不是「存储形式」。

    存到文件、发到网络时，要转成**字节**（bytes）。

    ── encode：字符串 → 字节 ──

        "hello".encode("utf-8")
        → b'hello'

        "中".encode("utf-8")
        → b'\xe4\xb8\xad'          3 个字节

    ── decode：字节 → 字符串 ──

        b"hello".decode("utf-8")
        → "hello"

        b'\xe4\xb8\xad'.decode("utf-8")
        → "中"

    ── 为什么中文要 3 个字节 ──

        UTF-8 是「变长编码」：

            ASCII 字符（英文字母、数字）  1 字节
            大部分欧洲字符                2 字节
            中文、日文、韩文              3 字节
            生僻字、emoji                 4 字节

        所以：

            len("hello")            → 5     字符数
            len("hello".encode())   → 5     字节数（都是 ASCII）
            len("中文")             → 2     字符数
            len("中文".encode())    → 6     字节数（各 3 字节）

    ── 这是「字符数」和「字节数」的区别 ──

        L1 第 1 课讲过那个报错位置按字节算的坑，就是这个原因。

    ── UTF-8 vs GBK ──

        中文有两种常见编码：

            UTF-8   国际标准，中文 3 字节
            GBK     中国标准，中文 2 字节

        **同一个中文，两种编码的字节完全不同。**

             "中".encode("utf-8")    → b'\xe4\xb8\xad'
             "中".encode("gbk")      → b'\xd6\xd0'

        用 UTF-8 编码的字节，用 GBK 解码会乱码（或者报错）。

        **「乱码」的本质就是「编码和解码用了不同的规则」。**

    ── Python 3 默认用 UTF-8 ──

        open() 读文件时默认是 UTF-8（除非系统设置不同）。
        这是 L5 第 3 课要注意的地方。

    ── 什么时候要手动 encode/decode ──

        ① 处理二进制数据（图片、压缩包）
        ② 计算「字节数」（比如限制上传大小）
        ③ 调试编码问题
        ④ 加密、哈希

        日常字符串处理不太需要碰。
'''

