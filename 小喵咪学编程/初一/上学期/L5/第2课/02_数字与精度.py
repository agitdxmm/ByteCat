        if 税率 > 0:
            print(f"  税率：{税率 * 100:.0f}%")
        print("-" * 40)
        print(f"  总价：{显示(总价)} 元")
        print(f"  {人数} 人分摊：")
        for i, 份 in enumerate(明细, 1):
            print(f"    第 {i} 人：{显示(份)} 元")
        print("-" * 40)
        print(f"  合计：{显示(sum(明细))} 元")
        print(f"  校验：{'✓ 分毫不差' if sum(明细) == 总价 else '✗ 有问题'}")
