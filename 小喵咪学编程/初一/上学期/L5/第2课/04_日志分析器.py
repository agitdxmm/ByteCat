    def 找慢请求(日志, 阈值毫秒=1000):
        """返回耗时超过阈值的记录。"""
        结果 = []
        for 条 in 日志:
            字段 = 提取字段(条["消息"])
            if "time" in 字段:
                值 = 字段["time"]
                if 值.endswith("ms"):
                    数字 = 值[:-2]
                    if 数字.isdigit() and int(数字) > 阈值毫秒:
                        结果.append((条, int(数字)))
        return 结果


    def 用户活跃度(日志):
        """返回 [(用户, 次数), ...]，降序。"""
        次数 = {}
        for 条 in 日志:
            字段 = 提取字段(条["消息"])
            if "user" in 字段:
                名 = 字段["user"]
                次数[名] = 次数.get(名, 0) + 1
        return sorted(次数.items(), key=lambda x: -x[1])


    def 错误时间线(日志):
        """每个小时的错误数。"""
        结果 = {}
        for 条 in 日志:
            if 条["级别"] != "ERROR":
                continue
            时 = 条["时间"][:2]
            结果[时] = 结果.get(时, 0) + 1
        return 结果


    def 摘要一行(日志):
        """一句话摘要。"""
        if len(日志) == 0:
            return "没有日志"

        错误数 = sum(1 for x in 日志 if x["级别"] == "ERROR")

        用户们 = set()
        for 条 in 日志:
            字段 = 提取字段(条["消息"])
            if "user" in 字段:
                用户们.add(字段["user"])

        小时数 = 计数(日志, lambda x: x["时间"][:2])
        最忙时 = max(小时数.items(), key=lambda x: x[1])[0] if 小时数 else "-"

        return (f"共 {len(日志)} 条日志，{错误数} 条错误，"
                f"涉及 {len(用户们)} 个用户，最忙的时段是 {最忙时} 点")


