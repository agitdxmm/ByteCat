def 计数(列表, 取键):
    """通用的计数函数：按 取键 函数的结果分组计数。"""
    次数 = {}
    for 项 in 列表:
        键 = 取键(项)
        次数[键] = 次数.get(键, 0) + 1
    return 次数


def 找连续错误(日志, 阈值=2):
    """返回连续 ERROR 的片段。"""
    片段们 = []
    当前 = []
    for 条 in 日志:
        if 条["级别"] == "ERROR":
            当前.append(条)
        else:
            if len(当前) >= 阈值:
                片段们.append(当前)
            当前 = []
    if len(当前) >= 阈值:
        片段们.append(当前)
    return 片段们


