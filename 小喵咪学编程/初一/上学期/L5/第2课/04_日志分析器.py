    def 转CSV(日志):
        """转成 CSV 格式。"""
        行们 = []
        行们.append("日期,时间,级别,消息")
        for 条 in 日志:
            消息 = 条["消息"]
            # 消息里有逗号或引号 → 用引号包起来，内部引号翻倍
            if "," in 消息 or '"' in 消息:
                消息 = '"' + 消息.replace('"', '""') + '"'
            行们.append(f"{条['日期']},{条['时间']},{条['级别']},{消息}")
        return "\n".join(行们)


    def 转JSON(日志):
        """转成 JSON（手写）。"""
        条目 = []
        for 条 in 日志:
            部分 = []
            for 键 in ["日期", "时间", "级别", "消息"]:
                值 = 条[键].replace("\\", "\\\\").replace('"', '\\"')
                部分.append(f'"{键}": "{值}"')
            条目.append("{" + ", ".join(部分) + "}")
        return "[\n  " + ",\n  ".join(条目) + "\n]"


