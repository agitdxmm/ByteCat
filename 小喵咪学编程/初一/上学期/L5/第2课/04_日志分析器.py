def 解析行(行):
    """返回字典，格式不对返回 None。"""
    部分 = 行.split(" ", 3)
    if len(部分) != 4:
        return None
    if not (部分[2].startswith("[") and 部分[2].endswith("]")):
        return None
    return {
        "日期": 部分[0],
        "时间": 部分[1],
        "级别": 部分[2].strip("[]"),
        "消息": 部分[3],
    }


def 提取字段(消息):
    """从消息里提取 key=value。"""
    结果 = {}
    for 部分 in 消息.split():
        if "=" in 部分:
            键, _, 值 = 部分.partition("=")
            if 键 and 值:
                结果[键] = 值
    return 结果


def 解析日志(文本):
    """返回 (有效列表, 无效行数)。"""
    有效 = []
    无效 = 0
    for 行 in 文本.splitlines():
        行 = 行.strip()
        if not 行:
            continue
        条 = 解析行(行)
        if 条 is None:
            无效 += 1
        else:
            有效.append(条)
    return 有效, 无效


