r'''
════════════════════════════════════════════════════════
  L5 · 第 4 课 · 用法 4        综合项目：健壮的数据导入器
════════════════════════════════════════════════════════

需求：从一批 CSV 文件里导入数据，任何环节出问题都不能崩。

这个项目把「文件读写 + 字符串处理 + 异常处理」全串起来。

────────────────────────────────────────────────────────
【需求分析】
════════════════════════════════════════════════════════

    输入：一个目录，里面有若干 .csv 文件

    每个文件的格式（可能有问题）：

        姓名,年龄,分数
        张三,18,92
        李四,20,88
        王五,abc,90          ← 年龄不是数字
        ,19,75               ← 姓名为空
        赵六,150,85          ← 年龄不合理
        钱七,21,                ← 分数缺失
        孙八,22,100

    输出：
        · 有效数据列表
        · 问题报告（哪个文件、第几行、什么问题）
        · 汇总统计

    ── 可能出问题的地方 ──

        ① 目录不存在
        ② 文件读不了（权限、编码）
        ③ CSV 格式不对（列数不够）
        ④ 字段内容不合法（年龄不是数字、分数超范围）
        ⑤ 姓名为空
        ⑥ 整个目录一个文件都没有

    **每一处都要处理，而且不能因为一条坏数据就全停。**

────────────────────────────────────────────────────────
【设计：分层 + 错误收集】
════════════════════════════════════════════════════════

    四层：

        ① 发现层：找出所有 csv 文件
        ② 读取层：读一个文件的所有行
        ③ 校验层：检查每一行的字段
        ④ 汇总层：统计 + 报告

    ── 错误收集的设计 ──

        不要在出错的地方直接 print。

        而是**收集到一个列表里**，最后统一报告：

            问题 = []
            问题.append({
                "文件": 文件名,
                "行号": i,
                "问题": "年龄不是数字",
                "原始": 行,
            })

        为什么：
            · 能统计「一共几个问题」
            · 能按类型分组
            · 能写到日志文件

        边处理边 print 的话，这些信息就散了。

    ── 校验函数的设计 ──

        def 校验一行(行, 行号, 文件名):
            """返回 (数据字典 或 None, 问题列表)。"""

        返回两个东西：
            · 成功 → (字典, [])
            · 失败 → (None, ["问题1", "问题2"])

        一行可能有**多个**问题（比如姓名空 + 年龄不合法）。

        **一次把所有问题找出来，而不是「发现第一个就返回」。**

        —— 因为用户改一次文件不容易，别让他改 5 次。

────────────────────────────────────────────────────────
【关键：异常处理的层次】
════════════════════════════════════════════════════════

    ── 最外层：整个程序 ──

        try:
            主流程()
        except Exception as e:
            print(f"程序异常退出：{e}")

        兜底，防止「意外崩溃」。

        ⚠ 但这不能替代内部的精细处理 ——
          它只是「最后一道防线」。

    ── 文件级：一个文件读失败 ──

        try:
            内容 = 读文件(路径)
        except Exception as e:
            问题.append({"文件": 文件名, "问题": f"读不了：{e}"})
            continue          ← 跳到下一个文件

        一个文件坏了，不影响其他文件。

    ── 行级：一行数据有问题 ──

        try:
            数据, 错误们 = 校验一行(...)
        except Exception as e:
            问题.append({...})
            continue          ← 跳到下一行

    ── 字段级：一个字段转换失败 ──

        try:
            年龄 = int(年龄文本)
        except ValueError:
            问题.append("年龄不是数字")
            年龄 = None

        这一级**不 continue** —— 因为其他字段还要检查。

    ── 三层 try 的嵌套 ──

        这就是「错误隔离」：
        **每一层的失败只在它自己的范围内传播。**

        最内层失败 → 只影响这个字段
        行级失败 → 只影响这一行
        文件级失败 → 只影响这个文件

    **好的程序不是「不会出错」，是「出错不影响整体」。**

────────────────────────────────────────────────────────
【一个重要的取舍：要不要吞掉异常】
════════════════════════════════════════════════════════

    这个项目里，「文件读不了」「一行数据坏了」都用 `except` 吞掉了。

    因为它们**是预期内的**（真实数据总会有问题）。

    但如果是「代码写错了」（比如变量名拼错），
    就不该吞 —— 那需要修代码。

    ── 怎么区分 ──

        捕获**具体的**异常类型：

            ✅ except (FileNotFoundError, UnicodeDecodeError):
                   → 数据/环境问题，可以继续
            ✅ except ValueError:
                   → 数据内容问题，可以继续

            ❌ except Exception:
                   → 什么都吞，包括代码 bug

        **能写具体类型就写具体类型。**

        （这个项目里为了演示，有些地方用了 Exception。
          真实项目里应该尽量细化。）

────────────────────────────────────────────────────────
【报告的设计】
════════════════════════════════════════════════════════

    ── 按文件分组 ──

        某个人看到报告，最想知道「我的哪个文件有问题」。

    ── 按问题类型分组 ──

        「年龄不合法 3 条」「姓名为空 2 条」——
        能看出「主要问题是什么」。

    ── 保留原始数据 ──

        报告里要显示「出问题的那一行原样是什么」，
        否则用户不知道去改哪里。

    ── 一个例子 ──

        ============================================================
                              数据导入报告
        ============================================================
          扫描目录：F:\...\数据
          文件数：2    成功：1    失败：1

        ------------------------------------------------------------
          数据汇总：
            导入成功：5 条
            存在问题：3 条

        ------------------------------------------------------------
          问题清单：
            [student1.csv] 第 4 行：年龄「abc」不是整数
              原始：王五,abc,90
            [student1.csv] 第 5 行：姓名为空
              原始：,19,75
            [student1.csv] 第 6 行：年龄 150 超出 1~120
              原始：赵六,150,85

        ------------------------------------------------------------
          问题类型统计：
            年龄不是整数      1 条
            姓名为空          1 条
            年龄超范围        1 条
        ============================================================

    **这个报告能让用户直接去改文件。**
'''

