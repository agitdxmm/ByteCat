import os
import csv


def 读一行(行们, 表头):
    """把一行列表转成字典。"""
    结果 = {}
    for i, 字段名 in enumerate(表头):
        if i < len(行们):
            结果[字段名] = 行们[i].strip()
        else:
            结果[字段名] = ""
    return 结果


def 校验(数据, 行号, 文件名):
    """返回 (有效字典 或 None, 问题列表)。"""
    问题 = []

    # 姓名
    姓名 = 数据.get("姓名", "").strip()
    if not 姓名:
        问题.append("姓名为空")
    elif len(姓名) > 20:
        问题.append(f"姓名太长（{len(姓名)} 字）")

    # 年龄
    年龄文本 = 数据.get("年龄", "").strip()
    年龄 = None
    if not 年龄文本:
        问题.append("年龄缺失")
    else:
        try:
            年龄 = int(年龄文本)
            if not (1 <= 年龄 <= 120):
                问题.append(f"年龄 {年龄} 超出 1~120")
                年龄 = None
        except ValueError:
            问题.append(f"年龄「{年龄文本}」不是整数")

    # 分数
    分数文本 = 数据.get("分数", "").strip()
    分数 = None
    if not 分数文本:
        问题.append("分数缺失")
    else:
        try:
            分数 = float(分数文本)
            if not (0 <= 分数 <= 100):
                问题.append(f"分数 {分数} 超出 0~100")
                分数 = None
        except ValueError:
            问题.append(f"分数「{分数文本}」不是数字")

    if 问题:
        return None, 问题

    return {"姓名": 姓名, "年龄": 年龄, "分数": 分数}, []


def 读一个文件(路径, 文件名):
    """返回 (有效数据列表, 问题列表)。"""
    有效 = []
    问题 = []

    try:
        with open(路径, "r", encoding="utf-8", newline="") as f:
            行们 = list(csv.reader(f))
    except UnicodeDecodeError as e:
        问题.append({
            "文件": 文件名, "行号": "-",
            "问题": f"编码不是 UTF-8：{e}", "原始": "",
        })
        return 有效, 问题
    except OSError as e:
        问题.append({
            "文件": 文件名, "行号": "-",
            "问题": f"读不了文件：{e}", "原始": "",
        })
        return 有效, 问题

    if len(行们) == 0:
        问题.append({
            "文件": 文件名, "行号": "-",
            "问题": "空文件", "原始": "",
        })
        return 有效, 问题

    表头 = [h.strip() for h in 行们[0]]
    必需字段 = ["姓名", "年龄", "分数"]
    缺字段 = [f for f in 必需字段 if f not in 表头]
    if 缺字段:
        问题.append({
            "文件": 文件名, "行号": 1,
            "问题": f"表头缺字段：{缺字段}",
            "原始": ",".join(行们[0]),
        })
        return 有效, 问题

    for i, 行 in enumerate(行们[1:], 2):
        if not 行 or all(not x.strip() for x in 行):
            continue

        数据 = 读一行(行, 表头)
        结果, 错误们 = 校验(数据, i, 文件名)

        if 结果:
            有效.append(结果)
        else:
            for 错误 in 错误们:
                问题.append({
                    "文件": 文件名, "行号": i,
                    "问题": 错误,
                    "原始": ",".join(行),
                })

    return 有效, 问题


def 导入目录(目录):
    """返回 (所有有效数据, 所有问题, 文件统计)。"""
    所有有效 = []
    所有问题 = []
    统计 = {"文件数": 0, "成功文件": 0, "失败文件": 0}

    if not os.path.isdir(目录):
        所有问题.append({
            "文件": "-", "行号": "-",
            "问题": f"目录不存在：{目录}", "原始": "",
        })
        return 所有有效, 所有问题, 统计

    文件名们 = [f for f in sorted(os.listdir(目录))
               if f.lower().endswith(".csv")]

    统计["文件数"] = len(文件名们)

    for 文件名 in 文件名们:
        路径 = os.path.join(目录, 文件名)
        try:
            有效, 问题 = 读一个文件(路径, 文件名)
        except Exception as e:
            所有问题.append({
                "文件": 文件名, "行号": "-",
                "问题": f"意外错误：[{type(e).__name__}] {e}",
                "原始": "",
            })
            统计["失败文件"] += 1
            continue

        所有有效.extend(有效)
        所有问题.extend(问题)

        if 问题:
            统计["失败文件"] += 1
        else:
            统计["成功文件"] += 1

    return 所有有效, 所有问题, 统计


def 打印报告(目录, 有效, 问题, 统计):
    print("=" * 64)
    print("数据导入报告".center(60))
    print("=" * 64)
    print(f"  扫描目录：{os.path.abspath(目录)}")
    print(f"  文件数：{统计['文件数']}    "
          f"成功：{统计['成功文件']}    有问题：{统计['失败文件']}")

    print("-" * 64)
    print(f"  导入成功：{len(有效)} 条")
    print(f"  存在问题：{len(问题)} 条")

    if 有效:
        print("-" * 64)
        print("  有效数据：")
        print(f"    {'姓名':<10}{'年龄':>6}{'分数':>8}")
        for 条 in 有效:
            print(f"    {条['姓名']:<10}{条['年龄']:>6}{条['分数']:>8.1f}")

        平均分 = sum(条["分数"] for 条 in 有效) / len(有效)
        平均年龄 = sum(条["年龄"] for 条 in 有效) / len(有效)
        print(f"    {'平均':<10}{平均年龄:>6.1f}{平均分:>8.1f}")

    if 问题:
        print("-" * 64)
        print("  问题清单：")
        for 项 in 问题:
            print(f"    [{项['文件']}] 第 {项['行号']} 行：{项['问题']}")
            if 项["原始"]:
                print(f"      原始：{项['原始']}")

        print("-" * 64)
        print("  问题类型统计：")
        类型数 = {}
        for 项 in 问题:
            名 = 项["问题"].split("「")[0].split("（")[0]
            类型数[名] = 类型数.get(名, 0) + 1
        for 名, n in sorted(类型数.items(), key=lambda x: -x[1]):
            print(f"    {名:<20}{n:>3} 条")

    print("=" * 64)


