print("① 最简单的 for")
for i in range(5):
    print(i, end=" ")
print("  ← range(5) 是 0 1 2 3 4")

print("\n② 从 1 开始")
for i in range(1, 6):
    print(i, end=" ")
print("  ← range(1, 6) 是 1 到 5，不含 6")

print("\n③ 步长")
for i in range(0, 11, 2):
    print(i, end=" ")
print("  ← 从 0 到 10，每次加 2")

print("\n④ 倒着来")
for i in range(5, 0, -1):
    print(i, end=" ")
print("  ← 从 5 到 1")

print("\n⑤ 遍历字符串")
for 字 in "小喵咪":
    print(字, end=" ")
print()

print("\n⑥ 循环里做计算")
for i in range(1, 6):
    print(f"{i} 的平方是 {i ** 2}")

print("\n⑦ 累加")
总和 = 0
for i in range(1, 101):
    总和 += i
print("1 到 100 的和：", 总和)

print("\n⑧ 循环结束后，变量还在")
for i in range(3):
    pass
print("循环结束，i =", i)


