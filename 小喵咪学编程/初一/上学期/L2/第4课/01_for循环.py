r"""
════════════════════════════════════════════════════════
  L2 · 第 4 课 · 用法 1        for 循环
════════════════════════════════════════════════════════

这一节把 for 讲完 —— 它和 while 干同一件事，但写法完全不同。

────────────────────────────────────────────────────────
【先对比】
────────────────────────────────────────────────────────

    while 的写法：

        i = 1
        while i <= 5:
            print(i)
            i += 1

    for 的写法：

        for i in range(1, 6):
            print(i)

    同样的结果，for 少了三样东西：
        不用写初始值
        不用写条件
        不用写 i += 1

    因为 for 的意思是「把这一堆东西挨个拿出来」。

────────────────────────────────────────────────────────
【for 的形状】
────────────────────────────────────────────────────────

    for 变量 in 一堆东西:
        循环体

    执行过程：
        从「一堆东西」里拿第一个，赋给变量，执行循环体
        拿第二个，执行循环体
        ...
        拿完了，循环结束

    关键：**for 不需要你管「什么时候停」**，
    东西拿完自然就停了。

────────────────────────────────────────────────────────
【range：生成一串整数】
────────────────────────────────────────────────────────

    for 最常配 range 用，因为 range 能造出一串数字。

        range(5)            →  0 1 2 3 4          （5 个，从 0 开始）
        range(1, 6)         →  1 2 3 4 5          （从 1 到 5）
        range(1, 10, 2)     →  1 3 5 7 9          （步长 2）
        range(10, 0, -1)    →  10 9 8 ... 1       （倒着来）

    ⚠ 最重要的一条：**range 是左闭右开的**。

        range(1, 6) 包括 1，不包括 6。
        所以它给的是 1 2 3 4 5，五个数。

    很多人第一反应是「1 到 6 应该是 6 个数」，然后循环少跑一次。
    这是初学 for 时最常见的错，没有之一。

────────────────────────────────────────────────────────
【为什么是左闭右开】
────────────────────────────────────────────────────────

    因为这样「长度 = 右 - 左」：

        range(1, 6)   长度 = 6 - 1 = 5
        range(0, 10)  长度 = 10 - 0 = 10

    如果左闭右闭，range(1, 6) 是 6 个数，长度 = 6-1+1，还得加一。

    而且左闭右开能无缝衔接：
        range(0, 5) 和 range(5, 10) 拼起来正好是 0-9，不重不漏。

────────────────────────────────────────────────────────
【for 也能遍历字符串】
────────────────────────────────────────────────────────

    for 字 in "abc":
        print(字)

    输出：a  b  c（每次一个）

    因为字符串也是一串东西，可以一个个拿出来。

    这个特性以后很有用（比如统计字符、逐字处理）。

────────────────────────────────────────────────────────
【for 里的变量叫「循环变量」】
────────────────────────────────────────────────────────

    它每轮都会被重新赋值，所以：

        for i in range(3):
            print(i)
        print("循环结束后 i 是", i)      →  2

    循环结束后 i 还留着最后的值（Python 的特性，其他语言可能不同）。

    如果你在循环外还需要 i，要小心它已经被改了。
    一般建议：循环变量只在循环里用，出来就别管它。

────────────────────────────────────────────────────────
【for 和 while 的根本区别】
────────────────────────────────────────────────────────

    while   你知道「什么时候停」，用条件控制
    for     你知道「要处理哪些东西」，用遍历

    能用 for 就用 for，因为：
        · 不会忘记 i += 1（不会死循环）
        · 代码短
        · 意图清楚（「对每一个……」）

    只有「不知道要循环几次」时才用 while。
"""

