r"""
════════════════════════════════════════════════════════
  L2 · 第 4 课 · 用法 2        range 详解
════════════════════════════════════════════════════════

这一节把 range 讲完 —— 它才是 for 循环真正的引擎。

────────────────────────────────────────────────────────
【三种写法】
────────────────────────────────────────────────────────

    range(停止)             从 0 开始，到 停止-1
    range(开始, 停止)        从 开始，到 停止-1
    range(开始, 停止, 步长)  从 开始，每次加 步长，到 停止-1

    永远是「左闭右开」：包含开始，不包含停止。

────────────────────────────────────────────────────────
【三个参数逐个看】
────────────────────────────────────────────────────────

    只给一个数：

        range(5)      →  0 1 2 3 4
        range(0)      →  空（一个都没有）
        range(-3)     →  空

    给两个：

        range(2, 6)   →  2 3 4 5
        range(6, 2)   →  空（开始比停止大，步长默认是正的，走不过去）

    给三个：

        range(0, 10, 2)    →  0 2 4 6 8
        range(10, 0, -2)   →  10 8 6 4 2
        range(5, 5)        →  空

────────────────────────────────────────────────────────
【左闭右开：再说一遍】
────────────────────────────────────────────────────────

    range(1, 11) 是 1 到 10，十个。
    range(1, 10) 是 1 到 9，九个。

    需要「1 到 n」时，写 range(1, n + 1)。

    这个 +1 会写一辈子，记住就好。

    ── 为什么这么设计 ──

        因为这样「个数 = 停止 - 开始」，不用加一：

            range(1, 11)  个数 = 11 - 1 = 10 ✓
            range(0, 100) 个数 = 100 - 0 = 100 ✓

        如果左闭右闭，个数就是 停止 - 开始 + 1，每次都要想一下。

────────────────────────────────────────────────────────
【步长可以是负数】
────────────────────────────────────────────────────────

    想倒着数，必须给负步长：

        range(5, 0, -1)    →  5 4 3 2 1
        range(5, 0)        →  空！因为默认步长 +1，5 加不到 0

    这个坑很多：
        写 range(5, 0) 以为会倒着数，结果一次都不循环。

    规律：
        步长为正 → 开始必须小于停止，否则空
        步长为负 → 开始必须大于停止，否则空

────────────────────────────────────────────────────────
【range 不是列表】
────────────────────────────────────────────────────────

    print(range(5))        →  range(0, 5)

    它打印不出 0 1 2 3 4，只显示它自己。

    因为 range 是「惰性」的 —— 它不真的存那一串数字，
    只在需要的时候一个个算出来。

    想看内容，得转成列表（L4 讲）或者用 for 遍历：

        for i in range(5):
            print(i)

    或者：
        print(list(range(5)))    →  [0, 1, 2, 3, 4]

    这个特性是优点：range(100000000) 不占内存，
    因为它不真的生成一亿个数。

────────────────────────────────────────────────────────
【range 能求长度】
────────────────────────────────────────────────────────

    len(range(5))          →  5
    len(range(1, 11))      →  10
    len(range(0, 10, 3))   →  4      （0,3,6,9）

    算的时候是「(停止 - 开始 + 步长 - 1) // 步长」，
    但一般直接用 len() 就行。

────────────────────────────────────────────────────────
【常见错误清单】
────────────────────────────────────────────────────────

    1. range(1, n) 少了一个
       → 循环少跑一次，最后一个数没处理

    2. range(1, 11) 以为到 11
       → 实际到 10

    3. range(5, 0) 以为倒序
       → 空的，需要 range(5, 0, -1)

    4. range(0, 10, 0) 步长为 0
       → ValueError: range() arg 3 must not be zero

    5. 在 for 里改 i
       for i in range(5):
           i = i * 2        ← 改了也没用，下一轮还是从 range 取
"""

