r"""
════════════════════════════════════════════════════════
  L2 · 第 4 课 · 用法 4        for 和 while 怎么选
════════════════════════════════════════════════════════

这一节把两种循环的取舍讲完 —— 它们能互相替代，但有一个更合适。

────────────────────────────────────────────────────────
【一句话区分】
────────────────────────────────────────────────────────

    for     你知道「要处理哪些东西」       → 遍历
    while   你知道「什么时候该停」        → 条件

    能说清「对每一个 X」的，用 for。
    只能说出「一直到 Y 为止」的，用 while。

────────────────────────────────────────────────────────
【六个典型场景，该用哪个】
────────────────────────────────────────────────────────

    1. 打印 1 到 100
       知道范围 → for

    2. 求 1 到 n 的和
       知道范围 → for

    3. 用户输入密码，直到输对为止
       不知道几次 → while（而且输入次数取决于用户）

    4. 遍历一个字符串的每个字符
       知道遍历对象 → for

    5. 一直跑，直到程序被关闭（游戏主循环）
       不知道几次 → while True（配 break）

    6. 找一个数，直到找到为止
       不知道几次 → while 配标志变量，或 while True + break

────────────────────────────────────────────────────────
【为什么「知道对象」就该用 for】
────────────────────────────────────────────────────────

    三个理由：

    一、不会死循环
        for 的终止由「东西拿完」保证，你不可能写错。
        while 要自己维护条件，忘了 i += 1 就死。

    二、意图更清楚
        for 字 in 文本:      →  一看就是「对每个字符」
        i = 0
        while i < len(文本):  →  要多想一步才知道在遍历

    三、少写两行
        初始值、变化都不用写。

────────────────────────────────────────────────────────
【while 不可替代的地方】
────────────────────────────────────────────────────────

    用 for 写这种需求会很别扭：

        猜数字游戏：
            答案是 42
            一直让用户猜，直到猜对

        用 while：
            while 猜的数 != 42:
                猜的数 = int(input("再猜："))

        用 for 怎么写？
            得先知道「最多猜几次」，如果不知道次数，就写不了。

    所以：
        **次数未知 → while**
        **次数已知 → for**

────────────────────────────────────────────────────────
【互相转换：能转，但有代价】
────────────────────────────────────────────────────────

    for → while（简单，但变长）：

        for i in range(1, 6):
            print(i)

        转成：

        i = 1
        while i <= 5:
            print(i)
            i += 1

        注意 range(1, 6) 对应 i <= 5，不是 i <= 6。

    while → for（只有「范围明确」时才行）：

        i = 1
        while i <= 5:
            print(i)
            i += 1

        转成：

        for i in range(1, 6):
            print(i)

    但如果是「一直等用户输入」那种 while，就转不了。

────────────────────────────────────────────────────────
【转换时最容易出的错】
────────────────────────────────────────────────────────

    一、边界漏一

        while i < 5     →   i 走 0 1 2 3 4
        对应 for 是 range(5)，不是 range(1, 5)

        while i <= 5    →   i 走 1 2 3 4 5
        对应 for 是 range(1, 6)

    记法：
        while i <= n   ↔   range(?, n + 1)
        while i < n    ↔   range(?, n)

    二、忘了改条件里的变量

        for 改 while 时，如果 while 条件是 i <= 5，
        循环体里必须写 i += 1，否则死循环。

    三、改变量改了两次

        从 for 转 while 时，如果原来循环体里也用了 i，
        容易重复添加 i += 1，导致跳着走。

────────────────────────────────────────────────────────
【一个反直觉的建议】
────────────────────────────────────────────────────────

    初学者往往更爱用 while，因为它「更自由」。
    但绝大多数 bug 都出在 while 上（死循环、边界错）。

    所以：
        **能用 for 就别用 while。**
        写 while 之前先问自己：这个真不能用 for 吗？

    等你熟练了，会自然倾向 for，因为省心。
"""

