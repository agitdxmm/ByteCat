    def 猜数字(猜测列表):
        答案 = 73
        次数 = 0
        上限 = 7
        下标 = 0

        while 次数 < 上限:
            if 下标 >= len(猜测列表):
                break
            原始 = 猜测列表[下标]
            下标 += 1

            try:
                猜 = int(原始)
            except ValueError:
                print(f"  「{原始}」不是数字，请重新输入")
                continue          # 不消耗次数

