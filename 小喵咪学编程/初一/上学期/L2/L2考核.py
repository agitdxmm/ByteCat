    def 是完数(n):
        if n < 2:
            return False
        和 = 1
        因子 = 2
        while 因子 * 因子 <= n:
            if n % 因子 == 0:
                和 += 因子
                另一个 = n // 因子
                if 另一个 != 因子:
                    和 += 另一个
            因子 += 1
        return 和 == n


    def 是水仙花数(n):
        if n < 100 or n > 999:
            return False
        百 = n // 100
        十 = n // 10 % 10
        个 = n % 10
        return 百 ** 3 + 十 ** 3 + 个 ** 3 == n


    def 是回文数(n):
        原 = n
        反 = 0
        while n > 0:
            反 = 反 * 10 + n % 10
            n //= 10
        return 原 == 反


    def 是素数(n):
        if n < 2:
            return False
        i = 2
        while i * i <= n:
            if n % i == 0:
                return False
            i += 1
        return True


    def 各位数字乘积(n):
        if n == 0:
            return 0
        积 = 1
        while n > 0:
            积 *= n % 10
            n //= 10
        return 积


    def 各位数字和(n):
        和 = 0
        while n > 0:
            和 += n % 10
            n //= 10
        return 和


