r"""
════════════════════════════════════════════════════════
  L2 · 第 2 课 · 用法 4      三种分支写法怎么选
════════════════════════════════════════════════════════

这一节把「同样的事有几种写法，该用哪个」讲完。

────────────────────────────────────────────────────────
【三种写法，一张表】
────────────────────────────────────────────────────────

    并列 if          每个条件独立判断，可能命中多个
    elif            从上往下，命中即停，最多命中一个
    嵌套 if         条件有先后依赖

────────────────────────────────────────────────────────
【并列 if：什么时候用】
────────────────────────────────────────────────────────

    适用：几件事互相独立，都可能发生。

    例：检查一份表单有多少个问题

        if not 名字:
            print("名字没填")
        if not 电话:
            print("电话没填")
        if 年龄 < 0:
            print("年龄不合法")

    三个问题可能同时存在，用户想知道全部。
    如果改成 elif，只会报第一个，修完再报第二个，体验很差。

    判断标准：**「这几个结果能同时出现吗？」**
        能 → 并列 if

────────────────────────────────────────────────────────
【elif：什么时候用】
────────────────────────────────────────────────────────

    适用：几件事互斥，只会发生一件。

    例：分档

        if 分数 >= 90:
            等级 = "A"
        elif 分数 >= 80:
            等级 = "B"
        else:
            等级 = "C"

    一个人不可能同时是 A 和 B。
    用 elif 就是「只取一个」，语义清楚，而且效率高（命中就停）。

    判断标准：**「这几个结果互斥吗？」**
        互斥 → elif

────────────────────────────────────────────────────────
【嵌套：什么时候用】
────────────────────────────────────────────────────────

    适用：后一个条件只有在前一个成立时才有意义。

    例：除法前的检查

        if 除数 != 0:
            if 100 / 除数 > 10:
                print("结果很大")

    第二个条件依赖第一个：除数 0 的时候 100/除数 直接崩。

    再例：
        if 用户存在:
            if 密码正确:
                登录

    「密码正确」这个判断，前提是「用户存在」。
    用户都不存在，谈什么密码。

    判断标准：**「后一个条件离开前一个会不会出错 / 变得没意义？」**
        会 → 嵌套

────────────────────────────────────────────────────────
【一个逻辑，三种写法】
────────────────────────────────────────────────────────

    需求：分数 60 以下打印「不及格」，60-79 打印「及格」，80 以上打印「优秀」。

    写法 A：并列 if（错的）

        if 分数 < 60:
            print("不及格")
        if 分数 >= 60:
            print("及格")
        if 分数 >= 80:
            print("优秀")

        85 分会打印「及格」和「优秀」两行。
        因为后两个条件同时成立。

        要修就得写完整的区间：
        if 分数 < 60: ...
        elif 60 <= 分数 < 80: ...
        else: ...

    写法 B：elif（推荐）

        if 分数 >= 80:
            print("优秀")
        elif 分数 >= 60:
            print("及格")
        else:
            print("不及格")

        简洁，互斥，顺序从大到小。

    写法 C：嵌套（没必要）

        if 分数 >= 60:
            if 分数 >= 80:
                print("优秀")
            else:
                print("及格")
        else:
            print("不及格")

        能跑，但比 B 多一层缩进，没带来任何好处。
        这种情况下嵌套是浪费。

────────────────────────────────────────────────────────
【怎么判断该用哪个：三个问题】
────────────────────────────────────────────────────────

    第 1 问：这几个结果能同时发生吗？
        能 → 并列 if
        不能 → 往下问

    第 2 问：后一个条件依赖前一个吗？
        依赖 → 嵌套（或者用 and 合并）
        不依赖 → 往下问

    第 3 问：那就用 elif。

    绝大多数情况都是 elif。
    并列 if 和嵌套都是特例，不是默认选择。

────────────────────────────────────────────────────────
【一个实用技巧：用 and 代替一层嵌套】
────────────────────────────────────────────────────────

    嵌套：
        if 年龄 >= 18:
            if 有身份证:
                print("可以办理")

    合并：
        if 年龄 >= 18 and 有身份证:
            print("可以办理")

    什么时候能合并？
        两个条件都只是「判断」，不涉及计算，不会出错 → 可以合并
        后面那个可能崩（比如除法、索引）→ 不能合并，必须嵌套或短路的 and

    注意 and 本身就是短路的：
        if 年龄 >= 18 and 有身份证:
    左边假就不会算右边，所以即使右边会崩也没事。
    这跟嵌套效果一样，只是少一层缩进。

    所以：
        if A and B:        ≈  if A: if B:
    只要 B 不会在 A 为假时产生副作用，两者等价。
"""

