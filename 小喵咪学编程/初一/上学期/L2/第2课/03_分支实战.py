r"""
════════════════════════════════════════════════════════
  L2 · 第 2 课 · 用法 3        多分支实战
════════════════════════════════════════════════════════

这一节不教新语法，把 if / elif / else 用在几种真实场景里。

────────────────────────────────────────────────────────
【场景一：BMI 分类】
────────────────────────────────────────────────────────

    BMI = 体重 / 身高²

    分类标准（中国标准）：
        < 18.5        偏瘦
        18.5 - 23.9   正常
        24.0 - 27.9   偏胖
        >= 28.0       肥胖

    注意这里有个陷阱：区间是「左闭右开」还是「左闭右闭」？
    18.5 到底算偏瘦还是正常？

    写成「从大到小 + 单边判断」就不用纠结边界：

        if bmi >= 28:
            "肥胖"
        elif bmi >= 24:
            "偏胖"
        elif bmi >= 18.5:
            "正常"
        else:
            "偏瘦"

    每个条件只是下限，上限由上一个条件兜住了。
    bmi = 23.9 时，>= 28 不成立，>= 24 不成立，>= 18.5 成立 → 正常 ✓

────────────────────────────────────────────────────────
【场景二：运费分档】
────────────────────────────────────────────────────────

    重量 <= 1kg      8 元
    1 < 重量 <= 3    8 + (重量-1) * 2
    3 < 重量 <= 10   12 + (重量-3) * 1.5
    重量 > 10        按 10kg 算，超出部分每 kg 加 3

    这种「分档 + 每档算法不同」的需求，elif 是最直接的写法。

    关键：每个分支里不只要给「结果」，可能还要算。
    所以分支里可以有多行代码。

────────────────────────────────────────────────────────
【场景三：两个条件组合分类】
────────────────────────────────────────────────────────

    会员等级 × 消费金额，给出不同折扣。

        普通会员：消费 >= 500 打 9 折，否则不打折
        白银会员：消费 >= 300 打 85 折，否则 95 折
        黄金会员：一律 8 折

    这种情况要判断两个维度，有三种写法：

    写法一：嵌套
        if 等级 == "黄金":
            折扣 = 0.8
        else:
            if 等级 == "白银":
                if 消费 >= 300:
                    折扣 = 0.85
                else:
                    折扣 = 0.95
            else:
                ...

        层级深，但每个分支只看自己关心的条件。

    写法二：全部拉平成 elif
        if 等级 == "黄金":
            折扣 = 0.8
        elif 等级 == "白银" and 消费 >= 300:
            折扣 = 0.85
        elif 等级 == "白银":
            折扣 = 0.95
        elif 消费 >= 500:
            折扣 = 0.9
        else:
            折扣 = 1.0

        一层到底，但条件变长了，而且要小心顺序。

    写法三：先算基础折扣，再调整
        分两步，每步一个 if/elif。

    三种都行。选哪个看「哪个读起来最像业务规则」。
    业务规则是分层的，就写嵌套；是并列的条条框框，就写 elif。

────────────────────────────────────────────────────────
【实战里的一个习惯：别在分支里 print】
────────────────────────────────────────────────────────

    差：

        if 分数 >= 90:
            print("A")
        elif 分数 >= 80:
            print("B")

    好：

        if 分数 >= 90:
            等级 = "A"
        elif 分数 >= 80:
            等级 = "B"

        print("等级：", 等级)

    为什么？

    因为分支只负责「算出一个值」，
    输出格式只写一次，改的时候只改一处。

    而且以后要把结果存文件、发给别人，
    算和输出分开的代码，改起来简单得多。

    这条习惯从现在开始养成，能省很多返工。
"""

