r"""
════════════════════════════════════════════════════════
  L2 · 第 2 课 · 用法 2        分支的顺序
════════════════════════════════════════════════════════

这一节把「顺序为什么重要」讲完 —— elif 一命中就停，所以顺序会改变结果。

────────────────────────────────────────────────────────
【先记住一句话】
────────────────────────────────────────────────────────

    elif 是「从上往下试，第一个成立的说了算」。

    所以：**谁排前面，谁就有优先权。**

────────────────────────────────────────────────────────
【用 >= 判断：必须从大到小】
────────────────────────────────────────────────────────

    想给分数分档，条件是 分数 >= 90 / >= 80 / >= 70 / >= 60。

    正确的顺序：

        if 分数 >= 90:
            "A"
        elif 分数 >= 80:
            "B"
        elif 分数 >= 70:
            "C"
        elif 分数 >= 60:
            "D"

    错误的顺序（从小到大）：

        if 分数 >= 60:      ← 85 分在这里就命中了
            "D"
        elif 分数 >= 70:
            "C"
        ...

    85 分先满足 >= 60，直接判成 D，后面三个永远轮不到。

    原因：
        ">= 60" 这个条件**包含了** ">= 90" 的情况。
        宽松的条件如果排在前面，会抢先命中，把严格的条件全部屏蔽掉。

    规律：
        用 >=  →  数值从大到小排
        用 <=  →  数值从小到大排

    因为「先排除最苛刻的情况，剩下的自然就是宽松的」。

────────────────────────────────────────────────────────
【用区间判断：也一样】
────────────────────────────────────────────────────────

    另一种写法是用区间：

        if 90 <= 分数 <= 100:
            "A"
        elif 80 <= 分数 < 90:
            "B"

    这种写法每个区间是互斥的（不重叠），所以**顺序无所谓**。

    但注意：这样写每个条件都变长了，而且要考虑边界。
    90 到底算 A 还是 B？写成 <= 还是 < ？

    所以虽然顺序自由，但**容易写错边界**。
    相比之下，「从大到小 + 单边 >=」更省心：

        if 分数 >= 90: ...
        elif 分数 >= 80: ...

    因为每个条件只是「下限」，上限由前一个条件隐式保证了。

────────────────────────────────────────────────────────
【互斥条件：顺序真的无所谓】
────────────────────────────────────────────────────────

    如果几个条件彼此不重叠，顺序就不影响结果：

        if 月份 in (3,4,5):
            "春"
        elif 月份 in (6,7,8):
            "夏"

    7 月不可能同时满足「在 3,4,5 里」，所以谁先谁后都一样。

    判断方法：
        问自己：**这两个条件可能同时成立吗？**
            可能 → 顺序重要，严格的放前面
            不可能 → 顺序随意

────────────────────────────────────────────────────────
【一个隐蔽的顺序坑：把「兜底」写成 elif】
────────────────────────────────────────────────────────

    差：

        if 分数 >= 90:
            "A"
        elif 分数 >= 80:
            "B"
        elif True:              ← 永远成立，等于兜底
            "其他"

    能用，但读代码的人要想一下「这个 True 是什么意思」。

    好：

        if 分数 >= 90:
            "A"
        elif 分数 >= 80:
            "B"
        else:
            "其他"

    else 的语义是「上面全不成立」，天生就是兜底。
    用 elif True 是绕远路。

────────────────────────────────────────────────────────
【如果顺序写反了，怎么发现】
────────────────────────────────────────────────────────

    这类 bug 不会报错，只会给错结果。所以只能靠测试。

    做法：
        拿一组**边界值**挨个试：
            59、60、61
            69、70、71
            79、80、81
            89、90、91

        每个边界上下各试一个，就能看出分档有没有错位。

    这就是「边界测试」，写任何分档逻辑都要做一遍。
"""

