r"""
════════════════════════════════════════════════════════
  L2 · 第 3 课 · 用法 3        while 实战
════════════════════════════════════════════════════════

这一节不教新语法，用 while 解三种经典题 —— 拆数字、判素数、求公约数。

────────────────────────────────────────────────────────
【工具：怎么把数字一位一位拆出来】
────────────────────────────────────────────────────────

    两个运算符就能拆：

        n % 10      拿到最后一位
        n // 10     去掉最后一位

    例：n = 58374

        58374 % 10  = 4       最后一位
        58374 // 10 = 5837    去掉最后一位

        循环下去：
            5837 % 10 = 7
            5837 // 10 = 583
            ...

    一直到最后：
        n 变成 0，循环结束。

    这个「% 10 取位，// 10 去掉」的套路，
    是所有「处理整数每一位」的题目必用的。

────────────────────────────────────────────────────────
【经典题一：反转数字】
────────────────────────────────────────────────────────

    58374 → 47385

    思路：
        每次取出最后一位，接到结果后面。

        结果 = 结果 * 10 + 位

    为什么乘 10？
        假设结果现在是 47，来个新位 3，
        47 * 10 = 470，加 3 得 473 —— 新位就接到末尾了。

    这是「数字拼接」的标准写法，和字符串拼接一个道理，
    只不过这里用乘 10 代替了「往后加」。

────────────────────────────────────────────────────────
【经典题二：判断素数】
────────────────────────────────────────────────────────

    素数：除了 1 和它本身，不能被任何数整除的、大于 1 的整数。

    判断方法：
        拿 2 到 n-1 挨个试除，有一个能整除就不是素数。

        除数 = 2
        是素数 = True
        while 除数 < n:
            if n % 除数 == 0:
                是素数 = False
                退出循环
            除数 += 1

    优化（重要）：
        不用试到 n-1，试到 √n 就够了。

        理由：如果 n = a × b，那么 a 和 b 里至少有一个 <= √n。
        所以只要试到 √n，还没找到因子，就一定是素数。

        例：n = 100，√100 = 10。
        试 2 就发现能整除，立刻退出。
        n = 97，√97 ≈ 9.8，试 2 到 9 都不整除，就是素数。

        不优化的话，判断 1000003 要循环一百万次；
        优化后只要一千次。

    怎么在代码里写「试到 √n」？
        除数 * 除数 <= n

        这样不用导入 math 模块，也不用算平方根。

────────────────────────────────────────────────────────
【经典题三：最大公约数（欧几里得算法）】
────────────────────────────────────────────────────────

    求 a 和 b 的最大公约数，两千年前的方法：

        只要 b 不为 0：
            临时 = b
            b = a % b
            a = 临时
        结果就是 a

    例：求 48 和 18 的最大公约数

        a=48, b=18
        18 不为 0 → 临时=18, b=48%18=12, a=18
        a=18, b=12
        12 不为 0 → 临时=12, b=18%12=6, a=12
        a=12, b=6
        6 不为 0 → 临时=6, b=12%6=0, a=6
        a=6, b=0
        b 是 0，结束，结果 a=6

    验证：48 和 18 的最大公约数确实是 6（48=6×8，18=6×3）。

    这个算法的漂亮之处：
        不管 a、b 多大，几步就收敛。因为余数每次至少减半。

────────────────────────────────────────────────────────
【这三个题为什么值得做】
────────────────────────────────────────────────────────

    不是因为考试会考，而是因为它们代表了三种思维：

        反转数字    「把一个东西拆开，按新顺序拼回去」
        素数判断    「穷举 + 提前退出」
        最大公约数  「把一个问题的规模不断缩小」

    这三种思维换到别的问题上也一样用。
"""

