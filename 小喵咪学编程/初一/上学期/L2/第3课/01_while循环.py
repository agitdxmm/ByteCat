r"""
════════════════════════════════════════════════════════
  L2 · 第 3 课 · 用法 1        while 循环
════════════════════════════════════════════════════════

这一节把「重复做同一件事」讲完 —— 让程序跑很多遍，而不是只跑一遍。

────────────────────────────────────────────────────────
【先看形状】
────────────────────────────────────────────────────────

    while 条件:
        重复做的事

    和 if 长得几乎一样，区别只有一点：

        if      条件成立，**做一次**，然后往下走
        while   条件成立，**做完回到开头再判断**，一直重复到不成立

    if 是一次性检查，while 是反复检查。

────────────────────────────────────────────────────────
【最简单的例子】
────────────────────────────────────────────────────────

    i = 1
    while i <= 3:
        print(i)
        i = i + 1

    执行过程：

        i = 1
        判断 1 <= 3  →  真，进循环
            打印 1
            i 变成 2
        回到 while 那行，判断 2 <= 3  →  真
            打印 2
            i 变成 3
        判断 3 <= 3  →  真
            打印 3
            i 变成 4
        判断 4 <= 3  →  假，退出循环

    输出：1 2 3

────────────────────────────────────────────────────────
【循环必须能结束】
────────────────────────────────────────────────────────

    如果忘了 i = i + 1：

        i = 1
        while i <= 3:
            print(i)

        → 1 1 1 1 1 1 ... 永远不停

    这叫「死循环」。屏幕上数字疯狂滚动，只能用 Ctrl+C 强制停止。

    每个 while 都必须回答一个问题：
        **「这个条件，什么时候会变成假？」**

    如果答不上来，就是死循环。

────────────────────────────────────────────────────────
【死循环不一定是 bug】
────────────────────────────────────────────────────────

    有些程序故意死循环，比如游戏主循环：

        while True:
            # 处理输入、更新画面、判断退出
            ...

    用 True 当条件，永远成立。
    靠内部的 break 跳出来（第 5 课讲）。

    在你还没学 break 之前，别写 while True。

────────────────────────────────────────────────────────
【三个要素】
────────────────────────────────────────────────────────

    一个正确的 while 循环，一定包含三样东西：

        1. 初始值      i = 1
        2. 条件        while i <= 3:
        3. 变化        i = i + 1

    少任何一个都会出问题：
        少初始值    → NameError
        少条件      → 语法错误
        少变化      → 死循环

────────────────────────────────────────────────────────
【i = i + 1 的简写】
────────────────────────────────────────────────────────

    Python 有简写：

        i += 1      等价于  i = i + 1
        i -= 1      等价于  i = i - 1
        i *= 2      等价于  i = i * 2
        i /= 2      等价于  i = i / 2

    这叫「增强赋值」。省事，而且写起来更清楚（一看就知道是「加到自己身上」）。

    i++ 这种写法在 Python 里**不存在**。
    那是 C、Java、JavaScript 的写法，Python 没有。

────────────────────────────────────────────────────────
【while 和 if 的根本区别】
────────────────────────────────────────────────────────

    if 执行完就往下走，不再回头看。
    while 执行完会**回到开头**，重新判断条件。

    这个「回到开头」是关键。

    如果条件是变量，而变量在循环里被改了，
    那么每次判断的结果都可能不同 —— 这就产生了「循环」。

    如果条件是个常量：
        while True:      永远真
        while False:     一次都不执行
        while 1:         永远真（1 是真值）
"""

