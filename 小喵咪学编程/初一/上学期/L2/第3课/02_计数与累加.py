r"""
════════════════════════════════════════════════════════
  L2 · 第 3 课 · 用法 2        计数与累加
════════════════════════════════════════════════════════

这一节把 while 最常见的几种用法讲完 —— 数数、攒东西、挑最大最小。

────────────────────────────────────────────────────────
【模式一：计数器】
────────────────────────────────────────────────────────

    目的：数「发生了多少次」。

    形状：

        次数 = 0                 ← 初始为 0
        while 条件:
            if 某个情况:
                次数 += 1        ← 满足就加一
            ...

    「次数」这个变量只负责记数，不参与别的计算。

    例：统计 1 到 100 里有多少个偶数

        次数 = 0
        i = 1
        while i <= 100:
            if i % 2 == 0:
                次数 += 1
            i += 1

        print(次数)          →  50

────────────────────────────────────────────────────────
【模式二：累加器】
────────────────────────────────────────────────────────

    目的：把一堆数加起来。

    形状：

        总和 = 0                 ← 初始为 0
        while 条件:
            总和 += 某个值
            ...

    例：算 1 到 100 的和

        总和 = 0
        i = 1
        while i <= 100:
            总和 += i
            i += 1

    换成累乘，初始值就得是 1：

        积 = 1
        while ...:
            积 *= i

    为什么初始值不同？
        加法：0 + x = x，所以从 0 开始
        乘法：1 * x = x，所以从 1 开始

    这叫「单位元」—— 加法的单位元是 0，乘法的是 1。

────────────────────────────────────────────────────────
【模式三：找最大 / 最小】
────────────────────────────────────────────────────────

    目的：在一串数里挑出最大的那个。

    形状：

        最大 = 第一个值           ← 注意！不是 0
        while 还有数:
            if 当前 > 最大:
                最大 = 当前

    为什么初始值要是第一个值，不是 0？

        如果全是负数，比如 -5、-3、-8，
        初始设 0 的话，0 比它们都大，最后结果会变成 0 —— 错的。

    这是新手常犯的错。正确做法：
        用第一个值当初始值

────────────────────────────────────────────────────────
【三种模式的区别】
────────────────────────────────────────────────────────

    计数器      初始 0，遇到就 +1         记「几次」
    累加器      初始 0（或 1），每次加/乘  记「总共多少」
    最值        初始第一个值，比大小替换  记「最大 / 最小」

    这三个模式会跟着你写一辈子程序。
    几乎所有「统计」需求，都是这三种的组合。

────────────────────────────────────────────────────────
【一个常见错误：把赋值写成加】
────────────────────────────────────────────────────────

    错：

        i = 1
        次数 = 0
        while i <= 10:
            次数 = i            ← 这是「赋值」，不是「累加」
            i += 1
        print(次数)              →  10

    结果碰巧是 10（因为循环 10 次），但含义完全不同 ——
    它记的是「最后一次的 i」，不是「循环了几次」。

    改成 `次数 += 1` 才是真正的计数。

    这个差别在什么时候暴露？
        如果循环体里有 continue 跳过某些次，
        `次数 += 1` 只在没被跳过时执行，
        而「最后一次的 i」永远是最后那个 i。
"""

