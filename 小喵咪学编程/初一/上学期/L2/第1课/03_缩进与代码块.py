r"""
════════════════════════════════════════════════════════
  L2 · 第 1 课 · 用法 3        缩进与代码块
════════════════════════════════════════════════════════

这一节把「缩进」讲完 —— 它是语法，不是排版。错了程序直接不跑。

────────────────────────────────────────────────────────
【核心区别：别的语言用括号，Python 用缩进】
────────────────────────────────────────────────────────

    C / Java / JavaScript：

        if (x > 0) {
            print("正数");
            print("很大");
        }
        print("结束");

        大括号 { } 划范围，缩进随便写。

    Python：

        if x > 0:
            print("正数")
            print("很大")
        print("结束")

        冒号开始，缩进划范围。**缩进必须存在，而且必须一致。**

────────────────────────────────────────────────────────
【缩进多少？4 个空格】
────────────────────────────────────────────────────────

    Python 官方规范（PEP 8）：4 个空格。

    1 个、2 个、3 个、8 个，语法上都合法，只要同一个块里一致。
    但所有人都用 4 个，你不跟着用，代码发给别人会被嫌弃。

    ── 一个块里缩进不一致会怎样？ ──

        if x > 0:
            print("A")
              print("B")

        → IndentationError: unexpected indent

    「unexpected indent」= 这里不该缩进，但你缩了。

────────────────────────────────────────────────────────
【Tab 和空格：混用是灾难】
────────────────────────────────────────────────────────

    Tab 看起来像 4 个空格（或者 8 个），但它是一个字符 \t。
    空格是 4 个字符。

    Python 3 **禁止**在同一个文件里混用 Tab 和空格：

        → TabError: inconsistent use of tabs and spaces in indentation

    更坑的情况：两个不同文件，一个用 Tab 一个用空格，
    语法上都对，但你把代码复制粘贴过来，就炸了。

    ── 怎么办 ──

    编辑器里打开「显示空白字符」，或者设置「按 Tab 插入 4 个空格」。
    PyCharm、VS Code 默认就是这样，一般不用管。
    但如果你从别的地方复制代码，一定要检查。

────────────────────────────────────────────────────────
【块的范围：往回缩就结束】
────────────────────────────────────────────────────────

    if x > 0:
        print("A")
        print("B")
    print("C")

    A、B 缩进了 → 属于 if 的块
    C 没缩进     → 不属于 if，无论条件真假都会执行

    改一下：

    if x > 0:
        print("A")
    print("B")
    print("C")

    现在只有 A 属于 if。

    **缩进结束 = 块结束**。没有别的标记。

────────────────────────────────────────────────────────
【缩进错误的三种典型】
────────────────────────────────────────────────────────

    1. 该缩没缩
        if x > 0:
        print("A")
        → IndentationError: expected an indented block

    2. 不该缩缩了
        print("A")
            print("B")
        → IndentationError: unexpected indent

    3. 该缩但缩了不同的量
        if x > 0:
            print("A")
              print("B")
        → IndentationError: unindent does not match any outer indentation level

    三种都是 IndentationError，但后面的说明不一样。
    看最后一个词就知道是哪种。

────────────────────────────────────────────────────────
【为什么 Python 要这么设计】
────────────────────────────────────────────────────────

    因为「代码的样子」和「代码的行为」一致了。

    别的语言里，你看到缩进整齐，但它可能和实际逻辑不符：

        if (x > 0)
            print("A");
            print("B");        ← 缩进像在里面，实际在外面

    Python 里不可能出现这种错位：
        缩进就是逻辑，逻辑就是缩进。

    代价是：**改代码时你的缩进必须跟着改**。
    复制一段代码到别的地方，缩进不对就报错。

────────────────────────────────────────────────────────
【一个必须知道的细则：同一层要对齐】
────────────────────────────────────────────────────────

    if x > 0:
        print("A")       ← 缩进 4
    else:
        print("B")       ← 缩进 4，和上面那层一致

    if 和 else 必须对齐（同一层）。
    如果 else 前面多一个空格：

        if x > 0:
            print("A")
         else:                ← 多了一个空格
            print("B")

        → IndentationError

    这种错肉眼极难发现，尤其是只有一个空格的时候。
    所以：**永远别手动微调缩进，用编辑器自动对齐**。
"""

