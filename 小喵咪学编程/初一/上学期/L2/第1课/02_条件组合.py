r"""
════════════════════════════════════════════════════════
  L2 · 第 1 课 · 用法 2        条件组合 and / or / not
════════════════════════════════════════════════════════

这一节把「多个条件怎么连起来」讲完 —— 三个逻辑运算符和它们的脾气。

────────────────────────────────────────────────────────
【and：都真才真】
────────────────────────────────────────────────────────

    真 and 真   →  真
    真 and 假   →  假
    假 and 真   →  假
    假 and 假   →  假

    一句话：**有一个假就假**。

    例：
        if 分数 >= 60 and 出勤 >= 80:
            print("可以结业")

        两个条件都成立才打印。

────────────────────────────────────────────────────────
【or：一个真就真】
────────────────────────────────────────────────────────

    真 or 真    →  真
    真 or 假    →  真
    假 or 真    →  真
    假 or 假    →  假

    一句话：**有一个真就真**。

    例：
        if 天气 == "晴" or 带伞:
            print("可以出门")

        只要一个条件满足就出门。

────────────────────────────────────────────────────────
【not：取反】
────────────────────────────────────────────────────────

    not 真      →  假
    not 假      →  真

    例：
        if not 已完成:
            print("继续做")

        if not 名字:           ← 等价于 if 名字 == ""
            print("你还没输入名字")

    用 not 判断「空」特别方便：
        not 空字符串  →  True
        not 空列表    →  True
        not 0         →  True

────────────────────────────────────────────────────────
【优先级：not > and > or】
────────────────────────────────────────────────────────

    not 最高，and 次之，or 最低。

    所以：

        A or B and C      等价于   A or (B and C)
        not A and B       等价于   (not A) and B

    记不住没关系，**加括号**就行。
    括号不花钱，猜错要命。

        想表达「A 或（B 且 C）」 → 写 A or (B and C)
        想表达「（A 或 B）且 C」 → 写 (A or B) and C

    这两个差别巨大，加括号能救命。

────────────────────────────────────────────────────────
【短路求值：后面的可能不执行】
────────────────────────────────────────────────────────

    这是 and / or 最容易被忽略的行为。

    and：左边是假，右边**根本不看**
        假 and 什么   →  假       右边不执行

    or：左边是真，右边**根本不看**
        真 or 什么    →  真       右边不执行

    为什么重要？因为它能做「保护」：

        if 除数 != 0 and 100 / 除数 > 10:
            ...

        如果 除数 是 0，第一个条件就是假，
        第二个条件（100/0）**不会执行**，所以不会崩。

        反过来写：
        if 100 / 除数 > 10 and 除数 != 0:
            ...
        除数 是 0 时，先算 100/0，直接 ZeroDivisionError。

    顺序很重要，但只在「右边会出事」的时候才重要。

────────────────────────────────────────────────────────
【返回值不是 True/False，是「最后算的那个值」】
────────────────────────────────────────────────────────

    and / or 的行为比想象的复杂一点：

        5 and 3          →  3        两个都真，返回最后一个
        0 and 3          →  0        左边假，直接返回左边
        5 or 3           →  5        左边真，直接返回左边
        0 or 3           →  3        左边假，返回右边

    所以它们返回的**不一定是 bool**。

    在 if 里用没问题（任何值都能判真假），
    但如果你想把它赋值：
        x = 名字 or "无名氏"      ← 名字为空时，x 变成 "无名氏"

    这叫「短路取值」，是个常用技巧，以后会经常见到。

────────────────────────────────────────────────────────
【三个要点总结】
────────────────────────────────────────────────────────

    1. and 有一个假就假，or 有一个真就真
    2. 优先级 not > and > or，不确定就加括号
    3. 短路：and 左边假、or 左边真，右边不执行
"""

