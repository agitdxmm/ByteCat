r"""
════════════════════════════════════════════════════════
  L2 · 第 1 课 · 用法 4        嵌套分支
════════════════════════════════════════════════════════

这一节把「if 里面再放 if」讲完 —— 什么时候该套、套多深会出事。

────────────────────────────────────────────────────────
【什么叫嵌套】
────────────────────────────────────────────────────────

    if 外层条件:
        ...
        if 内层条件:
            ...
        ...

    内层的 if 必须比外层再往右缩一层（一般再加 4 个空格）。

    执行逻辑：
        外层不成立 → 内层整个不执行（连条件都不看）
        外层成立   → 才进到里面，再看内层条件

────────────────────────────────────────────────────────
【一个典型例子】
────────────────────────────────────────────────────────

    分数 = 85

    if 分数 >= 60:
        print("及格")
        if 分数 >= 90:
            print("而且优秀")
        else:
            print("但不算优秀")
    else:
        print("不及格")

    流程：
        1. 分数 >= 60 ？ → 是
        2. 进入外层，打印「及格」
        3. 分数 >= 90 ？ → 否
        4. 走内层 else，打印「但不算优秀」

    注意：内层的 else 属于内层的 if，不是外层的。

────────────────────────────────────────────────────────
【嵌套判断属于谁：看缩进对齐】
────────────────────────────────────────────────────────

    if A:
        if B:
            ...
        else:          ← 这个 else 属于 if B
            ...
    else:              ← 这个 else 属于 if A
        ...

    else 永远配「和它同一缩进层、最近的那个 if」。
    所以对齐非常关键，错一格就配错了。

────────────────────────────────────────────────────────
【嵌套超过三层就该重构】
────────────────────────────────────────────────────────

    三层嵌套，缩进就到 12 个空格。
    四层 16 个，五层 20 个 —— 屏幕左边全是空白，
    代码被挤到右边，一行装不下几个字。

    更麻烦的是：**你要同时记住五个条件才能读懂一行代码**。
    这种代码叫「箭头型代码」，是公认的坏味道。

    ── 怎么减少嵌套 ──

    方法一：把「不满足就退出」的条件提前

        差：
            if 用户存在:
                if 密码正确:
                    if 未锁定:
                        print("登录成功")

        好（用 not 提前拦）：
            if not 用户存在:
                print("用户不存在")
            else:
                if 密码正确:
                    if 未锁定:
                        print("登录成功")

        但这样还是嵌套，只是把「失败」提前说了。

    方法二：用 and 合并条件（如果逻辑允许）

        if 用户存在 and 密码正确 and 未锁定:
            print("登录成功")

        一层解决，但缺点是出错时不知道是哪一步失败。

    方法三：用 elif 拉平（下一课）

        if not 用户存在:
            print("用户不存在")
        elif 密码错误:
            print("密码错误")
        elif 已锁定:
            print("账号锁定")
        else:
            print("登录成功")

        这是最好的，下一节讲。

────────────────────────────────────────────────────────
【什么时候嵌套是合理的】
────────────────────────────────────────────────────────

    当「内层条件只有在外层成立时才有意义」的时候。

    例：
        if 列表:
            if 列表[0] > 0:
                ...

        空列表时，列表[0] 会 IndexError。
        所以必须先确认非空，再访问第一个元素。
        这种嵌套是必要的，因为内层条件依赖外层的前提。

    反例：
        if 年龄 >= 18:
            if 年龄 < 60:
                ...

        这两个条件互不依赖，完全可以写成：
        if 18 <= 年龄 < 60:
            ...

    判断标准：
        内层条件**离了外层会不会出错**？
            会 → 该嵌套
            不会 → 想办法合并
"""

