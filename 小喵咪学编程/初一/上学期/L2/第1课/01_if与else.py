r"""
════════════════════════════════════════════════════════
  L2 · 第 1 课 · 用法 1        if 与 else
════════════════════════════════════════════════════════

这一节把「分支」讲完 —— 让程序遇到不同情况走不同的路。

────────────────────────────────────────────────────────
【先看形状】
────────────────────────────────────────────────────────

    if 条件:
        条件为真时做的事
    else:
        条件为假时做的事

    三件东西必须有：
        1. if 后面跟一个「能判断真假」的条件
        2. 行末的冒号 :
        3. 下面那一行要缩进

    少任何一个都报错。

────────────────────────────────────────────────────────
【冒号是什么】
────────────────────────────────────────────────────────

    冒号的意思是「下面开始是一个块」。

    Python 没有大括号 {}，所以它用「冒号 + 缩进」来划范围。

        其他语言：
            if (x > 0) {
                print("正数");
            }

        Python：
            if x > 0:
                print("正数")

    冒号说「块开始了」，缩进说「块的范围到这里」。

────────────────────────────────────────────────────────
【缩进不是好看，是语法】
────────────────────────────────────────────────────────

    下面这段会直接报错：

        if x > 0:
        print("正数")

        → IndentationError: expected an indented block

    「expected an indented block」= 这里应该有一个缩进的块。

    所以：
        if 下面那一行**必须**比 if 往右缩。
        缩多少？Python 推荐 4 个空格。

    不缩进 = 语法错误，程序根本不跑。
    这和其他语言不一样 —— C、Java 里缩进只是给人看的。

────────────────────────────────────────────────────────
【条件的真假】
────────────────────────────────────────────────────────

    if 后面跟的东西，Python 会转成 True 或 False：

        if True:            永远执行
        if False:           永远不执行
        if 5 > 3:           判断后为 True，执行
        if 分数 >= 60:      看分数
        if 名字:            非空字符串为真，空字符串为假
        if 0:               0 为假
        if []:              空列表为假

    完整的「什么东西算假」：
        假：False、None、0、0.0、""、[]、{}、()
        真：其他一切

    这条以后会经常用到，因为它能省掉一些判断。

────────────────────────────────────────────────────────
【else 是可选的】
────────────────────────────────────────────────────────

    只有 if 没有 else，完全合法：

        if 分数 >= 60:
            print("及格")

    及格就打印，不及格就什么都不做，程序继续往下走。

    else 的意思是「如果前面所有条件都不成立」：
        它不是「条件为假」这么简单，
        在后面学 elif 之后，它是「上面全部失败」。

────────────────────────────────────────────────────────
【执行流程：一次只走一条路】
────────────────────────────────────────────────────────

    分数 = 75

    if 分数 >= 60:
        print("及格")
    else:
        print("不及格")

    执行过程：
        1. 算 分数 >= 60   →  True
        2. True 就走 if 那块
        3. **跳过 else 那块**
        4. 继续执行下面的代码

    两条路只走一条，不可能都走、也不可能都不走。

────────────────────────────────────────────────────────
【if 和 = 的区别】
────────────────────────────────────────────────────────

    if x = 5:        ← SyntaxError
    if x == 5:       ← 正确

    条件是「问」，赋值是「装」。
    问用 ==，装用 =。

    Python 在这里比 C 严格：C 里写 if (x = 5) 是合法的
    （赋值表达式的值非零就算真），Python 直接拒绝。
    这是好事，省了一类经典 bug。
"""

