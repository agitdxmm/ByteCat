r"""
════════════════════════════════════════════════════════
  L2 · 第 5 课 · 用法 2        continue
════════════════════════════════════════════════════════

break 是「整个循环不要了」，continue 是「这一轮不要了，下一轮继续」。

────────────────────────────────────────────────────────
【continue 的作用：跳过本轮剩下的代码】
────────────────────────────────────────────────────────

    for i in range(1, 6):
        if i == 3:
            continue
        print(i)

    输出：1 2 4 5

    i = 3 那一轮，continue 一跳，print 就没执行。
    但循环没结束，i = 4 照常继续。

    对比 break：

        break      → 1 2
        continue   → 1 2 4 5

────────────────────────────────────────────────────────
【continue 之后，本轮的代码全部作废】
────────────────────────────────────────────────────────

    for i in range(1, 4):
        print("A", i)
        if i == 2:
            continue
        print("B", i)

    i=1: A1 B1
    i=2: A2         ← continue，B2 不打印
    i=3: A3 B3

    输出：
        A 1
        B 1
        A 2
        A 3
        B 3

    continue 只影响「这一轮后面还没执行的」，已经执行过的收不回来。

────────────────────────────────────────────────────────
【continue 最容易翻车的地方：while 里】
────────────────────────────────────────────────────────

    看这段，看着没问题：

        i = 1
        while i <= 5:
            if i == 3:
                continue        ← 危险！
            print(i)
            i += 1

    它是个**死循环**。

    为什么：
        i = 1 → 打印 1，i 变 2
        i = 2 → 打印 2，i 变 3
        i = 3 → continue 直接跳回条件判断
                但 i += 1 在 continue 后面，**永远执行不到**
                i 卡在 3，条件 3 <= 5 永远成立
                → 死循环

    正确写法：**把 i += 1 挪到 continue 前面**

        i = 1
        while i <= 5:
            if i == 3:
                i += 1          ← 先更新，再跳
                continue
            print(i)
            i += 1

    跑出来还是 1 2 4 5。

    更稳的写法是把更新放循环最开头：

        i = 0
        while i < 5:
            i += 1              ← 一进来就更新，谁也别想跳过
            if i == 3:
                continue
            print(i)

    ── 规律 ──
        for 循环用 continue 安全（下一轮 Python 自己会推进）。
        while 循环用 continue 必须先保证「循环变量会变」。

────────────────────────────────────────────────────────
【continue 的真正价值：减少缩进】
────────────────────────────────────────────────────────

    不用 continue，代码会越缩越深：

        for i in range(1, 11):
            if i % 2 == 0:
                if i % 3 == 0:
                    if i > 5:
                        print(i)

    四层缩进，读起来要一层层剥。

    用 continue 把「不满足」的提前踢走：

        for i in range(1, 11):
            if i % 2 != 0:
                continue        ← 奇数？不要，下一个
            if i % 3 != 0:
                continue        ← 不能被 3 整除？不要，下一个
            if i <= 5:
                continue        ← 太小？不要，下一个
            print(i)

    全部平铺，一眼看到最后要干的事。

    这个写法叫**卫语句**（guard clause）。
    思路是：先排除所有不该继续的情况，剩下的就是该处理的。

────────────────────────────────────────────────────────
【continue 和 break 的选择】
────────────────────────────────────────────────────────

    问自己一句话：

        后面还有没有「有用的轮次」？

        有  → continue（跳过这一轮）
        没有 → break（整个循环结束）

    ── 例子 ──

        在一堆数里找 7：
            找到了 → 后面没有意义了 → break

        统计 1 到 100 里的偶数：
            奇数那轮没事干，但后面还有偶数 → continue

    ── 常见的错用 ──

        想找第一个满足条件的数，却用了 continue：

            for i in range(1, 100):
                if i % 7 == 0:
                    print("找到了", i)
                    continue        ← 错！它没停，会一直找下去

        这是把「跳过不满足的」和「找到了就停」搞混了。

────────────────────────────────────────────────────────
【一个容易忽略的细节】
────────────────────────────────────────────────────────

    continue 在循环的**最后一行**，等于没写。

        for i in range(5):
            print(i)
            continue        ← 后面本来就没代码了，跳不跳都一样

    写这种代码说明你可能想表达别的意思，检查一下。

────────────────────────────────────────────────────────
【continue 在嵌套里的行为】
────────────────────────────────────────────────────────

    和 break 一样，continue 也只作用**最近的一层**循环。

        for i in range(3):
            for j in range(3):
                if j == 1:
                    continue
                print(i, j)

    输出：
        0 0
        0 2
        1 0
        1 2
        2 0
        2 2

    j = 1 的三次都被跳过，但 i 一直正常推进。
"""

