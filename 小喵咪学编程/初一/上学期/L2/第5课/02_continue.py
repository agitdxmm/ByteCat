for i in range(1, 4):
    print(f"  A{i}", end="")
    if i == 2:
        continue
    print(f" B{i}")

print("\n③ while 里 continue，更新要放前面")
i = 1
while i <= 5:
    if i == 3:
        i += 1
        continue
    print(i, end=" ")
    i += 1
print()

print("\n④ 卫语句：只打印 1~20 里能被 6 整除的数")
for i in range(1, 21):
    if i % 6 != 0:
        continue
    print(f"  {i}", end="")
print()

print("\n⑤ 卫语句的好处：平铺，不套娃")
print("  找一个三位数：各位数字之和是 9，且本身是 7 的倍数")
for n in range(100, 1000):
    if n % 7 != 0:
        continue            # 不是 7 的倍数，下一个
    if n // 100 + n // 10 % 10 + n % 10 != 9:
        continue            # 各位和不是 9，下一个
    print(f"  {n}", end=" ")
print()

print("\n⑥ 嵌套里 continue 只作用内层")
for i in range(3):
    for j in range(3):
        if j == 1:
            continue
        print(f"  ({i},{j})", end="")
    print()


