r"""
════════════════════════════════════════════════════════
  L2 · 第 5 课 · 用法 1        break
════════════════════════════════════════════════════════

这一节把 break 讲完 —— 让它提前跳出循环，不等条件不成立。

────────────────────────────────────────────────────────
【break 的作用：立刻退出整个循环】
────────────────────────────────────────────────────────

    for i in range(1, 11):
        if i == 5:
            break
        print(i)

    输出：1 2 3 4

    到 i = 5 时，break 直接跳出去，
    后面的 6 到 10 再也不看了。

    循环条件写的是「到 10」，但实际只跑到 4。

────────────────────────────────────────────────────────
【break 和「条件不成立」的区别】
────────────────────────────────────────────────────────

    正常结束：
        for i in range(1, 11):
            print(i)
        → 1 到 10 全打印，循环完整跑完

    提前结束：
        for i in range(1, 11):
            if i == 5:
                break
            print(i)
        → 只打印 1 到 4，循环被中断

    区别在于：**break 之后，循环体剩下的部分也不执行了。**

        for i in range(1, 6):
            print("A", i)
            if i == 3:
                break
            print("B", i)

        i=1: A1 B1
        i=2: A2 B2
        i=3: A3      ← break 了，B3 不打印
        结束

────────────────────────────────────────────────────────
【while True + break：最常见的组合】
────────────────────────────────────────────────────────

    while True:
        做点事
        if 该停了:
            break

    这是「不知道要循环几次」的标准写法。

    例：一直问用户，直到输入 quit

        while True:
            命令 = input("输入命令（quit 退出）：")
            if 命令 == "quit":
                break
            print("你输入了：", 命令)

    while True 的条件永远成立，循环本来会无限跑。
    靠 break 跳出来。

    ── 为什么不用 while 命令 != "quit" ──

        那样也能写：

            命令 = input(...)
            while 命令 != "quit":
                print(...)
                命令 = input(...)

        但 input 要写两遍（循环前一次、循环内一次），
        而且第一次输入的处理逻辑和后面不同，容易出错。

        while True 版只写一遍 input，逻辑更直。

────────────────────────────────────────────────────────
【break 只能跳一层】
────────────────────────────────────────────────────────

    嵌套循环里：

        for i in range(3):
            for j in range(3):
                if j == 1:
                    break
                print(i, j)

    内层的 break 只跳出**内层**循环，
    外层还会继续下一轮。

    输出：
        0 0
        1 0
        2 0

    想跳出外层，得用标志变量或者 return（函数里）。

────────────────────────────────────────────────────────
【不写 break 会怎样】
────────────────────────────────────────────────────────

    很多人用「标志变量」代替 break：

        找到 = False
        for i in range(1, 11):
            if 找到:
                break
            if i == 5:
                找到 = True
                print("找到了")

    这写法很绕，而且还是在用 break。

    纯标志变量版（完全不用 break）：

        找到 = False
        for i in range(1, 11):
            if not 找到:
                if i == 5:
                    找到 = True
                    print("找到了")
                else:
                    print(i)

    能跑，但比 break 版难读得多。

    **结论：有 break 就用 break。** 它是为了让代码短，不是限制。

────────────────────────────────────────────────────────
【break 的位置很重要】
────────────────────────────────────────────────────────

    break 后面的代码永远不会执行：

        for i in range(5):
            break
            print("这行永远不执行")

    编辑器一般会提示「unreachable code」，但 Python 不报错。

    所以 break 一般放在 if 里面，或者循环的最后。

    放循环最后也有用：
        表示「这一轮做完了，检查一下要不要停」。
"""

