r"""
════════════════════════════════════════════════════════
  L1 · 第 2 课 · 用法 3        类型与 type()
════════════════════════════════════════════════════════

这一节把「类型」讲完 —— Python 里有哪些类型、怎么看、类型决定了什么。

────────────────────────────────────────────────────────
【最常用的四种类型】
────────────────────────────────────────────────────────

    整数    int         95      -3      0       1000000
    小数    float       3.14    -0.5    2.0
    文字    str         "hello" "95"    ""        "小喵咪"
    真假    bool        True    False

    还有一个特殊的：
    空      NoneType    None

────────────────────────────────────────────────────────
【怎么查类型：type()】
────────────────────────────────────────────────────────

    print(type(95))         →  <class 'int'>
    print(type(3.14))       →  <class 'float'>
    print(type("hi"))       →  <class 'str'>
    print(type(True))       →  <class 'bool'>

    <class 'int'> 这个写法不用怕，读作「这玩意的类型是 int」。
    它是 Python 告诉你答案的方式，不是错误信息。

────────────────────────────────────────────────────────
【类型决定了能做什么】
────────────────────────────────────────────────────────

    同样是加号，碰到不同类型，行为完全不同：

        1 + 1            →  2           数字相加
        "1" + "1"        →  "11"        字符串拼接
        1 + "1"          →  TypeError   不能混着加

    报错长这样：
        TypeError: unsupported operand type(s) for +: 'int' and 'str'
        读作：这个 + 号，不会处理 int 和 str 的组合

    这是新手最常撞的墙：
        input() 拿到的永远是字符串，你以为是数字，一加就炸。

────────────────────────────────────────────────────────
【类型转换：三个函数】
────────────────────────────────────────────────────────

    int("95")       →  95        字符串转整数
    int(3.9)        →  3         小数转整数，直接砍掉小数部分（不四舍五入！）
    float("3.14")   →  3.14      字符串转小数
    str(95)         →  "95"      什么东西都能转成字符串

    注意 int(3.9) 是 3，不是 4。
    要四舍五入得用 round(3.9)，结果才是 4。

────────────────────────────────────────────────────────
【转不了会怎样】
────────────────────────────────────────────────────────

    int("abc")
    → ValueError: invalid literal for int() with base 10: 'abc'

    「invalid literal」= 无效的字面量。意思是：这串字符不是一个合法数字。

    注意它和 TypeError 的区别：
        TypeError    类型不对（1 + "1"）
        ValueError   类型对，但值不对（"abc" 是字符串，但转不成数字）

────────────────────────────────────────────────────────
【bool 的隐藏规则】
────────────────────────────────────────────────────────

    在需要真假的场合，Python 会自动判断：

        假：0、0.0、""、None、[]、{}、()
        真：其他一切（包括 "0" 和 "False" 这两个字符串！）

    这条以后学 if 会用到。现在记一句：
        字符串 "False" 是真值，因为它是非空字符串。

────────────────────────────────────────────────────────
【为什么要关心类型】
────────────────────────────────────────────────────────

    因为 Python 不会提前告诉你类型错了，它只在真出事的那一刻炸。

    写    成绩 = input("输入分数：")
    你以为 成绩 是数字，能比较大小。
    实际上它是字符串。后面写 成绩 >= 60，直接 TypeError。

    这类错误在 C、Java 里编译时就拦住了，
    在 Python 里要等到运行到那一行才炸。
    所以写 Python 要更主动地想：这个变量现在是什么类型？
"""

