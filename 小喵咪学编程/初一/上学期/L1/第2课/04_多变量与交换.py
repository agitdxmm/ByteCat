m, n = 0, 1
m = n
n = m + n
print("两行写法：", m, n)
print("两行写法错了，因为第二行的 m 已经被第一行改过了")

print("\n⑤ 链式赋值")
a1 = b1 = c1 = 0
print(a1, b1, c1)

print("\n⑥ 右值可以是表达式")
