r"""
════════════════════════════════════════════════════════
  L1 · 第 2 课 · 用法 4        多变量与交换
════════════════════════════════════════════════════════

这一节把「一次处理多个变量」讲完 —— 同时赋值、交换、链式赋值、以及它们各自的坑。

────────────────────────────────────────────────────────
【同时赋值：一行定义多个】
────────────────────────────────────────────────────────

    a, b = 1, 2

    左边几个名字，右边几个值，一一对应。
    效果等于：
        a = 1
        b = 2

    但有一处关键差别，往下看。

────────────────────────────────────────────────────────
【交换：a, b = b, a】
────────────────────────────────────────────────────────

    这是 Python 最出名的一行。不用临时变量：

        a, b = 1, 2
        a, b = b, a
        print(a, b)      →  2 1

    为什么能成立？

    Python 执行这行分两步：
        第一步：先把右边整体算完，得到一个元组 (2, 1)
        第二步：再把元组拆开，依次装进 a 和 b

    所以右边那两个 b、a 用的是**交换前**的值。
    这不是「先算一个再算一个」，是「全部算完再一起装」。

────────────────────────────────────────────────────────
【这个特性可以玩出花来】
────────────────────────────────────────────────────────

    斐波那契数列（不用临时变量）：

        a, b = 0, 1
        a, b = b, a + b
        print(a, b)      →  1 1

    注意 a + b 用的是旧值。
    如果写成两行：
        a = b
        b = a + b
    就会错，因为第二行的 a 已经被改过了。

    这就是「同时赋值」和「逐行赋值」的本质区别。

────────────────────────────────────────────────────────
【链式赋值：a = b = 0】
────────────────────────────────────────────────────────

    a = b = c = 0

    三个变量都指向 0。

    但要注意：
        数字和字符串，这么写没问题。
        列表、字典这么写，三个名字会指向**同一个对象**，
        改一个，三个都变。以后学列表会撞上这个坑。

────────────────────────────────────────────────────────
【数量必须对上】
────────────────────────────────────────────────────────

    a, b = 1, 2, 3
    → ValueError: too many values to unpack (expected 2)

    a, b, c = 1, 2
    → ValueError: not enough values to unpack (expected 3, got 2)

    「unpack」= 拆包。左右数量不等就拆不动。

    一个例外：用星号可以吸收多余的（进阶内容，以后讲）。

────────────────────────────────────────────────────────
【右值可以是任何东西】
────────────────────────────────────────────────────────

    不只是字面量，任何能算出两个值的表达式都行：

        a, b = 1 + 1, 3 * 3
        print(a, b)      →  2 9

        x = 10
        a, b = x, x * 2
        print(a, b)      →  10 20

    右边先全部算完，再一起装。

────────────────────────────────────────────────────────
【变量名可以一次定义，但不建议滥用】
────────────────────────────────────────────────────────

    a, b, c, d, e = 1, 2, 3, 4, 5

    能用，但读起来要来回对照。
    一般 2-3 个是舒适区，超过 3 个就该考虑是不是该用列表了（L4 讲）。
"""

