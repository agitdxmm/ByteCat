r"""
════════════════════════════════════════════════════════
  L1 · 第 2 课 · 用法 1        变量与赋值
════════════════════════════════════════════════════════

这一节把「变量」讲完 —— 它是什么、= 是什么意思、怎么覆盖、什么时候会出问题。

────────────────────────────────────────────────────────
【变量就是一个贴了标签的盒子】
────────────────────────────────────────────────────────

    名字 = 值

    例：
        分数 = 95

    Python 做的事：
        1. 造一个 95
        2. 给它贴个标签，标签上写「分数」
        3. 以后说「分数」，就是从这个盒子里取 95

────────────────────────────────────────────────────────
【= 不是「等于」，是「赋值」】
────────────────────────────────────────────────────────

    这是初学者最大的误解来源。

    数学里     x = 5     表示「x 就是 5」
    Python 里  x = 5     表示「把 5 装进 x」

    所以下面这句在 Python 里合法，在数学里荒谬：

        x = x + 1

    读法：先把 x 现在装的东西取出来，加 1，再装回 x。
    数学上 x = x+1 无解，程序里这叫做「自增」，天天用。

    判断等不等于，用两个等号：  ==

────────────────────────────────────────────────────────
【取出来用】
────────────────────────────────────────────────────────

    分数 = 95
    print(分数)          →  95
    print("分数")        →  分数

    这就是上一课讲的：加引号是文字，不加引号是名字。

────────────────────────────────────────────────────────
【覆盖：变量只有一个值，新的会顶掉旧的】
────────────────────────────────────────────────────────

    分数 = 95
    分数 = 60
    print(分数)          →  60        ← 95 去哪了？没了

    变量不是容器，是标签。
    重新赋值 = 把标签从旧东西上撕下来，贴到新东西上。
    旧东西没人引用了，Python 会在合适的时候清理掉。

────────────────────────────────────────────────────────
【变量可以先定义类型，也可以换】
────────────────────────────────────────────────────────

    这跟 C、Java 不一样。Python 的变量没有固定类型：

        x = 100          x 现在装整数
        x = "一百"        x 现在装字符串，没问题
        x = 3.14         x 现在装小数，也没问题

    Python 允许，但不代表你应该这么写。
    同一个变量名在几行里换来换去，读代码的人会疯。

────────────────────────────────────────────────────────
【必须先赋值，才能用】
────────────────────────────────────────────────────────

    print(分数)          ← 如果上面没写过 分数 = ...
    → NameError: name '分数' is not defined

    「is not defined」= 这个名字我从来没见过。

    注意区分两种错：
        NameError     名字不存在（拼错了 / 没赋值）
        SyntaxError   语法写错了（少了括号 / 中文引号）

    NameError 说明代码结构没问题，是逻辑/拼写问题。

────────────────────────────────────────────────────────
【赋值语句的右边先算完，再装】
────────────────────────────────────────────────────────

    a = 1
    b = 2
    a = b          ← 先把 b 的值（2）取出来，再装进 a

    现在 a 是 2，b 还是 2。
    不是「a 指向 b」，是「a 拿到了 b 当时的副本」。

    这点很重要，后面学列表会翻车：
        数字字符串是「复制一份」
        列表是「共享同一个」

────────────────────────────────────────────────────────
【变量名和值，是两回事】
────────────────────────────────────────────────────────

    分数 = 95
    科目 = "数学"

    现在 print(科目, 分数) 输出：  数学 95
    但如果写 
        科目 = 分数
    那 科目 就变成 95 了，字符串「数学」被丢掉了。

    赋值不看变量原来的内容，直接覆盖。
"""

