r"""
════════════════════════════════════════════════════════
  L1 · 第 2 课 · 用法 2          变量命名
════════════════════════════════════════════════════════

这一节把「给变量起名」讲完 —— 什么能当名字、什么不能、该怎么起。

────────────────────────────────────────────────────────
【合法字符】
────────────────────────────────────────────────────────

    可以出现：字母、数字、下划线、汉字
    必须开头：字母、下划线、汉字（不能是数字）

    合法：
        分数       name      _temp     count2     小喵咪
    非法：
        2score    ← 数字开头
        my-name   ← 减号不是合法字符
        my name   ← 有空格
        a.b       ← 点也不合法

────────────────────────────────────────────────────────
【不能是关键字】
────────────────────────────────────────────────────────

    Python 有一批词被语言本身占用了，不能拿来当变量名：

        if  else  elif  for  while  def  return  class
        import  from  as  try  except  finally  with
        and  or  not  in  is  None  True  False
        pass  break  continue  lambda  global  nonlocal
        del  assert  yield  raise  async  await

    写  if = 5  会直接报：
        SyntaxError: invalid syntax

    查全部关键字：
        import keyword
        print(keyword.kwlist)

────────────────────────────────────────────────────────
【大小写敏感】
────────────────────────────────────────────────────────

    Name、name、NAME 是三个不同的变量。

        name = "小喵咪"
        print(Name)
        → NameError: name 'Name' is not defined

    这个错特别隐蔽：你明明定义了，为什么说没有？
    因为大小写不一样。

────────────────────────────────────────────────────────
【中文变量名：能用，但要想清楚】
────────────────────────────────────────────────────────

    Python 3 允许中文变量名，因为它支持 Unicode 标识符。

        分数 = 95        合法
        我的变量 = 1      合法

    但中文变量名只是「允许」，不是「推荐」：
        · 输入时要切输入法，一进一出就是两次切换
        · 全角半角容易混，肉眼看不出来
        · 报错信息定位更难
        · 以后和别人的代码对接会出问题

    建议：变量名一律英文，注释和打印内容用中文。

────────────────────────────────────────────────────────
【命名风格：snake_case】
────────────────────────────────────────────────────────

    Python 的官方规范（PEP 8）规定：

        变量名、函数名      全小写，单词之间用下划线
                            user_name   total_price   is_ready

        类名                每个单词首字母大写
                            MyClass     GamePlayer

        常量                全大写
                            MAX_SIZE    PI

    别用：
        userName        这是 Java 风格，Python 里不推荐
        username        能用，但两个词挤一起不好读
        用户名           不推荐（见上）

────────────────────────────────────────────────────────
【名字要有意义】
────────────────────────────────────────────────────────

    差：
        a = 95
        b = 88
        c = (a + b) / 2

    好：
        数学 = 95
        语文 = 88
        平均分 = (数学 + 语文) / 2

    差的名字省了你 3 秒，坑了读代码的人 3 分钟。
    三个月后那个读代码的人，就是你自己。

    —— 但注意：循环里的临时变量用 i、j、k 是可以的，
       因为大家都知道它们是什么。短名字不是原罪，
       「含义不明的短名字」才是。
"""

