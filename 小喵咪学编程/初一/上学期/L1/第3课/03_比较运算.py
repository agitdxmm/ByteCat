r"""
════════════════════════════════════════════════════════
  L1 · 第 3 课 · 用法 3        比较运算
════════════════════════════════════════════════════════

这一节把「比较」讲完 —— 六个符号、结果是真假、以及三个必踩的坑。

────────────────────────────────────────────────────────
【六个符号，结果是 True 或 False】
────────────────────────────────────────────────────────

    ==      等于       5 == 5      →  True
    !=      不等于     5 != 3      →  True
    >       大于       5 > 3       →  True
    <       小于       5 < 3       →  False
    >=      大于等于   5 >= 5      →  True
    <=      小于等于   5 <= 3      →  False

    注意：结果是 bool，不是数字。
    所以 print(5 > 3) 输出 True，不是 1。

    （虽然 bool 是 int 的子类，True + True 会等于 2，
      但这是历史遗留设计，别用。）

────────────────────────────────────────────────────────
【坑一：= 和 == 是两件事】
────────────────────────────────────────────────────────

    =     赋值        x = 5       把 5 装进 x
    ==    比较        x == 5      问「x 是不是 5」

    写错的情况：
        if x = 5        →  SyntaxError，能立刻发现
        print(x = 5)    →  SyntaxError（print 不接受这个写法）

    在新版 Python 里，把 = 写成 == 的地方基本都会报错，
    这是好事。但在老代码里见过 if (x == 5) 写成 if (x = 5) 造成死循环的。

────────────────────────────────────────────────────────
【坑二：浮点数不能直接 ==】
────────────────────────────────────────────────────────

    0.1 + 0.2 == 0.3        →  False

    因为 0.1 + 0.2 实际是 0.30000000000000004。
    这不是 Python 的 bug，是二进制表示小数的固有误差。

    正确做法：比差值
        abs((0.1 + 0.2) - 0.3) < 1e-9

    或者用 round() 后再比。

────────────────────────────────────────────────────────
【坑三：字符串比较是按码点，不是按「意思」】
────────────────────────────────────────────────────────

    "abc" == "abc"       →  True
    "abc" == "ABC"       →  False      大小写不同
    "abc" < "abd"        →  True       逐字符比码点
    "10" < "9"           →  True       因为 '1' < '9'，不是按数值比

    最后一条最坑：
        "10" < "9"  是 True
        10 < 9      是 False

    所以从 input() 拿到的数字，一定要先转 int 再比大小。

────────────────────────────────────────────────────────
【链式比较：Python 的语法糖】
────────────────────────────────────────────────────────

    数学里写 0 < x < 10，Python 直接支持：

        0 < x < 10

    等价于：
        0 < x and x < 10

    而且 x 只会被计算一次（这对有副作用的表达式很重要）。

    其他语言大多不支持这种写法，所以很多人不知道 Python 可以这么写。

────────────────────────────────────────────────────────
【比较可以连类型比】
────────────────────────────────────────────────────────

    1 == 1.0        →  True      值相等就相等，不管类型
    1 == "1"        →  False     不同类型，直接 False，不报错

    注意第二行：它**不报错**，只是返回 False。
    所以 1 == "1" 是 False，不会崩，很容易被忽略。

    对比一下：
        1 + "1"      →  TypeError   报错
        1 == "1"     →  False       不报错

    加号要求类型一致，等号不要求。这个不对称容易让人麻痹。
"""

