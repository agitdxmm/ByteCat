r"""
════════════════════════════════════════════════════════
  L1 · 第 3 课 · 用法 4      浮点数与精度
════════════════════════════════════════════════════════

这一节把「小数」讲完 —— 它为什么不准、怎么处理、什么时候必须小心。

────────────────────────────────────────────────────────
【先说结论：计算机存不准 0.1】
────────────────────────────────────────────────────────

    0.1 + 0.2       →  0.30000000000000004
    0.1 + 0.2 == 0.3  →  False

    这不是 Python 的问题，是所有用二进制浮点的语言共同的问题。
    C、Java、JavaScript 全都一样：
        0.1 + 0.2 在 JS 里也是 0.30000000000000004

────────────────────────────────────────────────────────
【为什么】
────────────────────────────────────────────────────────

    计算机用二进制存数。
    整数好办：10 就是 1010。
    小数麻烦：0.5 = 1/2 能存，0.25 = 1/4 能存，
              但 0.1 = 1/10，分母有质因子 5，二进制表示不了。

    就像十进制写不出 1/3 的精确值（0.3333...），
    二进制也写不出 1/10 的精确值。

    float 只能存 53 位有效二进制位，超出部分被截断。
    0.1 被截断后，实际存的是一个非常接近但不等于 0.1 的数。
    加两个这样的数，误差就显出来了。

────────────────────────────────────────────────────────
【怎么处理：三条路】
────────────────────────────────────────────────────────

    路一：比较时用误差范围
        abs(a - b) < 1e-9

    路二：显示时四舍五入
        round(0.1 + 0.2, 2)        →  0.3
        注意 round 返回的还是 float，只是位数对了。

    路三：涉及钱的时候，用整数（分）代替小数（元）
        12.34 元  →  1234 分
        计算全用整数，最后再除回去。

        或者用 decimal 模块（精确十进制）：
            from decimal import Decimal
            Decimal("0.1") + Decimal("0.2")    →  Decimal('0.3')

        decimal 是精确计算，但慢，而且必须用字符串初始化。

────────────────────────────────────────────────────────
【round 的两个坑】
────────────────────────────────────────────────────────

    坑一：round 不是「四舍五入」，是「银行家舍入」
        round(0.5)   →  0
        round(1.5)   →  2
        round(2.5)   →  2       ← 不是 3！
        round(3.5)   →  4

        规则是「遇到 .5 就往偶数那边靠」。
        这叫 banker's rounding，目的是减少统计偏差。
        想要传统四舍五入，得用 decimal 或者自己写。

    坑二：round 处理浮点误差时可能翻车
        round(2.675, 2)   →  2.67     不是 2.68
        因为 2.675 实际存的是 2.67499999999999982...

────────────────────────────────────────────────────────
【类型转换：一句话记住三件事】
────────────────────────────────────────────────────────

    int(x)      转整数    砍掉小数（向零方向）
    float(x)    转小数    整数补 .0
    str(x)      转文字    什么都能转

    反过来（文字转数字）只在内容是数字时才行：
        int("95")      →  95
        int("95.5")    →  ValueError    不能直接转，要先 float
        float("95.5")  →  95.5

────────────────────────────────────────────────────────
【int 和 float 混算，结果一定是 float】
────────────────────────────────────────────────────────

    1 + 2.0      →  3.0
    10 / 2       →  5.0      除法永远 float
    10 // 3      →  3        整除才是 int

    如果后面需要整数，记得转：
        int(10 / 2)  →  5
"""

