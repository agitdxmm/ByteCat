r"""
════════════════════════════════════════════════════════
  L1 · 第 5 课 · 用法 4        数字格式化
════════════════════════════════════════════════════════

这一节把「数字怎么显示」讲完 —— 小数位数、千分位、百分比、补零、进制。

────────────────────────────────────────────────────────
【格式说明符的完整结构】
────────────────────────────────────────────────────────

    f"{值:[填充][对齐][符号][宽度][,][.精度][类型]}"

    方括号里的都可以省略。常用的组合：

        :.2f        两位小数
        :>10.2f     右对齐，宽度 10，两位小数
        :08.2f      宽度 8，前面补零，两位小数
        :,          千分位
        :,.2f       千分位 + 两位小数
        :.1%        百分比，一位小数

────────────────────────────────────────────────────────
【小数位数：.nf】
────────────────────────────────────────────────────────

    f"{3.14159:.2f}"     →  3.14
    f"{3.14159:.4f}"     →  3.1416
    f"{3:.2f}"           →  3.00       整数也能用，会补 .00

    注意它会**四舍五入**，而且是标准的四舍五入（不是 round 的银行家舍入）：

        f"{2.5:.0f}"         →  2         等的，这也是银行家舍入
        f"{2.675:.2f}"       →  2.67      浮点误差，不是舍入问题

    对，.2f 用的也是浮点数的实际值，
    所以 2.675 那个老问题一样存在。

    想要绝对精确的十进制舍入，只能用 decimal 模块。

────────────────────────────────────────────────────────
【千分位：,】
────────────────────────────────────────────────────────

    f"{1234567:,}"       →  1,234,567
    f"{1234567.891:,.2f}"→  1,234,567.89

    这个符号放在宽度和精度之间。

────────────────────────────────────────────────────────
【百分比：%】
────────────────────────────────────────────────────────

    f"{0.856:.1%}"       →  85.6%
    f"{0.856:.0%}"       →  86%
    f"{1.5:%}"           →  150.000000%

    注意：
        · 它会自动乘 100
        · 不加精度会输出一堆小数，所以基本都要写 .1% 这种
        · 值本身要是小数（0.856），不是 85.6

────────────────────────────────────────────────────────
【补零和宽度：0 和数字】
────────────────────────────────────────────────────────

    f"{95:05d}"          →  00095
    f"{7:02d}"           →  07
    f"{2026:04d}"        →  2026

    用途：
        · 编号        f"{i:03d}"    001 002 003
        · 日期        f"{月:02d}-{日:02d}"
        · 时间        f"{时:02d}:{分:02d}:{秒:02d}"

    注意 0 是「填充字符」，不是「补到几位」。
    :05d 的意思是「总宽度 5，不够的部分用 0 从左补」。
    所以 123456 用 :05d 还是 123456，不会截断。

────────────────────────────────────────────────────────
【整数类型：d】
────────────────────────────────────────────────────────

    f"{95:d}"            →  95
    f"{95.9:.0f}"        →  96        四舍五入
    f"{95.9:d}"          →  报错！     d 只接受整数

    d 是 decimal 的缩写，表示「按十进制整数显示」。
    传小数进去会报 ValueError。

────────────────────────────────────────────────────────
【其他进制】
────────────────────────────────────────────────────────

    f"{255:b}"           →  11111111      二进制
    f"{255:o}"           →  377           八进制
    f"{255:x}"           →  ff            十六进制（小写）
    f"{255:X}"           →  FF            十六进制（大写）
    f"{255:#x}"          →  0xff          带前缀
    f"{255:#b}"          →  0b11111111

    这个在做底层相关的东西时有用（比如你之前玩 DLL、PE 文件）。

────────────────────────────────────────────────────────
【符号：+ 和空格】
────────────────────────────────────────────────────────

    f"{5:+d}"            →  +5            正数也显示符号
    f"{-5:+d}"           →  -5
    f"{5: d}"            →  " 5"          正数前面空一格
    f"{-5: d}"           →  "-5"

    : d 的用处是让正负数「右对齐」，因为符号位宽度一致。
"""

