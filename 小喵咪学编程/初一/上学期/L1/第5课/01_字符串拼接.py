r"""
════════════════════════════════════════════════════════
  L1 · 第 5 课 · 用法 1        字符串拼接与重复
════════════════════════════════════════════════════════

这一节把「把几段文字拼成一段」讲完 —— 加号、乘号、以及它们的死穴。

────────────────────────────────────────────────────────
【加号：拼接】
────────────────────────────────────────────────────────

    "Hello" + "World"       →  "HelloWorld"
    "a" + "b" + "c"         →  "abc"

    注意：
        · 拼接不加空格，空格要自己写
        · 两边都必须是字符串

    "Hello" + " " + "World"     →  "Hello World"

────────────────────────────────────────────────────────
【乘号：重复】
────────────────────────────────────────────────────────

    "ab" * 3        →  "ababab"
    "-" * 20        →  "--------------------"
    3 * "ab"        →  "ababab"      数字在前也行

    这个技巧非常常用：
        分隔线        print("=" * 40)
        缩进          " " * 4
        重复图案      "★" * 5

────────────────────────────────────────────────────────
【死穴：不能和数字直接加】
────────────────────────────────────────────────────────

    "分数：" + 95
    → TypeError: can only concatenate str (not "int") to str

    加号只接受「字符串 + 字符串」。
    想要拼数字，必须先转：

        "分数：" + str(95)      →  "分数：95"

    这是拼接最大的麻烦：每拼一个数字就要写一次 str()。

        姓名 = "小喵咪"
        年龄 = 14
        分数 = 95

        print(姓名 + "今年" + str(年龄) + "岁，考了" + str(分数) + "分")
        →  小喵咪今年14岁，考了95分

    长了以后非常难看，容易漏括号、漏 str。

────────────────────────────────────────────────────────
【所以有了 f-string】
────────────────────────────────────────────────────────

    同样的输出：

        print(f"{姓名}今年{年龄}岁，考了{分数}分")

    不用 str()，不用加号，数字自动转。
    这是下一节的主题，这里先知道它解决了什么问题。

────────────────────────────────────────────────────────
【拼接的性能问题（了解一下）】
────────────────────────────────────────────────────────

    Python 的字符串是「不可变」的。
    每次 + 都会创建一个新字符串，旧的丢掉。

    拼 2 段无所谓，拼 10000 段就会很慢：

        s = ""
        for i in range(10000):
            s = s + str(i)       ← 每次都复制一遍，越来越慢

    正确做法是用 join()（L5 后面讲）或者列表。

    但你现在写的东西都是拼两三段，不用管这个。
    知道有这回事，以后遇到「拼接很慢」时能想起来。

────────────────────────────────────────────────────────
【什么时候该用拼接】
────────────────────────────────────────────────────────

    现在（还没学 f-string 之前）：
        · 简单拼接两三段，用 +
        · 需要重复图案，用 *

    学了 f-string 之后：
        · 带变量的，一律 f-string
        · 只有纯字面量的常量拼接，才用 +

    例：
        "https://" + "example.com"      ← 两个都是常量，+ 就行
        f"你好，{名字}"                  ← 有变量，用 f
"""

