r"""
════════════════════════════════════════════════════════
  L1 · 第 5 课 · 用法 2        f-string
════════════════════════════════════════════════════════

这一节把 f-string 讲完 —— 现在 Python 里拼字符串的标准做法。

────────────────────────────────────────────────────────
【基本写法：引号前面加个 f】
────────────────────────────────────────────────────────

    名字 = "小喵咪"
    print(f"你好，{名字}")

    输出：你好，小喵咪

    f 是 format（格式化）的缩写。
    加了 f，字符串里的 {} 就成了「坑」，里面可以写变量。

────────────────────────────────────────────────────────
【{} 里能放什么】
────────────────────────────────────────────────────────

    变量：
        f"{名字}"

    表达式（能算的都行）：
        f"{1 + 1}"              →  2
        f"{年龄 + 1}"           →  15
        f"{'abc'.upper()}"      →  ABC

    函数调用：
        f"{len(名字)}"          →  3

    一句话：{} 里就是一个正常的 Python 表达式，
    它会先被算出来，再把结果填进去。

────────────────────────────────────────────────────────
【它能自动处理类型】
────────────────────────────────────────────────────────

    这就是它比 + 强的地方：

        年龄 = 14
        print("年龄：" + str(年龄))      ← 必须 str()
        print(f"年龄：{年龄}")           ← 不用转

    {} 里不管是什么类型，f-string 都会自动转成字符串。
    数字、小数、True/False、列表，全都能塞。

────────────────────────────────────────────────────────
【引号怎么配】
────────────────────────────────────────────────────────

    f-string 的引号规则和普通字符串一样，但多一层：

        f"内容里有 {变量}"
        f'内容里有 {变量}'
        f'''多行
        {变量}'''

    如果 {} 里面要用字符串，注意别和外层引号撞：

        对：  f"{'单引号在里面'}"
        错：  f"{"双引号在里面"}"      ← 会报错

    Python 3.12 之后这个限制放宽了，但为了兼容，还是别撞。

────────────────────────────────────────────────────────
【转义还是照常】
────────────────────────────────────────────────────────

    f"第一行\n第二行"            \n 照样是换行
    f"路径：{路径}\n"            都可以

    但注意花括号：
        想输出一个真的 { 或 }，得写两个：
            f"{{}} "              →  {}
            f"{{名字}}"           →  {名字}

    因为单个 {} 会被当成坑。

────────────────────────────────────────────────────────
【格式说明符：冒号后面写规则】
────────────────────────────────────────────────────────

    这是 f-string 真正强的地方：

        f"{3.14159:.2f}"         →  3.14        保留两位小数
        f"{95:5d}"               →  "   95"     宽度 5，右对齐
        f"{95:<5d}"              →  "95   "     左对齐
        f"{95:^5d}"              →  " 95  "     居中
        f"{95:05d}"              →  "00095"     补零
        f"{1234567:,}"           →  1,234,567   千分位
        f"{0.856:.1%}"           →  85.6%       百分比

    冒号后面那一串叫「格式说明符」，下一节专门讲。
    这里先知道它能干这些事。

────────────────────────────────────────────────────────
【为什么推荐它】
────────────────────────────────────────────────────────

    对比三种写法，输出同一句话：

        # 1. 拼接
        print("我叫" + 名字 + "，今年" + str(年龄) + "岁")

        # 2. format 方法（老写法）
        print("我叫{}，今年{}岁".format(名字, 年龄))

        # 3. f-string（推荐）
        print(f"我叫{名字}，今年{年龄}岁")

    f-string 最短、最直观、不用数参数顺序、不容易漏 str。

    Python 3.6 之后的所有版本都支持。
    如果你看到有人还在用 % 或者 format，那是老代码或者兼容需求，
    新写的代码一律用 f-string。
"""

