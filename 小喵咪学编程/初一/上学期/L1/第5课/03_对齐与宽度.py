r"""
════════════════════════════════════════════════════════
  L1 · 第 5 课 · 用法 3        对齐与宽度
════════════════════════════════════════════════════════

这一节把「怎么让输出排整齐」讲完 —— 宽度、方向、填充、以及中文的坑。

────────────────────────────────────────────────────────
【三个方向符】
────────────────────────────────────────────────────────

    :<n     左对齐，总宽度 n
    :>n     右对齐，总宽度 n
    :^n     居中，总宽度 n

    例（n = 8）：

        f"[{'ab':<8}]"      →  [ab      ]
        f"[{'ab':>8}]"      →  [      ab]
        f"[{'ab':^8}]"      →  [   ab   ]

    数字默认是右对齐，字符串默认是左对齐：

        f"[{95:5}]"         →  [   95]     数字自动右对齐
        f"[{'ab':5}]"       →  [ab   ]     字符串自动左对齐

    所以写数字表格时，:5 就够了，不用写 :>5。

────────────────────────────────────────────────────────
【填充字符：在方向符前面加一个】
────────────────────────────────────────────────────────

    f"{'ab':*>8}"       →  ******ab
    f"{'ab':*<8}"       →  ab******
    f"{'ab':*^8}"       →  ***ab***
    f"{95:0>5}"         →  00095

    中间那个字符就是填充物，默认是空格。

    常见的：
        :0>5        数字补零
        :->20       目录线（左对齐，右边补横线）
        :.>20       点线

    目录里那种「章节........页码」的效果：

        f"{'第一章':.<30}"

    →  第一章............................

    想用横线，就把点换成 -：

        f"{'第一章':-<30}"    →  第一章----------------------------

────────────────────────────────────────────────────────
【一个必须知道的解析规则】
────────────────────────────────────────────────────────

    填充字符后面，必须**紧跟**对齐符（< > ^ =）。

    f"{'第一章':-<30}"      fill=-  align=<  width=30     ✓ 右补横线
    f"{'第一章':.<30}"      fill=.  align=<  width=30     ✓ 右补点

    但如果中间插了别的东西，就会解析失败：

        f"{'第二章':.->30}"    ✗  ValueError: Format specifier missing precision

    为什么？因为 Python 看到第二个字符是 `-`，
    `-` 不是对齐符（对齐符只有 < > ^ = 四个），
    于是它认为「第一个字符不是填充符」，
    转而去把 `.` 当成「精度」的开头，
    结果 `.` 后面跟着 `-`，不是数字 → 报「缺精度」。

    记住：fill 和 align 必须紧挨着，中间不能夹东西。
    而且 `-` 在这里是**符号位**的意思（正负号），不是对齐符。

────────────────────────────────────────────────────────
【中文的坑：len 不等于显示宽度】
────────────────────────────────────────────────────────

    这是 Windows 终端里最烦的问题。

    "小喵咪"     len() 是 3，但在屏幕上占 6 列
    "abc"        len() 是 3，屏幕上占 3 列

    因为中文是「全角字符」，一个字符画两个格子。

    f-string 的宽度按**字符数**算，不按显示列数算。
    所以用它对齐中文表格，结果一定是歪的：

        f"{'小喵咪':<8}"      字符数补到 8，显示宽度变成 6+5=11
        f"{'abc':<8}"         字符数补到 8，显示宽度是 3+5=8

    两者差 3 列，表格就歪了。

────────────────────────────────────────────────────────
【怎么解决中文对齐】
────────────────────────────────────────────────────────

    方法一：手动算宽度，自己补空格
        中文字符数 = len(s)
        显示宽度   = len(s) + 中文字符数
        需要补的空格 = 目标宽度 - 显示宽度

        代码：
            def 宽(s):
                return sum(2 if ord(c) > 127 else 1 for c in s)

        然后用 目标宽度 - 宽(s) 个空格去补。
        （这涉及 def 和 for，等 L3/L2 学过再回来写）

    方法二：干脆不用空格对齐，用制表符 \t
        前提是每列内容都短于 8 列。这招简单粗暴但有效。

    方法三：输出到文件或者网页，用 CSS 对齐
        终端里永远解决不了，就别硬扛。

────────────────────────────────────────────────────────
【实际建议】
────────────────────────────────────────────────────────

    现在你的程序输出给谁看？
        · 自己看 → 对齐差点没关系
        · 给别人看 → 尽量别用中文做需要对齐的列

    真要做中文表格，等你学完 L2（循环）和 L3（函数），
    写一个宽度计算函数，那时候再解决。

    现在知道「为什么歪」比「怎么修」更重要。
"""

