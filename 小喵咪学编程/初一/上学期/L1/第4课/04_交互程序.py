r"""
════════════════════════════════════════════════════════
  L1 · 第 4 课 · 用法 4        把输入输出串成程序
════════════════════════════════════════════════════════

这一节把前三节的零件组装起来 —— 一个能用的程序长什么样。

────────────────────────────────────────────────────────
【所有程序都是这三段】
────────────────────────────────────────────────────────

    输入  →  处理  →  输出

    输入：从用户那里拿数据      input()
    处理：算、判断、转换        运算、类型转换
    输出：把结果告诉用户        print()

    现在你只有 input 和 print，所以程序长这样：

        数据 = input("提示")
        结果 = 数据 * 2
        print("结果：", 结果)

    等你学了 if、for、def，中间那段会越来越长，
    但骨架永远是这三段。

────────────────────────────────────────────────────────
【提示语是程序的脸】
────────────────────────────────────────────────────────

    差：
        a = input()
        b = input()

    好：
        a = float(input("单价："))
        b = int(input("数量："))

    差在哪：
        · 差版本，用户不知道要输什么
        · 差版本，输错了也不知道是哪一步错的
        · 好版本自带说明书，还能当调试线索

    提示语的三个要求：
        1. 说清楚要什么        「请输入身高」
        2. 说清楚单位           「身高（米）」
        3. 说清楚格式（如果需要）「日期（2026-11-07）」

────────────────────────────────────────────────────────
【输出也要设计】
────────────────────────────────────────────────────────

    差：
        print(x)

    好：
        print("总价：", x, "元")

    差在：
        · 差版本，屏幕上只有一个数字，不知道是什么
        · 好版本，一眼看懂

    一条实用原则：
        **程序输出的每一行，都应该能单独读懂。**
        假设用户只截了那一行发给别人，对方要知道这是什么。

────────────────────────────────────────────────────────
【顺序会决定体验】
────────────────────────────────────────────────────────

    有时候先问什么后问什么，会影响用户的理解：

        先问「单价」再问「数量」      →  顺着算，自然
        先问「数量」再问「单价」      →  也行，但脑子里要存着

    涉及计算的，一般按「公式的顺序」问：

        总价 = 单价 × 数量
        ↓        ↓
        先问     再问

────────────────────────────────────────────────────────
【空行和分隔线不是装饰】
────────────────────────────────────────────────────────

    一次问三个问题，如果全挤在一起：

        姓名：张三
        年龄：14
        城市：杭州
        结果：张三 14 杭州

    加空行分组：

        姓名：张三
        年龄：14
        城市：杭州

        结果：张三 14 杭州

    第二种更好读，因为「输入区」和「结果区」被视觉隔开了。

    写的时候加一句 print() 就行。

────────────────────────────────────────────────────────
【现在做不到的事】
────────────────────────────────────────────────────────

    这一节的程序还是「假设用户输入全对」。

    做不到：
        · 用户输错时提示重来     （需要 if 和 try，L2/L5）
        · 让程序循环跑           （需要 while，L2）
        · 把结果存到文件里       （需要文件操作，L5）

    所以现在的程序都是「一次性」的：跑一遍，出结果，结束。

    这已经能做出很多有用的东西了，先把手感练出来。
"""

