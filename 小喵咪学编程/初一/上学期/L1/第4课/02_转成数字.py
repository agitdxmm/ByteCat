r"""
════════════════════════════════════════════════════════
  L1 · 第 4 课 · 用法 2        把输入转成数字
════════════════════════════════════════════════════════

这一节把「input + 类型转换」讲完 —— 为什么要转、怎么写、转不了会怎样。

────────────────────────────────────────────────────────
【标准写法：包起来】
────────────────────────────────────────────────────────

    整数：
        年龄 = int(input("年龄："))

    小数：
        身高 = float(input("身高（米）："))

    就这么写。绝大多数情况不需要别的花样。

────────────────────────────────────────────────────────
【嵌套顺序：从里往外读】
────────────────────────────────────────────────────────

    int(input("年龄："))

    读法是从最里面开始：

        第一步   input("年龄：")      显示提示，等输入，拿到字符串
        第二步   int(...)             把那个字符串转成整数
        第三步   装进 年龄

    写成反的会怎样？
        input(int("年龄："))

        第一步   int("年龄：")        → ValueError！"年龄："不是数字

    所以括号的方向记牢：**input 在最里层**。

────────────────────────────────────────────────────────
【转不了的三种情况】
────────────────────────────────────────────────────────

    情况一：输入了非数字
        输入   abc
        int("abc")
        → ValueError: invalid literal for int() with base 10: 'abc'

    情况二：直接回车（空输入）
        输入   （什么都没有）
        int("")
        → ValueError: invalid literal for int() with base 10: ''

    情况三：输入小数但用了 int
        输入   3.14
        int("3.14")
        → ValueError: invalid literal for int() with base 10: '3.14'

    注意第三条：int() 不接受带小数点的**字符串**。
    但 int(3.14) （真 float）是能转的，得到 3。
    区别在于：字符串 "3.14" 要转 int，得先 float 再 int：
        int(float("3.14"))   →  3

────────────────────────────────────────────────────────
【ValueError 和 TypeError 的区别】
────────────────────────────────────────────────────────

    TypeError      类型不对        1 + "2"
    ValueError     类型对但值不行   int("abc")

    int("abc") 的 TypeError 不会发生，因为 int() 接受字符串参数。
    它只是在转换的过程中发现「这个字符串不是数字」，所以是 ValueError。

    记法：
        连参数类型都不对 → TypeError
        类型对、内容坏   → ValueError

────────────────────────────────────────────────────────
【一次输入多个数？现在还不行】
────────────────────────────────────────────────────────

    你可能会想一次输入「12 34」然后拿到两个数。

    input() 不管里面有什么，整串都给你："12 34"。
    要拆开得用 split()，那是字符串方法（第 5 课）。

    现在只能一次问一个：
        a = int(input("第一个数："))
        b = int(input("第二个数："))

────────────────────────────────────────────────────────
【为什么要这么麻烦】
────────────────────────────────────────────────────────

    因为 input 拿到的永远是「用户敲的一串字符」，
    它不知道你想要数字还是文字。

    如果 Python 自动猜，反而更危险：
        用户输入 007，自动转成 7，丢了前导零
        用户输入 1e5，自动转成 100000
        用户输入 中文，转不了又该怎么办

    所以 Python 把决定权交给你：**你自己说这是什么**。

    这不是麻烦，这是明确。
"""

