r"""
════════════════════════════════════════════════════════
  L1 · 第 4 课 · 用法 1        input 基础
════════════════════════════════════════════════════════

这一节把 input() 讲完 —— 它做什么、返回什么、怎么用提示语。

────────────────────────────────────────────────────────
【input 只有一个作用：等用户打字，然后把打的东西拿回来】
────────────────────────────────────────────────────────

    名字 = input()

    执行到这一行，程序会停下来，光标闪烁，等你敲字 + 回车。
    你敲的内容，会被装进「名字」这个变量。

────────────────────────────────────────────────────────
【返回值永远是字符串】
────────────────────────────────────────────────────────

    这是最重要的一条，也是后面所有坑的源头。

    你输入  95      程序拿到的是 "95"     ← 字符串
    你输入  3.14    程序拿到的是 "3.14"   ← 字符串
    你输入  你好    程序拿到的是 "你好"   ← 字符串

    不管输入什么，类型都是 str。

    验证：
        x = input()
        print(type(x))       →  <class 'str'>

────────────────────────────────────────────────────────
【加提示语，别让用户瞎猜】
────────────────────────────────────────────────────────

    input() 可以带一个参数，作为提示：

        名字 = input("请输入你的名字：")

    屏幕上会先显示「请输入你的名字：」，然后等着。

    注意：这个提示语不会换行，会跟用户输入在同一行。
    想换行就在末尾自己加 \n：

        名字 = input("请输入你的名字：\n")

    不写提示语的后果：程序运行后屏幕上什么都没有，
    用户以为卡死了，其实是它在等你。

────────────────────────────────────────────────────────
【input 返回的一定是字符串，哪怕你只敲了数字】
────────────────────────────────────────────────────────

    这是新手 90% 的错误来源：

        年龄 = input("年龄：")
        年龄 = 年龄 + 1        ← TypeError!

    报错：
        TypeError: can only concatenate str (not "int") to str

    「can only concatenate str」= 只能拼接字符串。
    你拿字符串 + 数字，它不会自动帮你转。

────────────────────────────────────────────────────────
【想拿数字，必须自己转】
────────────────────────────────────────────────────────

    年龄 = int(input("年龄："))        整数
    身高 = float(input("身高："))      小数

    注意括号的嵌套顺序：
        int(input(...))     先执行里面的 input，拿到字符串，再转成 int

    写成  input(int("年龄："))  就错了，那样会把提示语拿去转数字。

────────────────────────────────────────────────────────
【一个细节：input 会吃掉末尾的换行】
────────────────────────────────────────────────────────

    你敲「张三」+ 回车，input 拿到的是 "张三"，不是 "张三\n"。

    但如果你敲了空格再回车，「空格」会被保留：
        输入   "张三 "     ← 末尾有个空格
        拿到   "张三 "     长度 3，不是 2

    所以做输入校验时，通常要 .strip() 一下：
        名字 = input("名字：").strip()

    strip 是字符串方法，第 5 课才讲，这里先知道有这回事。

────────────────────────────────────────────────────────
【input 在命令行和 IDE 里的表现不一样】
────────────────────────────────────────────────────────

    PyCharm 里运行，输入框在下方 Run 窗口里。
    双击 .py 文件运行，会弹出一个黑色窗口。
    在终端里 python xxx.py，就在终端里等。

    三种情况都能用，但报错信息的位置不一样。
    如果找不到输入的地方，看 Run 窗口底部。
"""

