r'''
════════════════════════════════════════════════════════
  L3 · 第 5 课 · 用法 1        函数作为参数
════════════════════════════════════════════════════════

L3 第 1 课讲过一句话：**函数名是一个值。**

当时演示的是 `别名 = 打招呼`。

这一节把它用到底：**函数能像数字一样，当参数传给别的函数。**

────────────────────────────────────────────────────────
【先确认一件事：函数真的能传】
────────────────────────────────────────────────────────

    def 打招呼():
        print("你好")

    def 执行(要做的事):
        要做的事()          ← 参数后面加括号，就是调用它

    执行(打招呼)            → 你好

    注意调用处的写法：`执行(打招呼)` ——
    **没有括号**。

        ✅ 执行(打招呼)     传的是「函数本身」
        ❌ 执行(打招呼())   传的是「打招呼的返回值」（这里是 None）

    这个区别是这一节的核心。

────────────────────────────────────────────────────────
【为什么这有用：一个函数，很多种行为】
────────────────────────────────────────────────────────

    看这个例子：

        def 加(a, b):
            return a + b

        def 减(a, b):
            return a - b

        def 乘(a, b):
            return a * b

        def 算(运算, a, b):
            return 运算(a, b)

    调用：

        算(加, 10, 3)       → 13
        算(减, 10, 3)       → 7
        算(乘, 10, 3)       → 30

    ── 发生了什么 ──

        `算` 这个函数不知道自己在做加法还是减法。
        它只知道「我要用传进来的这个东西，算 a 和 b」。

        具体算什么，由调用方决定。

    ── 好处 ──

        以后要加一个「除」，只要写一个 `除` 函数，
        `算` 一行都不用改：

            def 除(a, b):
                if b == 0:
                    return None
                return a / b

            算(除, 10, 5)        → 2.0

        **这就是「把变化的部分抽出去」。**

────────────────────────────────────────────────────────
【用途一：重复做同一件事】
────────────────────────────────────────────────────────

    def 重复(次数, 要做的事):
        for i in range(次数):
            要做的事()

    调用：

        def 打招呼():
            print("你好")

        重复(3, 打招呼)

        输出三行「你好」。

    ── 这个写法有个大好处 ──

        如果要「重复打印星号」，不用改 `重复`：

            def 打印星号():
                print("*" * 10)

            重复(2, 打印星号)

        `重复` 负责「重复几次」，`要做的事` 负责「做什么」。
        两件事分开了。

────────────────────────────────────────────────────────
【用途二：把「比较规则」参数化】
────────────────────────────────────────────────────────

    想找一个数里的「最大值」，但规则可以变：

        def 按数值(a, b):
            return a > b

        def 按绝对值(a, b):
            return abs(a) > abs(b)

        def 找最大(列表, 比较规则):
            ...

    （列表是 L4 的内容，这里换成两个数：）

        def 选大的(a, b, 比较规则):
            if 比较规则(a, b):
                return a
            return b

        选大的(3, -5, 按数值)       → 3
        选大的(3, -5, 按绝对值)     → -5    （因为 |-5| > |3|）

    同一个函数，换一个「规则」，行为完全不同。

    ── 这种写法在真实代码里很常见 ──

        Python 内置的排序函数就是这样：

            sorted(列表, key=某个函数)

        key 就是个函数，它决定「按什么排序」。
        （sorted 和列表都在 L4/L5 讲，这里先知道有这回事。）

────────────────────────────────────────────────────────
【用途三：根据条件选一个函数】
────────────────────────────────────────────────────────

        def 加(a, b):
            return a + b

        def 减(a, b):
            return a - b

        def 取运算(符号):
            if 符号 == "+":
                return 加
            if 符号 == "-":
                return 减
            return None

    注意 `return 加` —— 返回的是函数本身，没有括号。

    用起来：

        运算 = 取运算("+")
        结果 = 运算(10, 3)        → 13

    ── 这和 if-else 有什么区别 ──

        不用函数的话：

            if 符号 == "+":
                结果 = a + b
            elif 符号 == "-":
                结果 = a - b

        能跑，但每加一个运算就要改这段 if。

        用函数表：

            运算 = 取运算(符号)
            结果 = 运算(a, b)

        加新运算只要写个新函数，再在 `取运算` 里加一行。

        **主流程不变，这是最重要的。**

────────────────────────────────────────────────────────
【一个必须注意的坑：括号】
────────────────────────────────────────────────────────

    这是初学者最常犯的错，值得单独说。

        def 打招呼():
            print("你好")

        def 执行(要做的事):
            要做的事()

        执行(打招呼)         ✅ 传函数 → 「你好」
        执行(打招呼())       ❌ 传 None

    ── 为什么第二个错 ──

        括号是「调用」。

        `打招呼()` 会立刻执行 打招呼，
        打印「你好」，然后这个表达式的值是 None。

        所以 `执行(打招呼())` 等于 `执行(None)`。

        然后函数体里 `要做的事()` 就变成 `None()`，
        报错：TypeError: 'NoneType' object is not callable
        （None 这个类型不能被调用）

    ── 记忆方法 ──

        传函数时，你是在「把菜谱交给别人」。
        加了括号就是「先做好一道菜，把菜交出去」。

        你要交的是菜谱，不是菜。

────────────────────────────────────────────────────────
【什么样的函数适合当参数】
────────────────────────────────────────────────────────

    ── 适合 ──

        ① 短小的、只做一件事的
           加、减、判断大小、格式化 —— 这些天生就是「零件」。

        ② 会被反复用的
           比如「比较规则」在各种地方都要用。

        ③ 用来替换变化的部分
           主流程固定，细节可变。

    ── 不适合 ──

        ① 需要很多参数才能工作的
           传进去还得再准备一堆东西，不如直接写在里面。

        ② 有副作用的（会改外部状态）
           传进来的函数偷偷改了全局变量，调试起来很痛苦。

        ③ 只有一种可能性的
           如果「要做的事」永远是 打印星号，
           那就别加参数了，直接写死更简单。

────────────────────────────────────────────────────────
【这就是「高阶函数」】
────────────────────────────────────────────────────────

    接受函数作为参数的函数，或者返回函数的函数，
    叫**高阶函数**（higher-order function）。

    L3 第 3 课的「返回一个函数」也是高阶函数：

        def 乘以(n):
            def 内层(x):
                return x * n
            return 内层          ← 返回函数

    这一节的「接受函数作为参数」也是：

        def 执行(要做的事):
            要做的事()           ← 接受函数

    两个方向，合起来就是「函数是一等公民」：
    能赋值给变量、能当参数、能当返回值。

    这个概念在所有现代语言里都有（JavaScript、Java、C# 等）。
'''

