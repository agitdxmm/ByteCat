# ── 计算层 ──


def 总分(语文, 数学, 英语):
    """返回三科总分。"""
    return 语文 + 数学 + 英语


def 平均(总, 科目数=3):
    """返回平均分。科目数默认 3。"""
    return 总 / 科目数


def 等级(平均分):
    """按平均分返回等级字母：A/B/C/D/E。"""
    if 平均分 >= 90:
        return "A"
    if 平均分 >= 80:
        return "B"
    if 平均分 >= 70:
        return "C"
    if 平均分 >= 60:
        return "D"
    return "E"


# ── 显示层 ──


def 分隔线(字符="-", 宽度=62):
    """打印一条指定字符、指定宽度的分隔线。"""
    print(字符 * 宽度)


def 表头():
    """打印表格的标题行。"""
    print(f"{'姓名':<8}{'语文':>6}{'数学':>6}{'英语':>6}"
          f"{'总分':>7}{'平均':>8}{'等级':>6}")


def 打印一行(姓名, 语文, 数学, 英语):
    """打印一个学生的成绩行。"""
    总 = 总分(语文, 数学, 英语)
    均 = 平均(总)
    等 = 等级(均)
    print(f"{姓名:<8}{语文:>6}{数学:>6}{英语:>6}"
          f"{总:>7}{均:>8.1f}{等:>6}")


# ── 主程序 ──


def 主程序():
    """生成完整的成绩报告。"""
    学生1 = ("张三", 92, 88, 95)
    学生2 = ("李四", 78, 85, 80)
    学生3 = ("王五", 55, 62, 48)

    分隔线("=")
    print("成绩报告".center(56))
    分隔线("=")
    表头()
    分隔线("-")

    打印一行(*学生1)
    打印一行(*学生2)
    打印一行(*学生3)

    分隔线("-")

    总分1 = 总分(学生1[1], 学生1[2], 学生1[3])
    总分2 = 总分(学生2[1], 学生2[2], 学生2[3])
    总分3 = 总分(学生3[1], 学生3[2], 学生3[3])

    平均总分 = (总分1 + 总分2 + 总分3) / 3

    最高 = 总分1
    谁 = 学生1[0]
    if 总分2 > 最高:
        最高 = 总分2
        谁 = 学生2[0]
    if 总分3 > 最高:
        最高 = 总分3
        谁 = 学生3[0]

    print(f"  班级平均总分：{平均总分:.1f}")
    print(f"  最高总分：    {最高}（{谁}）")
    分隔线("=")


主程序()


