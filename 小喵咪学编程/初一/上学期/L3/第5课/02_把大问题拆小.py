r'''
════════════════════════════════════════════════════════
  L3 · 第 5 课 · 用法 2        把大问题拆小
════════════════════════════════════════════════════════

写程序最难的不是语法，是「不知道从哪下手」。

这一节讲一个方法：**自顶向下**。先写骨架，再填血肉。

────────────────────────────────────────────────────────
【错误的下手方式：从头往下写】
────────────────────────────────────────────────────────

    需求：做一个「银行存款利息计算报告」。

        输入：本金、年利率、年数
        输出：
            ==============================
            存款计划
            ==============================
            本金：10000 元
            年利率：3.0%
            年限：5 年
            ------------------------------
            第 1 年：10300.00 元
            第 2 年：10609.00 元
            ...
            第 5 年：11592.74 元
            ------------------------------
            总利息：1592.74 元
            平均每年增长：318.55 元
            ==============================

    ── 从头往下写会怎样 ──

        print("=" * 30)
        print("存款计划")
        print("=" * 30)
        print(f"本金：{10000} 元")
        print(f"年利率：{0.03 * 100:.1f}%")
        ...
        金额 = 10000
        for 年 in range(1, 6):
            金额 = 金额 * (1 + 0.03)
            print(f"第 {年} 年：{金额:.2f} 元")
        ...

    写到一半你会发现：

        · 年份要改（从 5 年改成 10 年）—— 得改好几处
        · 格式要调 —— 30 个等号散在五六个地方
        · 想加一段「如果利率超过 5%，标红警告」—— 不知道插哪儿
        · 想复用「打印分隔线」—— 已经复制粘贴了三次

    **这种写法叫「流水账式编程」。** 能跑，但改不动。

────────────────────────────────────────────────────────
【正确的方式：先写骨架】
────────────────────────────────────────────────────────

    第一步：**用中文描述一遍流程**，不管代码。

        ① 打印标题
        ② 打印参数（本金、利率、年数）
        ③ 逐年计算并打印
        ④ 打印汇总（总利息、平均每年）
        ⑤ 打印结尾

    第二步：**把每一步变成一个函数名**，先不实现。

        def 打印标题():
            pass

        def 打印参数(本金, 年利率, 年数):
            pass

        def 逐年计算(本金, 年利率, 年数):
            pass

        def 打印汇总(本金, 最终金额, 年数):
            pass

        def 主程序():
            打印标题()
            打印参数(10000, 0.03, 5)
            最终金额 = 逐年计算(10000, 0.03, 5)
            打印汇总(10000, 最终金额, 5)

        主程序()

    ── 现在就运行 ──

        程序能跑，什么都不输出。**这是对的** ——
        骨架阶段本来就不该有输出。

        但它证明了「主流程的逻辑是通的」：
        五个步骤的顺序对不对？谁依赖谁？`最终金额` 从哪来？

        这些问题在骨架阶段就能发现，不用等写完 100 行才看到。

    ── 为什么用 pass ──

        L3 第 1 课讲过：pass 是「什么都不做」的占位符。

        有了它，函数是「合法的空壳」，程序能运行。
        你可以先搭好整体结构，再一个个填。

────────────────────────────────────────────────────────
【第三步：一个个填】
────────────────────────────────────────────────────────

    从最简单的开始：

        def 打印标题():
            print("=" * 32)
            print("存款计划".center(30))
            print("=" * 32)

        def 打印参数(本金, 年利率, 年数):
            print(f"本金：      {本金:>10,.2f} 元")
            print(f"年利率：    {年利率 * 100:>9.1f}%")
            print(f"年限：      {年数:>10} 年")
            print("-" * 32)

    再填计算部分：

        def 逐年计算(本金, 年利率, 年数):
            金额 = 本金
            for 年 in range(1, 年数 + 1):
                金额 = 金额 * (1 + 年利率)
                print(f"第 {年:>2} 年：  {金额:>12,.2f} 元")
             return 金额

    最后是汇总：

        def 打印汇总(本金, 最终金额, 年数):
            利息 = 最终金额 - 本金
            print("-" * 32)
            print(f"总利息：    {利息:>10,.2f} 元")
            print(f"平均每年：  {利息 / 年数:>10,.2f} 元")
            print("=" * 32)

    ── 每填完一个就运行一次 ──

        填了 `打印标题` 就运行：
            标题对了，其他还是空的 → 继续

        填了 `逐年计算` 再运行：
            数字对不对？手算一年验证一下 → 对，继续

        这样每一步都是「小步验证」，
        出问题时你知道「刚才只改了这一块」。

────────────────────────────────────────────────────────
【自顶向下的四个好处】
────────────────────────────────────────────────────────

    ── ① 先想清楚结构，再想细节 ──

        写骨架的时候你在想「流程分几步」，
        填函数的时候你在想「这一步怎么算」。

        两件事分开想，脑子不打架。

        反过来（从头往下写），你会一边想着 print 的格式，
        一边想着利率怎么算 —— 两件事互相干扰。

    ── ② 能随时运行 ──

        骨架能跑，填一半能跑，全填完能跑。

        **永远有一个「能跑的版本」**，这让人安心，
        也让你随时能退回去。

    ── ③ 需求变化时，改一处 ──

        如果想加一个「按季度计算」的选项：

            在主流程里加一行：
                逐年计算(本金, 年利率, 年数)
                按季计算(本金, 年利率, 年数)      ← 新函数

            原来的代码一行都不用动。

    ── ④ 函数名就是文档 ──

        光看 主程序() 那 5 行，你就知道整个程序在干什么：

            打印标题()
            打印参数(...)
            最终金额 = 逐年计算(...)
            打印汇总(...)

        **不用读 100 行代码，读 5 行就够了。**

────────────────────────────────────────────────────────
【拆不拆？拆到什么程度？】
────────────────────────────────────────────────────────

    ── 该拆 ──

        ① 有不同的「阶段」（准备 → 计算 → 输出）
        ② 有一段代码重复出现
        ③ 某个操作需要单独验证（比如「这个公式对不对」）
        ④ 你写了个注释分段（`# 下面开始算利息`）

    ── 别拆过头 ──

        拆成这样就过了：

            def 打印等号():
                print("=")

            def 打印三十个等号():
                重复(30, 打印等号)

        三层函数只为打一行等号，读代码要跳三次。

        **拆分的目的是「让每块有名字」，不是「让每块尽量小」。**

    ── 一个实用的尺度 ──

        每个函数 5~20 行，能在一屏里读完，名字能说清它在干什么。

        低于 5 行的往往不值得单独拆（除非它会重复用）。
        超过 20 行的往往该再看看能不能分。

────────────────────────────────────────────────────────
【一个心态问题】
────────────────────────────────────────────────────────

    很多人不敢先写空函数，觉得「还没想清楚怎么写，怎么能先定名字」。

    事实相反：

        **定名字的过程，就是逼你想清楚「这一步到底要做什么」。**

        如果你写不出 `逐年计算(本金, 年利率, 年数)` 这个名字，
        说明你还没想明白这一步需要什么、产出什么。

        写不出来，就先写，写着写着就清楚了 ——
        名字可以改，结构可以调，但空着不动，永远不清楚。
'''

