r'''
════════════════════════════════════════════════════════
  L3 · 第 5 课 · 用法 3        调试
════════════════════════════════════════════════════════

写代码一定会出错。这一节讲：**出错了怎么办。**

────────────────────────────────────────────────────────
【第一件事：读报错信息】
────────────────────────────────────────────────────────

    大部分人看到一屏红字就慌，其实报错信息是**最好的线索**。

    ── 报错信息的结构 ──

        Traceback (most recent call last):
          File "test.py", line 5, in <module>
            结果 = 10 / 0
        ZeroDivisionError: division by zero

    三部分：

        ① `Traceback` 开始的那一段：调用链条
           从下往上看：最后发生错误的地方在最下面

        ② `File "..." line 5`：出错的文件和行号
           编辑器里点一下就跳过去了

        ③ 最后一行：错误类型 + 说明
           `ZeroDivisionError: division by zero`
           类型是 ZeroDivisionError，说明是「除以零」

    ── 看的时候从下往上看 ──

        最后一行告诉你「什么错」，
        往上几行告诉你「在哪错」。

        多层函数调用时 Traceback 会很长：

            File "test.py", line 12, in <module>
                f()
            File "test.py", line 8, in f
                g()
            File "test.py", line 4, in g
                结果 = 10 / 0

        读法：main 里第 12 行调了 f，f 里第 8 行调了 g，
              g 里第 4 行出错。

        **最终的错在最后，起因在最上面。** 两个都要看。

────────────────────────────────────────────────────────
【常见错误类型速查】
────────────────────────────────────────────────────────

    ── SyntaxError（语法错误）──

        代码根本没开始运行就报了。

            print("hello"        → 括号没闭合
            if x = 5:            → 用了 = 而不是 ==
            def f()              → 少了冒号

        报错里会有个小箭头指着位置：

            print("hello"
                 ^
            SyntaxError: '(' was never closed

    ── IndentationError（缩进错误）──

            def f():
            print("hi")

            IndentationError: expected an indented block

        缩进不对。也可能是空格和 Tab 混用（TabError）。

    ── NameError（名字不存在）──

            print(变量)

            NameError: name '变量' is not defined

        三种常见原因：
            · 拼错了
            · 变量在别的作用域（函数里定义的，外面用不了）
            · 用在了赋值之前

    ── TypeError（类型不对）──

            "3" + 5

            TypeError: can only concatenate str (not "int") to str

        类型不匹配。注意：参数个数不对也是 TypeError。

    ── ValueError（值不对）──

            int("abc")

            ValueError: invalid literal for int() with base 10: 'abc'

        类型对（是字符串），但内容转不了。

    ── ZeroDivisionError（除以零）──

            10 / 0

    ── IndexError（下标越界）──

        取的位置超出了范围（L4 讲列表时会常遇到）。

    ── AttributeError（属性不存在）──

            123.upper()

            AttributeError: 'int' object has no attribute 'upper'

        数字没有 upper 方法。通常是「以为它是字符串，其实不是」。

    ── RecursionError（递归太深）──

        L3 第 4 课讲过。

    ──────────────────────────────────────────────────

    **区分 TypeError 和 ValueError：**

        TypeError    → 类型不对（"abc" + 5）
        ValueError   → 类型对，但值不行（int("abc")）

        这两个经常混。记一句话：
        **「类型不对」是 TypeError，「内容不对」是 ValueError。**

────────────────────────────────────────────────────────
【第二件事：print 调试法】
════════════════════════════════════════════════════════

    最古老、最有效、不需要任何工具的调试方法：

        **在你怀疑的地方，把变量打印出来。**

    ── 例子 ──

        这段代码应该输出 6，但输出了 5：

            def 算平均(a, b, c):
                总 = a + b + c
                平均 = 总 / 3
                return 平均

            print(算平均(1, 2, 3))

        （实际会输出 2.0，这里假设它出错了）

        加 print：

            def 算平均(a, b, c):
                print("  [调试] a, b, c =", a, b, c)
                总 = a + b + c
                print("  [调试] 总 =", 总)
                平均 = 总 / 3
                print("  [调试] 平均 =", 平均)
                return 平均

        一跑就知道哪一步不对。

    ── 三个技巧 ──

        ① 加标记 `[调试]`，方便事后删干净
           搜索 `[调试]` 就能全找到。

        ② 把变量名一起打出来
               print(x)              → 5
               print("x =", x)       → x = 5

           前者看输出时要想「这是哪个变量」。

        ③ 打印类型
               print("x =", x, type(x))

           很多 bug 是「以为是数字，其实是字符串」。

    ── 调试完记得删 ──

        留在代码里的调试 print 会让输出一团糟。
        养成习惯：**找到 bug 就删，别等「以后一起删」。**

────────────────────────────────────────────────────────
【第三件事：二分法找 bug】
────────────────────────────────────────────────────────

    代码很长，不知道哪一段出错？

    **在中间插一个 print，看它对不对。对 → 错在后面；不对 → 错在前面。**

    假设 100 行的程序，第 60 行附近的输出不对：

        ① 在第 50 行插 print
           输出正常 → 前 50 行没问题，错在 50~100
           输出不对 → 错在 1~50

        ② 缩小范围后，再在中间插
           50~100 的中间是 75……

        100 行 → 50 → 25 → 12 → 6 → 3 → 1，
        7 次就能定位到具体哪一行。

    这比「从第 1 行开始一行行看」快得多。

    ── 前提 ──

        你要知道「正常应该是什么样」。
        所以调试前先想清楚：这个变量在这时候应该等于几？

────────────────────────────────────────────────────────
【第四件事：assert 断言】
────────────────────────────────────────────────────────

    assert 是「我确信这里是这个值，如果不是就停下」。

        金额 = 100 * 3
        assert 金额 == 300
        print("继续执行")

    如果 金额 不是 300，程序立刻停：

        AssertionError

    还可以带说明：

        assert 金额 > 0, f"金额不该是负数，现在是 {金额}"

    报错时会显示：

        AssertionError: 金额不该是负数，现在是 -50

    ── assert 和 if 的区别 ──

        if 是「程序逻辑的一部分」，条件不成立也继续跑（走 else 分支）。

        assert 是「检查我的假设」，假设破了，程序没有意义继续跑，
        所以直接停。

    ── 什么时候用 ──

        ① 函数入口检查参数
               def 算平均(*数字):
                   assert len(数字) > 0, "至少给一个数"
                   ...

        ② 写测试
               assert 加(1, 2) == 3
               assert 加(0, 0) == 0
               assert 加(-1, 1) == 0
               print("全部通过")

           这三行就是最简单的「单元测试」。

        ③ 怀疑某个值不对时
               在函数中间插一个 assert，比 print 更明确：
               它不但会告诉你「值不对」，还能告诉你「从哪开始不对」。

    ── 注意 ──

        assert 在「优化模式」下会被跳过（python -O 运行时）。
        所以**不要用 assert 做真正的错误处理**（比如检查用户输入）。
        它的定位是「开发者自己检查代码逻辑」。

────────────────────────────────────────────────────────
【第五件事：让函数好调试】
────────────────────────────────────────────────────────

    有些函数天生难调试，有些天生好调。区别在于设计。

    ── 难调试的 ──

        def 算(a, b):
            print("开始")
            结果 = a * 2
            print("中间", 结果)
            结果 = 结果 + b
            print("结束", 结果)
            return 结果

        问题：每调一次打一堆东西，想看清中间值反而被淹没。

    ── 好调试的 ──

        def 算(a, b):
            return a * 2 + b

        原因：
            · 短 —— 一眼看完
            · 纯 —— 不打印、不改外部状态
            · 能单独测 —— `算(3, 4)` 直接验证

        这个函数如果算错了，你只要测几组输入就知道规律。

    ── 所以 ──

        **「函数拆得小、职责单一」本身就是最好的调试手段。**
        L3 第 5 课第 2 节讲的拆分，不只是为了好看。

        L3 第 1 课讲的「print 和 return 分开」也是同一个道理：
        只 return 不 print 的函数，可以在任何地方被单独测试。

────────────────────────────────────────────────────────
【一个调试的顺序】
────────────────────────────────────────────────────────

    遇到 bug，按这个顺序走：

        ① 读报错最后一行 —— 什么错？
        ② 看报错的行号 —— 在哪？
        ③ 看那一行的变量是什么类型、什么值（print 或 assert）
        ④ 往前找「这个值是怎么变成现在这样的」
        ⑤ 实在找不到 —— 二分法插 print
        ⑥ 找到后：改完再跑一遍，确认真的好了
        ⑦ 想一想：有没有别的地方也可能有同样的问题
'''

