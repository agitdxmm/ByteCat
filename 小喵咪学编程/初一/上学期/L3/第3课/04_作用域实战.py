r'''
════════════════════════════════════════════════════════
  L3 · 第 3 课 · 用法 4        作用域实战
════════════════════════════════════════════════════════

前三节讲了规则。这一节讲：**遇到真问题时，该选哪种方案。**

────────────────────────────────────────────────────────
【一个需求，四种写法】
────────────────────────────────────────────────────────

    需求：记录一个游戏分数，每次击杀加 100 分。

    ── 写法一：全局变量 ──

        分数 = 0

        def 击杀():
            global 分数
            分数 = 分数 + 100
            return 分数

        击杀()      → 100
        击杀()      → 200

        优点：调用处最短，一个 `击杀()` 就完事
        缺点：只能有一个玩家；谁都能改；函数不能独立用

    ── 写法二：参数 + 返回值 ──

        def 击杀(当前分数):
            return 当前分数 + 100

        分数 = 0
        分数 = 击杀(分数)
        分数 = 击杀(分数)

        优点：纯函数，易测易复用；可以有很多个玩家的分数
        缺点：调用处要写 `分数 = 击杀(分数)`

    ── 写法三：闭包 ──

        def 造玩家():
            分数 = 0

            def 击杀():
                nonlocal 分数
                分数 = 分数 + 100
                return 分数

            return 击杀

        甲 = 造玩家()
        乙 = 造玩家()
        甲()        → 100
        甲()        → 200
        乙()        → 100      ← 独立

        优点：调用处短，且可以有多个独立状态
        缺点：状态藏起来了，外部看不到「现在多少分」，只能通过调用拿到

    ── 写法四：把分数放在一个「容器」里 ──

        这一步要等 L4（字典）或者 L6（类）。
        先知道有这么个方向：把「分数 + 相关操作」打包在一起。

    ── 怎么选 ──

        ┌──────────────┬──────────────────────────────────┐
        │ 只有一份状态 │ 全局变量可以，但闭包更干净       │
        │ 有多份状态   │ 参数版 或 闭包                   │
        │ 要能随时查看 │ 参数版（状态在明面上）           │
        │ 要给别处用   │ 参数版（函数不携带着状态）       │
        └──────────────┴──────────────────────────────────┘

    我的建议：**默认写参数版。**
    它的缺点（调用处啰嗦）是看得见的；
    全局和闭包的缺点（状态藏在暗处）是查不出来的。

────────────────────────────────────────────────────────
【坑：循环变量会留在作用域里】
────────────────────────────────────────────────────────

    L2 第 4 课讲过 for 循环，当时没提这一点：

        for i in range(3):
            print("循环里", i)

        print("循环外", i)

    输出：

        循环里 0
        循环里 1
        循环里 2
        循环外 2

    循环结束后 i 还在，值是最后一轮的值。

    ── 什么时候会炸 ──

        ① 循环后还以为 i 是「没用过」的：

            for i in range(5):
                ...
            # 很久之后
            for j in range(i):      ← 你以为 i 有什么值？其实是 4
                ...

        ② 循环之前的变量被覆盖：

            i = 100
            for i in range(3):
                ...
            print(i)               → 2，不是 100

        ③ 嵌套循环用同一个变量名：

            for i in range(3):
                for i in range(3):      ← 外层 i 被内层覆盖了
                    ...
                print(i)                ← 永远是 2，不是 0 1 2

            **这个最坑 —— 程序能跑，外层也确实转了三圈，
            但每圈结束时 i 都被内层改成了 2。**
            外层如果还要用 i 判断什么，全部失效。

    ── 怎么避免 ──

        · 循环变量用短名字（i、j、k），且只用在循环里
        · 嵌套循环用不同的变量名（外层 i，内层 j）
        · 循环结束后不要再指望这个变量的值

    ── `_` 的用法 ──

        如果你不需要循环变量的值：

            for _ in range(5):
                print("跑五次")

        `_` 是约定，表示「这个值我不关心」。
        它照样会留在作用域里，但至少不会和你有用的变量重名。

────────────────────────────────────────────────────────
【坑：同名变量让 bug 藏得很深】
────────────────────────────────────────────────────────

    看这段：

        x = 10

        def 处理(x):
            x = x + 1
            return x

        print(处理(x))
        print(x)

    输出 11 和 10。

    完全正确，但读代码的人要花几秒才能确认「外面的 x 没被改」。

    如果参数换个名字：

        x = 10

        def 处理(数值):
            数值 = 数值 + 1
            return 数值

    一眼就清楚。

    ── 建议 ──

        **参数名和外部变量名，尽量别一样。**

        除了「故意要传这个变量」的情况，同名的唯一作用就是让人困惑。

────────────────────────────────────────────────────────
【工具：看看作用域里到底有什么】
────────────────────────────────────────────────────────

    Python 有两个内置函数能帮你看清：

        locals()     当前作用域里的所有局部名字
        globals()    模块级（全局）的所有名字

    例：

        def f():
            a = 1
            b = "hello"
            print(locals())

        f()
        → {'a': 1, 'b': 'hello'}

    在模块级调用 `locals()`，会看到一大堆东西 ——
    包括你自己定义的变量、函数、导入的模块，还有 Python 自动加的
    `__name__`、`__doc__` 之类。

    ── 这有什么用来着 ──

        调试的时候，怀疑「这个变量到底有没有被赋值」，
        打印一下 locals().keys() 就知道了。

        比一个个 print 快。

    ── 注意 ──

        `locals()` 返回的东西最好不要去改它。
        它就是让你**看**的，不是让你**操作**的。

        想改值，直接写赋值语句。

────────────────────────────────────────────────────────
【一张速查表】
────────────────────────────────────────────────────────

    想在函数里……

        · 用外部变量的值
          → 直接读，什么都不用写

        · 改外部变量的值
          → 优先：把它当参数传进来，返回新值
          → 其次：闭包 + nonlocal（同一层嵌套内）
          → 最后：global（真的全程序只有一份时）

        · 保存「只有这个函数知道」的状态
          → 闭包 + nonlocal

        · 每次调用都从干净状态开始
          → 局部变量（默认行为）

    ── 最后再强调一次 ──

        **函数最好只依赖参数，只影响返回值。**
        这样的函数：看得懂、测得动、搬得走、不会互相干扰。

        需要状态的时候，让调用方保存，别藏在函数里。
'''

