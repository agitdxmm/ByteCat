r'''
════════════════════════════════════════════════════════
  L3 · 第 3 课 · 用法 1        局部变量
════════════════════════════════════════════════════════

到目前为止，我们写的变量都是「全局」的 —— 写在最外层，
整段程序哪儿都能用。

但函数里面的变量不一样。这一节讲清楚它们的规矩。

────────────────────────────────────────────────────────
【一句话：函数里造的变量，出了函数就没了】
────────────────────────────────────────────────────────

    def 演示():
        x = 100
        print("函数里：x =", x)

    演示()
    print(x)

    输出：

        函数里：x = 100
        NameError: name 'x' is not defined

    函数里那一行能打印，因为那时 x 还活着。
    函数一结束，x 立刻消失，外面根本不知道有过这个东西。

    ── 这类变量叫「局部变量」 ──

        「局部」= 只在一个小范围内存在。
        这个范围就是**函数体内部**。

    ── 为什么 Python 要这样设计 ──

        想象一下不这样会怎样：

            如果函数里所有变量都是全局的，
            你写一个函数用了 x，别人写的函数也用了 x，
            两边就会互相干扰。

        真实项目里可能有几百个函数。
        局部变量让每个函数可以「自己用自己的名字」，互不打架。

    ── 生活类比 ──

        全局变量 = 客厅里的东西，全家共用
        局部变量 = 你房间里抽屉的东西，只有你打开房间才在

        你房间的「笔记本」和客厅的「笔记本」可以是两个东西。

────────────────────────────────────────────────────────
【同名不冲突】
────────────────────────────────────────────────────────

    x = "外面的"

    def 甲():
        x = "甲里面的"
        print("甲里：", x)

    def 乙():
        x = "乙里面的"
        print("乙里：", x)

    甲()
    乙()
    print("外面：", x)

    输出：

        甲里： 甲里面的
        乙里： 乙里面的
        外面： 外面的

    三个 x，互不相干。

        外面的 x    → 模块级变量
        甲里的 x    → 甲的局部变量（甲一结束就没了）
        乙里的 x    → 乙的局部变量（乙一结束就没了）

    在函数里写 `x = ...`，Python 就认为「我要造一个新的局部变量」，
    不会去动外面的那个。

────────────────────────────────────────────────────────
【每次调用都是全新的】
────────────────────────────────────────────────────────

    def 计数():
        n = 0
        n += 1
        print(n)

    计数()      → 1
    计数()      → 1
    计数()      → 1

    每次都是 1，不会累加。

    ── 为什么 ──

        每次调用 计数()，Python 都新建一份「局部变量表」，
        里面 n = 0，然后加一，打印 1，函数结束，整张表扔掉。

        下次调用又从一张新的空表开始。

    ── 这个特性很重要 ──

        它意味着**函数不会记住上一次调用的事**（除非你用了全局变量、
        默认参数陷阱、或者闭包）。

        大多数时候这是好事：函数是「可重复的」，
        给同样的输入永远出同样的结果。

        如果想让函数记住点什么，有几种办法（这一课后面会讲）：

            · 用全局变量（第 2 节）
            · 用可变默认值（这个是坑，第 2 课讲过）
            · 用闭包（第 3 节）
            · 用「返回值 + 调用方保存」（推荐）

────────────────────────────────────────────────────────
【参数也是局部变量】
────────────────────────────────────────────────────────

    def 打招呼(名字):
        print("你好，" + 名字)

    名字 是参数，它和 函数体里 `x = ...` 造的变量，地位完全一样：

        · 只在函数内部存在
        · 函数结束就消失
        · 和外面的同名变量互不干扰

    所以「参数」本质上就是「调用时自动赋值的局部变量」——
    这句话 L3 第 1 课讲过，现在你知道了它为什么重要。

────────────────────────────────────────────────────────
【局部变量的寿命】
────────────────────────────────────────────────────────

    def 甲():
        x = 1
        return x        ← 函数结束，x 死

    def 乙():
        print(x)        ← 这里访问不到甲的 x

    每个函数的局部变量是**独立的房间**，甲房间的东西乙看不到。

    ── 更准确的说法 ──

        局部变量的寿命 = 从「被赋值那一刻」到「函数执行结束」。
        函数返回后，这些变量会被回收。

        所以：

            def f():
                print(y)      ← NameError，因为 y 还没被赋值
                y = 1

        注意这里不是「函数外部的问题」，是「顺序的问题」：
        print(y) 执行时 y 还不存在。

────────────────────────────────────────────────────────
【一个常见误解：以为函数里能随便改外面的变量】
────────────────────────────────────────────────────────

    x = 0

    def 改成一百():
        x = 100          ← 你以为改了外面的？没有
        print("函数里：", x)

    改成一百()
    print("函数外：", x)

    输出：

        函数里： 100
        函数外： 0

    `x = 100` 这一行在函数里，Python 就认定
    「这是要造一个新的局部变量 x」，于是外面那个完全没动。

    ── 那怎么才能真的改外面的？ ──

        要用 global 关键字。这是下一节的内容。

    ── 但这可能是件好事 ──

        「函数改了外面的变量」往往意味着 bug。
        不知道谁在什么时候改了什么，是调试噩梦的开始。

        Python 默认不让你改，是在保护你。

────────────────────────────────────────────────────────
【一个容易看错的地方】
────────────────────────────────────────────────────────

    函数内部**没有赋值**的变量，Python 会去外面找：

        x = "外面的"

        def 读一下():
            print(x)        ← 没有赋值，所以去找全局的

        读一下()            → 外面的

    但函数内部**有赋值**的变量，Python 只认局部的：

        x = "外面的"

        def 想读又赋值():
            print(x)        ← 报错！
            x = "新的"

        想读又赋值()
        → UnboundLocalError: cannot access local variable 'x'
          where it is not associated with a value

    ── 为什么这么怪 ──

        因为 Python 在**编译这个函数时**（还没执行）就扫了一遍，
        发现函数体里有 `x = ...`，于是把 x 登记成局部变量。

        等到执行 `print(x)` 时，局部变量 x 还没被赋值 ——
        它不会退回去找全局的那个，只会报错。

    ── 这个报错的名字是 UnboundLocalError ──

        看到这个词就知道：
        **「你在这个函数里给某个名字赋过值，但又想读它，而读的时候它还没值。」**

    ── 记住这条规则 ──

        一个名字在函数里**只要出现过赋值**，它就是局部变量，
        整个函数里都算局部的，从头到尾。

    这条规则违反了直觉，但它是 Python 的硬规定。
'''

