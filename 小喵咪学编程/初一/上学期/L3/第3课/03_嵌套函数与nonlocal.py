r'''
════════════════════════════════════════════════════════
  L3 · 第 3 课 · 用法 3        嵌套函数与 nonlocal
════════════════════════════════════════════════════════

函数里面还能定义函数。这事听起来奇怪，但用了会上瘾。

────────────────────────────────────────────────────────
【形状：函数里套函数】
────────────────────────────────────────────────────────

    def 外层():
        print("外层的开头")

        def 内层():
            print("  内层被执行了")

        内层()
        print("外层的结尾")

    外层()

    输出：

        外层的开头
          内层被执行了
        外层的结尾

    ── 三条规矩 ──

        ① `def 内层()` 写在 外层 的函数体里（要缩进）
        ② 内层函数也得先定义、后调用
        ③ 外层 不调用的话，内层根本不会被创建

    ── 那内层能不能从外面直接调？ ──

        不能。

            内层()
            → NameError: name '内层' is not defined

        内层 是 外层 的局部名字，和局部变量一个道理 ——
        出了 外层 就没了。

────────────────────────────────────────────────────────
【内层能看见外层的变量】
────────────────────────────────────────────────────────

    def 外层():
        问候 = "你好"

        def 内层():
            print(问候)         ← 能读到外层的 问候

        内层()

    外层()                      → 你好

    为什么能：内层在 外层 里面，外层的东西它都看得见。
    这就是「作用域」的方向：**里面能看到外面，外面看不到里面。**

    ── 但只能读，不能改 ──

        def 外层():
            计数 = 0

            def 内层():
                计数 = 100      ← 造了一个内层自己的局部变量
                print("内层：", 计数)

            内层()
            print("外层：", 计数)

        外层()

        输出：

            内层： 100
            外层： 0

    和「函数改全局变量」完全一样的规则：
    **只要有赋值，就造新的局部变量。**

    想改外层的，得用 nonlocal。

────────────────────────────────────────────────────────
【nonlocal：我要改外面那层的变量】
────────────────────────────────────────────────────────

    def 外层():
        计数 = 0

        def 内层():
            nonlocal 计数
            计数 = 计数 + 1
            print("内层：", 计数)

        内层()
        内层()
        print("外层：", 计数)

    外层()

    输出：

        内层： 1
        内层： 2
        外层： 2

    ── nonlocal 和 global 的区别 ──

        global     → 指向**模块级**（最外层）的变量
        nonlocal   → 指向**最近的一层外层函数**的变量

    ── nonlocal 的限制 ──

        ① 只能用在嵌套函数里（不在函数里写 nonlocal 会报错）
        ② 指向的那个变量必须**已经存在**
        ③ 不能指向模块级的变量（那是 global 的活）

        ❌ def f():
               nonlocal x        ← SyntaxError: no binding for nonlocal 'x'

           （f 外面没有函数，也就没有「外层函数变量」）

    ── 找不到会报什么 ──

            def 外():
                def 内():
                    nonlocal 不存在
                    不存在 = 1
                内()
            外()

        → SyntaxError: no binding for nonlocal '不存在' found

        注意这是**语法错误**，编译时就报了，程序根本不会开始运行。

────────────────────────────────────────────────────────
【真正的威力：函数可以返回函数】
────────────────────────────────────────────────────────

    这是嵌套函数最有用的地方。

        def 乘以(n):
            def 内层(x):
                return x * n
            return 内层

    注意 `return 内层` —— 返回的是**函数本身**，没有括号。
    所以不会调用它，只是把它交出去。

    用起来：

        乘2 = 乘以(2)
        乘3 = 乘以(3)

        print(乘2(10))      → 20
        print(乘3(10))      → 30

    ── 发生了什么 ──

        ① `乘以(2)` 执行：n = 2，创建了 内层 这个函数，返回它
        ② 乘2 现在就是那个「内层」，它记住了 n = 2
        ③ `乘2(10)` 就是 `内层(10)`，返回 10 * 2 = 20

    ── 奇怪的地方 ──

        乘以 早就执行完了，n 应该消失了吧？

        没有。因为 内层 还在用它，Python 就把 n 保留了下来。

        这个「函数 + 它记住的外层变量」的组合，叫**闭包**（closure）。

    ── 更直观的例子：造计数器 ──

        def 造计数器():
            计数 = 0

            def 加一():
                nonlocal 计数
                计数 = 计数 + 1
                return 计数

            return 加一

        计时器 = 造计数器()
        print(计时器())      → 1
        print(计时器())      → 2
        print(计时器())      → 3

    现在「计数」这个状态藏在闭包里，外面碰不到它。

    ── 想要两个独立计数器？再造一个 ──

        甲 = 造计数器()
        乙 = 造计数器()
        甲()        → 1
        甲()        → 2
        乙()        → 1        ← 乙是独立的
        甲()        → 3

    这就是 global 做不到的事：
    **同样的逻辑，可以有任意多份独立的状态。**

────────────────────────────────────────────────────────
【作用域查找顺序：LEGB】
────────────────────────────────────────────────────────

    一个名字找不到时，Python 按这个顺序往上找：

        L  Local      当前函数的局部变量
        E  Enclosing  外层函数的变量（嵌套时才有）
        G  Global     模块级变量
        B  Built-in   内置的（print、len、range 这些）

    找到就停，找不到就 NameError。

    ── 例子 ──

        x = "全局"

        def 外():
            x = "外层"

            def 内():
                print(x)        ← 内层没有 x，去外层找，找到 "外层"

            内()

        外()                    → 外层

    注意：它**不会**再往上找到全局的 "全局"，
    因为在外层就已经找到了。

    ── 想跳过外层直接要全局的？ ──

        在内层写 `global x`。但这样很绕，没人这么写。

    ── 实践建议 ──

        不要起同名变量。三层（内层、外层、全局）都有 x 的时候，
        读代码的人得在脑子里跑一遍 LEGB，太累。

        名字起得不一样，这种问题就不存在。

────────────────────────────────────────────────────────
【该不该用嵌套函数】
────────────────────────────────────────────────────────

    ── 适合 ──

        ① 内层函数只给外层用，外面不该碰
           这比在模块级定义一堆函数、再靠命名约定「这是内部的」干净多了。

        ② 需要「记住某个值」的函数（闭包）
           像上面的 乘2、乘3、计数器。

        ③ 函数太长，想把内部逻辑分块
           但又不想让这些块暴露给外部。

    ── 不适合 ──

        ① 内层超过 15 行
           外层函数会变得难以阅读，不如提出来单独定义。

        ② 嵌套超过两层
           三层的 LEGB 查起来很痛苦。

        ③ 只是为了少写几个参数
           用参数传更直接。
'''

