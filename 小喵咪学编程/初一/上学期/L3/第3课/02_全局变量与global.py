r'''
════════════════════════════════════════════════════════
  L3 · 第 3 课 · 用法 2        全局变量与 global
════════════════════════════════════════════════════════

上一节说了：函数里赋值会造局部变量，改不到外面的。

那如果真的要改外面的呢？用 global。

但先说结论：**能不用就别用。** 这一节讲清楚为什么。

────────────────────────────────────────────────────────
【什么是全局变量】
────────────────────────────────────────────────────────

    写在最外层（不在任何函数里）的变量，就是全局变量：

        班级 = "初一(3)班"

        def 打印班级():
            print(班级)      ← 能读到

        打印班级()          → 初一(3)班

    整个文件里所有函数都能看到它。

    ── 更准确的说法 ──

        全局变量存在「模块」这一层。
        一个 .py 文件就是一个模块，模块级的变量就是全局的。

        （如果程序分了多个文件，每个文件有自己的一套全局变量。
          跨文件用要 import，那是后面的事。）

────────────────────────────────────────────────────────
【函数里能读，不能改】
────────────────────────────────────────────────────────

    ── 读：完全没问题 ──

        税率 = 0.13

        def 算税(金额):
            return 金额 * 税率      ← 读全局，随便读

        算税(1000)                  → 130.0

    ── 改：改不动（其实是改的是另一个变量） ──

        税率 = 0.13

        def 改税率():
            税率 = 0.09            ← 这行造了一个局部变量
            print("函数里：", 税率)

        改税率()                    → 函数里： 0.09
        print("函数外：", 税率)      → 函数外： 0.13

    函数里那句 `税率 = 0.09`，Python 的理解是：
    「在这个函数里新建一个叫 税率 的局部变量。」

    它和外面的 税率 一点关系都没有。

    ── 所以你经常会遇到这种困惑 ──

        「我在函数里明明改了，怎么外面没变？」

        就是这个原因。不是 bug，是规则。

────────────────────────────────────────────────────────
【global 声明：告诉 Python「我要改那个全局的」】
────────────────────────────────────────────────────────

    写法：

        税率 = 0.13

        def 改税率():
            global 税率             ← 声明这一句
            税率 = 0.09
            print("函数里：", 税率)

        改税率()                    → 函数里： 0.09
        print("函数外：", 税率)      → 函数外： 0.09     ← 改了！

    ── global 做了什么 ──

        它告诉 Python：「这个函数里的 税率，指的就是全局那个，
        不要新建局部变量。」

        于是赋值就落在全局变量上了。

    ── 位置很关键 ──

        global 必须写在**使用这个名字之前**：

            ✅ def f():
                   global x
                   x = 1

            ❌ def f():
                   x = 1
                   global x         ← SyntaxError
                                       name 'x' is assigned to before
                                       global declaration

        Python 的要求是：在函数里第一次碰到 x 之前就得声明好。

    ── 只读的话不需要 global ──

        def 打印():
            print(税率)             ← 不需要 global

        global 只在「要赋值」时才需要。

    ── 多个变量可以一起声明 ──

        global 甲, 乙, 丙

────────────────────────────────────────────────────────
【为什么要慎用 global】
────────────────────────────────────────────────────────

    先看一个「能跑但很危险」的例子：

        总分 = 0

        def 加分(分):
            global 总分
            总分 = 总分 + 分
            return 总分

        加分(10)        → 10
        加分(20)        → 30
        加分(5)         → 35

    能用。但问题来了：

    ── 问题一：谁都能改 ──

        程序里任何一个函数，只要写一句 `global 总分`，
        就能改这个值。

        某天你在 2000 行的地方发现总分不对，要去哪找？
        得搜遍整个文件里所有写 `总分 =` 的地方。

    ── 问题二：只有一个 ──

        如果程序需要统计两个班的总分呢？

            总分 = 0            ← 一个
            def 加分(分): ...
            def 加分2(分): ...  ← 得复制一整套，包括全局变量

        全局变量没法「来两份」。

    ── 问题三：函数不能单独用了 ──

        加分(10) 这个调用，看起来是「给 10，返回结果」。
        但它偷偷依赖外面的 总分 现在是多少。

        同样的调用，在不同时刻结果不同：

            总分 = 0
            加分(10)        → 10

            总分 = 100
            加分(10)        → 110

        **同样的输入，不同的输出。** 这种函数最难测、最难懂。

    ── 问题四：顺序变得要命 ──

        加分(10) 写在 `总分 = 0` 之前会怎样？

            NameError: name '总分' is not defined

        所以你还得记住「哪些初始化必须写在哪些调用之前」。
        代码一长，这就不只是麻烦了。

────────────────────────────────────────────────────────
【更好的做法：把状态交出去】
────────────────────────────────────────────────────────

    不用 global 的版本：

        def 加分(当前总分, 分):
            return 当前总分 + 分

    调用：

        总分 = 0
        总分 = 加分(总分, 10)      → 10
        总分 = 加分(总分, 20)      → 30
        总分 = 加分(总分, 5)       → 35

    ── 好在哪 ──

        ① 函数纯粹：给 (0, 10) 永远返回 10
        ② 状态在调用方手里，谁改的、什么时候改的，全在明面上
        ③ 想要第二个总分？再写个变量就行：

               甲班总分 = 0
               乙班总分 = 0
               甲班总分 = 加分(甲班总分, 10)
               乙班总分 = 加分(乙班总分, 20)

        ④ 函数可以复制到别的项目里直接用

    ── 这个写法有个小缺点 ──

        调用方要写两遍 `总分 =`：

            总分 = 加分(总分, 10)

        有点啰嗦。但换来的是「一眼能看出状态在变」——
        这个代价很值。

────────────────────────────────────────────────────────
【什么时候真的该用 global】
────────────────────────────────────────────────────────

    也不是完全不能用。这几种情况合理：

    ── ① 常量 ──

        其实常量根本不需要 global（只读不写）：

            最大重试次数 = 3
            def 重试(函数):
                for i in range(最大重试次数):
                    ...

    ── ② 程序的全局配置，启动时读一次，之后只读 ──

            DEBUG = True
            def 日志(信息):
                if DEBUG:
                    print("[调试]", 信息)

        只读，没问题。

    ── ③ 状态确实只有一个，且到处都要用 ──

        比如：当前登录的用户、程序的运行模式、数据库连接。

        这些用 global 合理，但要注意：
        · 只在一个地方初始化
        · 改它的地方越少越好
        · 起个明显的名字（比如全大写表示「这是全局配置」）

    ── 判断标准 ──

        **「这个值是不是全程序只有一份，而且很多地方都要读？」**
        是 → 可以全局。
        「是不是只有一两个函数在改它？」
        是 → 那不如让函数返回新值。

────────────────────────────────────────────────────────
【一个常被搞混的点：global 在函数里声明，不是在外面】
────────────────────────────────────────────────────────

    ❌ 错误理解：

            global x = 1         ← 这不是定义全局变量

        global 不是「定义」，是「声明」。
        你不能用 global 创建变量，只能用它说明「我指的那个已经存在的全局的」。

    ✅ 全局变量就是直接赋值：

            x = 1                ← 在模块级赋值，它自动就是全局的

    ✅ 然后在函数里声明要用它：

            def f():
                global x
                x = 2

    顺序：先在模块级创建，再在函数里 global 声明。
'''

