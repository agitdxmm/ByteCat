r'''
════════════════════════════════════════════════════════
  L3 · 第 4 课 · 用法 3        递归与循环
════════════════════════════════════════════════════════

同样一个问题，几乎总能用两种写法解决。

这一节把它们摆在一起，看清楚各自的形状、代价、适用场合。

────────────────────────────────────────────────────────
【对照表：四个问题的两种写法】
────────────────────────────────────────────────────────

    ── 阶乘 ──

        递归：
            def 阶乘(n):
                if n <= 1:
                    return 1
                return n * 阶乘(n - 1)

        循环：
            def 阶乘(n):
                结果 = 1
                for i in range(2, n + 1):
                    结果 = 结果 * i
                return 结果

    ── 从 1 加到 n ──

        递归：
            def 求和(n):
                if n == 1:
                    return 1
                return n + 求和(n - 1)

        循环：
            def 求和(n):
                总 = 0
                for i in range(1, n + 1):
                    总 = 总 + i
                return 总

    ── 各位数字之和 ──

        递归：
            def 各位和(n):
                if n < 10:
                    return n
                return n % 10 + 各位和(n // 10)

        循环：
            def 各位和(n):
                总 = 0
                while n > 0:
                    总 = 总 + n % 10
                    n = n // 10
                return 总

    ── 最大公约数（辗转相除）──

        递归：
            def 最大公约数(a, b):
                if b == 0:
                    return a
                return 最大公约数(b, a % b)

        循环：
            def 最大公约数(a, b):
                while b != 0:
                    a, b = b, a % b
                return a

    ──────────────────────────────────────────────────────

    看出来了吗：

        **递归版**：都是「if 终止 → return 小一号」
        **循环版**：都是「初始化 → 循环里更新 → 返回」

    结构上一一对应。

────────────────────────────────────────────────────────
【改写的三个套路】
────────────────────────────────────────────────────────

    ── 套路一：累加型（最常见）──

        递归：
            return n + 递归(n - 1)         ← 结果层层相加

        循环：
            结果 = 初始值
            for 每个: 结果 = 结果 + 这一项

        对应关系：
            递归的「return 时累加」 → 循环的「在循环体里累加」

        阶乘、求和、各位和都是这一类。

    ── 套路二：传递型 ──

        递归：
            def f(n, 累计):
                if 结束:
                    return 累计
                return f(n - 1, 累计 + n)    ← 结果往下传，不往上传

        循环：
            累计 = 初始值
            while 未结束:
                累计 = 累计 + n
                n = n - 1
            return 累计

        这种递归叫「尾递归」（递归调用是最后一步，不再参与运算）。
        改成循环最容易 —— 把参数变成变量就行。

    ── 套路三：需要「倒退」的 ──

        有些递归在回程做事：

            def 倒着打印(n):
                if n == 0:
                    return
                倒着打印(n - 1)     ← 先递归到最底层
                print(n)            ← 回来的时候才打印

            倒着打印(3)  → 1 2 3

        这种改成循环就绕了，得自己维护一个「待处理」的栈：

            待处理 = [3, 2, 1]      ← 需要列表，L4 讲

        或者用别的手段（比如先算出来再倒序）。

        **这类递归，硬改成循环往往更难读。**

────────────────────────────────────────────────────────
【速度对比：其实差不多】
────────────────────────────────────────────────────────

    很多人以为「递归慢」。

    实际上对于**没有重复子问题**的递归（阶乘、求和这些），
    递归和循环的速度差距不大 ——
    递归多的那点开销是「每次调用要压栈」。

    真正的差距在**重复计算**（上一节讲的斐波那契）。

    ── 举例（大概的量级）──

        阶乘(500)     递归约 0.1 毫秒，循环约 0.05 毫秒
        斐波那契(30)  递归约 0.2 秒，循环约 0.00002 秒

    所以：

        **「递归慢」这个说法不准确。**
        **「有重复子问题的递归慢」才准确。**

────────────────────────────────────────────────────────
【什么时候必须用递归】
────────────────────────────────────────────────────────

    有些问题的结构本身就是「自己包含自己」，循环写起来极其别扭：

        ── 树形结构 ──
            文件夹 → 子文件夹 → 子子文件夹
            网页 DOM → 子元素 → 子子元素

            递归：「总大小 = 本层的 + 每个子节点的总大小」
            循环：得自己维护一个「还有哪些没处理」的列表，而且
                  处理到第几层了要另外记

        ── 分治 ──
            归并排序、快速排序、二分查找
            思路是「把问题劈成两半，分别解决，再合并」
            递归天然对应这个思路

        ── 回溯 ──
            走迷宫、八皇后、数独
            「试一步，不行就退回来换一条」
            递归的「去程 + 回程」正好对应「前进 + 回退」

    这几种，用循环不是不能写，是写出来没人看得懂。

────────────────────────────────────────────────────────
【什么时候必须用循环】
────────────────────────────────────────────────────────

    ── 规模可能很大 ──

        递归深度受限于 1000 层左右。
        要处理 10 万个数据，递归必爆。

    ── 子问题大量重复 ──

        斐波那契那种，递归是指数级，循环是线性。

    ── 只是简单的累加 ──

        1 加到 10000，写递归纯属自找麻烦（还会爆）。

    ── 性能敏感的地方 ──

        循环没有函数调用开销，能省一点是一点。

────────────────────────────────────────────────────────
【一个实用的判断流程】
────────────────────────────────────────────────────────

    拿到一个问题，按顺序问：

        ① 数据结构是树形/嵌套的吗？
           是 → 递归

        ② 需要「试错 + 回退」吗？
           是 → 递归

        ③ 子问题会重复出现吗？
           是 → 循环（或者递归 + 缓存，L4 后再说）

        ④ 规模可能超过 1000 吗？
           是 → 循环

        ⑤ 以上都不是
           → 随便，哪个写起来短用哪个

    ── 最后一条很重要 ──

        不要为了「显得高级」用递归。
        也不要说「递归不好」就永远不用。

        工具而已，看场合。
'''

