print("① 阶乘：两种写法")


def 阶乘_递归(n):
    if n <= 1:
        return 1
    return n * 阶乘_递归(n - 1)


def 阶乘_循环(n):
    结果 = 1
    for i in range(2, n + 1):
        结果 = 结果 * i
    return 结果


for n in [1, 5, 10]:
    print(f"  {n}! 递归 = {阶乘_递归(n)}，循环 = {阶乘_循环(n)}")

print("\n② 各位和：两种写法")


def 各位和_递归(n):
    if n < 10:
        return n
    return n % 10 + 各位和_递归(n // 10)


def 各位和_循环(n):
    总 = 0
    while n > 0:
        总 = 总 + n % 10
        n = n // 10
    return 总


for n in [12345, 9, 1000, 987654321]:
    print(f"  {n:>10}：递归 {各位和_递归(n):>3}，循环 {各位和_循环(n):>3}")

print("\n③ 最大公约数：两种写法")


def 最大公约数_递归(a, b):
    if b == 0:
        return a
    return 最大公约数_递归(b, a % b)


def 最大公约数_循环(a, b):
    while b != 0:
        a, b = b, a % b
    return a


for a, b in [(12, 18), (100, 75), (17, 5), (48, 36)]:
    print(f"  gcd({a}, {b}) = {最大公约数_递归(a, b)} / {最大公约数_循环(a, b)}")

print("\n④ 去程做事 vs 回程做事")


def 去程打印(n):
    print(f"    {n}", end="")       # 一进来就打印
    if n == 1:
        return
    去程打印(n - 1)


def 回程打印(n):
    if n == 1:
        print("    1", end="")      # 只有在最里层才打印这一次
        return
    回程打印(n - 1)
    print(f"    {n}", end="")       # 从里往外回来时才打印


print("  去程打印(5)：", end="")
去程打印(5)
print()
print("  回程打印(5)：", end="")
回程打印(5)
print()
