r'''
════════════════════════════════════════════════════════
  L3 · 第 4 课 · 用法 2        递归的代价
════════════════════════════════════════════════════════

上一节说递归「两行就完事」，听起来很划算。

这一节算算账：**递归到底付了什么钱。**

────────────────────────────────────────────────────────
【账单一：调用栈（内存）】
────────────────────────────────────────────────────────

    每次调用函数，Python 都要记一些东西：

        · 这个函数的参数是什么
        · 现在执行到第几行了（算完要回到哪儿）
        · 函数里的局部变量

    这些东西堆在一个叫「调用栈」的地方。

    ── 递归的时候栈会长很高 ──

        阶乘(5) 的栈，从下往上长：

            ┌─────────────────┐
            │ 阶乘(1)          │  ← 栈顶（最后一个进去的）
            │ 阶乘(2)          │
            │ 阶乘(3)          │
            │ 阶乘(4)          │
            │ 阶乘(5)          │  ← 栈底（第一个进去的）
            └─────────────────┘

        算 5! 要 5 层。算 1000! 要 1000 层。

    ── 栈有多高是有限的 ──

        Python 默认限制约 1000 层，超过就 RecursionError。

        为什么要有这个限制：
        每层都占内存，不限的话一个死循环递归能把内存吃光。

    ── 所以 ──

        **递归的深度 ≈ 问题规模。**
        规模 1000 以内基本安全，上万的规模别用递归。

        （有人会改 sys.setrecursionlimit 提高上限，
          但那只是把「报错」变成「可能真的把内存撑爆 / 段错误」，
          不是解决办法。）

────────────────────────────────────────────────────────
【账单二：重复计算（时间）】
────────────────────────────────────────────────────────

    看斐波那契数列：

        1, 1, 2, 3, 5, 8, 13, 21, ...

        规律：前两个是 1，之后每个数是前两个之和。

    递归写法很自然：

        def 斐波那契(n):
            if n <= 2:
                return 1
            return 斐波那契(n - 1) + 斐波那契(n - 2)

    ── 但它的效率低得吓人 ──

        算 斐波那契(6) 时会发生什么：

            斐波那契(6)
            ├── 斐波那契(5)
            │   ├── 斐波那契(4)
            │   │   ├── 斐波那契(3)
            │   │   │   ├── 斐波那契(2) → 1
            │   │   │   └── 斐波那契(1) → 1
            │   │   └── 斐波那契(2) → 1
            │   └── 斐波那契(3)
            │       ├── 斐波那契(2) → 1
            │       └── 斐波那契(1) → 1
            └── 斐波那契(4)
                ├── 斐波那契(3)
                │   ├── 斐波那契(2) → 1
                │   └── 斐波那契(1) → 1
                └── 斐波那契(2) → 1

        注意到没有：**斐波那契(3) 被算了 2 次，斐波那契(2) 被算了 3 次。**

    ── 规模一大，重复量爆炸 ──

        算 斐波那契(30)：
            调用约 166 万次
        算 斐波那契(40)：
            调用约 2.05 亿次（这台机器上跑了二十多秒）
        算 斐波那契(50)：
            两百多亿次，跑到天荒地老

        增长速度是**指数级**：n 每加 1，调用次数乘约 1.618。

    ── 而循环版呢 ──

        def 斐波那契_循环(n):
            if n <= 2:
                return 1
            前, 后 = 1, 1
            for i in range(3, n + 1):
                前, 后 = 后, 前 + 后
            return 后

        算 斐波那契(50)：50 次循环，瞬间完成。

    **同样的答案，一个要几秒，一个是瞬间。**

    ── 为什么会这样 ──

        递归是「从大往小拆」，拆的时候不知道小问题的答案，
        所以同一个子问题会被重复拆很多次。

        循环是「从小往大算」，每一步都用了前两步的结果，
        每个值只算一次。

    （这个问题有解决办法：把算过的结果存起来。
      需要字典，L4 讲完再回来看。这种方法叫「记忆化」。）

────────────────────────────────────────────────────────
【账单三：可读性有时反而下降】
────────────────────────────────────────────────────────

    短递归好读：

        def 阶乘(n):
            if n == 1:
                return 1
            return n * 阶乘(n - 1)

    但复杂一点的递归，读起来要在脑子里维护一整个栈：

        def 复杂递归(n):
            if n <= 1:
                return n
            a = 复杂递归(n // 2)
            b = 复杂递归(n - 1)
            return a + b

    看到这玩意儿，你得自己画递归树才能算出它到底算了什么。

    ── 判断标准 ──

        「这个递归能不能用一句话说清楚它在干什么？」

            阶乘：能 ——「n 乘上 n-1 的阶乘」
            上面那个：不能

        说不清，就别用递归。

────────────────────────────────────────────────────────
【递归的调试：加追踪打印】
────────────────────────────────────────────────────────

    递归出问题的时候，光看代码很难想明白。

    最有效的办法是**把调用过程打出来**：

        def 阶乘(n, 层=0):
            print("  " * 层 + f"→ 阶乘({n})")
            if n == 1:
                print("  " * 层 + f"← 返回 1")
                return 1
            结果 = n * 阶乘(n - 1, 层 + 1)
            print("  " * 层 + f"← 返回 {结果}")
            return 结果

    跑 阶乘(4) 会看到：

        → 阶乘(4)
          → 阶乘(3)
            → 阶乘(2)
              → 阶乘(1)
              ← 返回 1
            ← 返回 2
          ← 返回 6
        ← 返回 24

    `层` 这个参数不是给算法用的，纯为了打印缩进。
    这种「只为调试而加的参数」，写正式版本时要删掉。

    ── 另一种调试方法：自己手推 ──

        拿最小的输入（比如 n=2、n=3），在纸上一步步写：
        参数是什么、走到哪个 return、返回什么。

        手推三四个就基本能发现问题。

────────────────────────────────────────────────────────
【递归的账单汇总】
════════════════════════════════════════════════════════

    ┌──────────────┬───────────────────────────────────┐
    │ 成本         │ 说明                              │
    ├──────────────┼───────────────────────────────────┤
    │ 内存         │ 每层占一个栈帧，深度 ≈ 问题规模   │
    │ 深度限制     │ 默认约 1000 层，超了报 RecursionError │
    │ 重复计算     │ 子问题重叠时，效率指数级下降      │
    │ 调试难度     │ 要想清楚整个调用链                │
    │ 可读性       │ 简单问题更好读，复杂问题更差      │
    └──────────────┴───────────────────────────────────┘

    ── 所以 ──

        递归适合：问题天然是「自己包含自己」、规模不大、
                  子问题不重复。

        递归不适合：规模大、子问题大量重复、纯粹为了写得短。
'''

