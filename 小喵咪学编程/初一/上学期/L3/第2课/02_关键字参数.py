r'''
════════════════════════════════════════════════════════
  L3 · 第 2 课 · 用法 2        关键字参数
════════════════════════════════════════════════════════

上一节最后留了个问题：只想改第 3 个参数，怎么办？

位置传参只能从左往右挨个填，跳不过去。
关键字参数就是「不按位置，直接点名」。

────────────────────────────────────────────────────────
【形状：调用时把参数名写出来】
────────────────────────────────────────────────────────

    def 全名(姓, 名):
        print(姓 + 名)

    位置传参（老写法）：

        全名("张", "三")            → 张三

    关键字传参：

        全名(姓="张", 名="三")      → 张三

    一样的格式，多写了一层「谁是谁」。

────────────────────────────────────────────────────────
【好处一：顺序可以随便换】
────────────────────────────────────────────────────────

        全名(姓="张", 名="三")      → 张三
        全名(名="三", 姓="张")      → 张三

    结果完全一样。

    ── 为什么 ──

        因为名字就是地址。你写了 `名="三"`，
        Python 直接把 "三" 送到 名 那个格子里，
        跟它在第几个位置没关系。

    ── 什么时候这个特性有用 ──

        参数多、顺序记不住的时候。

            def 创建用户(姓名, 年龄, 性别, 城市, 电话):
                ...

            位置版：
                创建用户("张三", 18, "男", "北京", "13800138000")
                ← 18 是年龄还是工龄？"男" 是性别还是部门？

            关键字版：
                创建用户(姓名="张三", 年龄=18, 性别="男",
                         城市="北京", 电话="13800138000")
                ← 一眼全清楚

────────────────────────────────────────────────────────
【好处二：能跳过中间的默认参数】
────────────────────────────────────────────────────────

    这是关键字参数最实际的用途。

        def 画线(长度=40, 字符="-", 前后空行=False):
            ...

    只想打开「前后空行」，其他不变：

        ❌ 画线(40, "-", True)       ← 能跑，但 40 和 "-" 是白写的
        ✅ 画线(前后空行=True)       ← 只写要改的那一个

    ── 这就是上一节那个问题的答案 ──

        画线("*")           → 把 "*" 当成 长度，报错
        画线(字符="*")      → 正确

    关键字跳过了 长度，直接给 字符。

────────────────────────────────────────────────────────
【混用规则：位置在前，关键字在后】
────────────────────────────────────────────────────────

    这两种可以混着写，但顺序有讲究：

        ✅ 全名("张", 名="三")          位置在前，关键字在后
        ❌ 全名(姓="张", "三")          关键字在前，位置在后
            → SyntaxError: positional argument follows keyword argument

    ── 为什么 ──

        位置参数是「填剩下的空格」。
        如果关键字已经填了 姓，那 "三" 从哪儿开始填？
        为了不产生歧义，规定死了：**位置参数必须全部在前。**

    ── 记住一句话 ──

        先按位置一批，再按名字一批。顺序不能颠倒。

────────────────────────────────────────────────────────
【错误一：参数名写错】
────────────────────────────────────────────────────────

        def 全名(姓, 名):
            print(姓 + 名)

        全名(姓="张", 名子="三")

        → TypeError: 全名() got an unexpected keyword argument '名子'
          （全名() 收到了一个意料之外的关键字参数 '名子'）

    注意：它说的是「意料之外」，说明这个参数名函数里没有。
    报错信息会告诉你函数实际有哪些参数 —— 照着改就行。

────────────────────────────────────────────────────────
【错误二：同一个参数给了两次】
────────────────────────────────────────────────────────

        全名("张", 姓="李")

        → TypeError: 全名() got multiple values for argument '姓'
          （全名() 的 '姓' 收到了多个值）

    ── 为什么 ──

        "张" 按位置填给了 姓（第一个位置）。
        然后又写了 姓="李"，也想填 姓。
        一个格子塞两个值，冲突了。

    ── 这类错误什么时候会出现 ──

        参数名和变量名同名的时候最容易糊：

            姓名 = "张三"
            全名(姓名, 姓=姓名)      ← 看起来合理，其实 姓 收了两次

        看到 multiple values，就去数「这个参数是不是既被位置填了、
        又被关键字填了」。

────────────────────────────────────────────────────────
【什么时候该用关键字】
────────────────────────────────────────────────────────

    ── 建议用 ──

        ① 参数超过 3 个
        ② 参数里有布尔开关（True/False 在调用处看不出含义）
        ③ 有默认参数，只想改其中一两个
        ④ 参数名本身能说明含义（城市=、电话=）

    ── 建议不用 ──

        ① 只有一两个参数，且含义明显
               全名("张", "三")        比 全名(姓="张", 名="三") 清爽

        ② 参数名很短又很通用（a、b、x）
               算(a=1, b=2)            没比 算(1, 2) 清楚

    ── 一个实用判断 ──

        看调用处：**如果不看函数定义，能猜出每个值是干什么的吗？**

            画线(40, "-", True)             猜不出 True 是什么
            画线(前后空行=True)              猜得出

    ── 布尔参数尤其要注意 ──

            def 导出(数据, 是否压缩, 是否加密, 是否包含表头):
                ...

            导出(表, True, False, True)     ← 三个布尔，顺序一错就完蛋
            导出(表, 是否压缩=True,
                     是否加密=False,
                     是否包含表头=True)     ← 不可能搞错

    这条规则几乎所有语言都适用，Python 社区里管它叫
    「布尔参数应该用关键字传」。

────────────────────────────────────────────────────────
【和默认参数的关系】
────────────────────────────────────────────────────────

    两个概念经常一起出现，但管的是不同的事：

        默认参数  → 定义函数时：这个参数可以不给
        关键字参数 → 调用函数时：这个值给哪个参数

    它们互不依赖：

        def 甲(a, b):               ← 没有默认值，也能用关键字调用
            甲(a=1, b=2)

        def 乙(a=1, b=2):           ← 有默认值，也能用位置调用
            乙(1, 2)

    一起用最舒服：

        def 画线(长度=40, 字符="-"):
            ...

        画线(字符="*")              ← 默认值负责「可以不给」，
                                       关键字负责「跳过前面那个」
'''

