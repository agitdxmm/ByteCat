r'''
════════════════════════════════════════════════════════
  L3 · 第 2 课 · 用法 1        默认参数
════════════════════════════════════════════════════════

上一节的函数，每次调用都必须把所有参数给全：

    def 打招呼(名字):
        print("你好，" + 名字)

    打招呼()        → 报错，少参数

但现实里，大部分时候我们想说的就是「你好」，
只有少数情况才换别的词。

默认参数让「常用的情况」可以不写。

────────────────────────────────────────────────────────
【形状：等号给个默认值】
────────────────────────────────────────────────────────

    def 打招呼(名字, 问候="你好"):
        print(问候 + "，" + 名字)

    打招呼("小明")              → 你好，小明
    打招呼("小明", "早上好")     → 早上好，小明

    ── 规则 ──

        不给第二个参数 → 用默认值 "你好"
        给了           → 用你给的

    ── 本质还是赋值 ──

        调用 打招呼("小明") 时，Python 实际做的是：

            名字 = "小明"
            问候 = "你好"        ← 因为没给，用默认值

        调用 打招呼("小明", "早") 时：

            名字 = "小明"
            问候 = "早"          ← 你给的覆盖了默认值

    默认参数就是「实参没来时，顶上的那个值」。

────────────────────────────────────────────────────────
【默认参数必须放在后面】
────────────────────────────────────────────────────────

    这样写会报错：

        def 打招呼(问候="你好", 名字):
            ...

        → SyntaxError: non-default argument follows default argument
          （非默认参数不能跟在默认参数后面）

    ── 为什么 ──

        假设允许这么写，调用 `打招呼("小明")` 时，
        Python 没法判断 "小明" 是给 问候 还是给 名字。

        因为位置参数是按顺序从左往右填的：
        第一个实参填第一个形参。
        如果第一个形参有默认值，那第一个实参到底该不该填它？

        规则定成「默认参数一律靠右」，这个歧义就消失了。

    ── 正确写法 ──

        ✅ def f(a, b, c=1)          （a b 必填，c 可省）
        ✅ def f(a, b=1, c=2)        （a 必填，b c 可省）
        ✅ def f(a=1, b=2, c=3)      （全可省）
        ❌ def f(a=1, b, c)          （默认值在中间）
        ❌ def f(a, b=1, c)          （默认值在中间）

    一句话：**有默认值的参数，全部靠右排。**

────────────────────────────────────────────────────────
【多个默认参数】
────────────────────────────────────────────────────────

    def 画线(长度=30, 字符="-"):
        print(字符 * 长度)

    四种调用方式：

        画线()              → 30 个 -
        画线(10)            → 10 个 -
        画线(10, "*")       → 10 个 *
        画线(长度=10)       → 10 个 -

    ── 注意第三个 ──

        画线(10, "*") 能跑，因为 10 填 长度，"*" 填 字符。
        位置顺序对得上。

    ── 那如果想只改字符、不改长度呢？ ──

        画线("*")       → 出错

        因为 "*" 会被按位置填给第一个参数 长度，
        函数体里就成了 `"-" * "*"`，
        报 TypeError: can't multiply sequence by non-int of type 'str'

        正确做法：**用关键字参数**。

            画线(字符="*")       → 30 个 *

        这就是下一节的内容。这里先记住一个结论：

        **默认参数靠右的规则，使得「只想改后面那个」必须用关键字。**
        因为位置传参只能从左往右挨个填，跳不过去。

────────────────────────────────────────────────────────
【默认参数不是「每次调用重新算」】
────────────────────────────────────────────────────────

    这一条先记住结论，第 4 节会详细展开：

        默认值是在**定义函数的那一刻**算好的，只算一次。
        之后每次调用，用的都是那一个存下来的值。

    对数字、字符串这种「不会变」的值，完全没影响。
    但对「会变」的值（比如列表），会出大问题 —— 第 4 节讲。

────────────────────────────────────────────────────────
【什么时候该用默认参数】
────────────────────────────────────────────────────────

    ── 适合 ──

        ① 绝大多数调用都用同一个值
           画线() 大部分时候就是 30 个减号

        ② 想给调用方「少写几个参数」的便利
           print 的 sep 和 end 就是默认参数：
               print("a", "b")              默认 sep=" "
               print("a", "b", sep="")      改成不留空格

        ③ 参数是「可选项」，不给也能正常工作

    ── 不适合 ──

        ❌ 每个调用方都会传不同的值
           那就别给默认值，强制要求传，省得有人忘了传还以为用了默认值。

        ❌ 默认值需要「根据别的参数算出来」
           def f(长, 宽=长)      ← 不行，定义时 长 还不存在
                                               会报 NameError

           这种得写在函数体里：
               def f(长, 宽=None):
                   if 宽 is None:
                       宽 = 长
                   ...

────────────────────────────────────────────────────────
【内置函数里的默认参数】
────────────────────────────────────────────────────────

    你早就用过默认参数了：

        print("a", "b")
        → a b

    中间那个空格是哪来的？print 的定义大概长这样：

        def print(*值, sep=" ", end="\n"):
            ...

    所以：

        print("a", "b")                  → a b
        print("a", "b", sep="")          → ab
        print("a", "b", sep="-")         → a-b

        print("a", end="")               → 不换行
        print("a", end="...")            → 结尾加三个点

    还有 round：

        round(3.14159)          → 3        （默认保留 0 位）
        round(3.14159, 2)       → 3.14

    **默认参数是「常用配置」的固化。**
    你天天都在用，只是没意识到。

────────────────────────────────────────────────────────
【一个设计上的建议】
────────────────────────────────────────────────────────

    默认值不要写「魔法数字」：

        ❌ def 算税(金额, 税率=0.13):
        ✅ def 算税(金额, 税率=0.13):    # 增值税 13%

    至少加个注释说明这个数从哪来。

    更好的做法是给它一个名字：

        def 算税(金额, 税率=0.13):
            """按增值税率算税。默认 13%，是现行的标准税率。"""

    因为税率会变，将来 0.13 变成 0.09 的时候，
    读代码的人得知道这个数字是什么意思，才敢改。
'''

