r'''
════════════════════════════════════════════════════════
  L3 · 第 2 课 · 用法 3        可变参数
════════════════════════════════════════════════════════

目前为止，函数的参数个数是**写死的**。

    def 求和(a, b):
        return a + b

    求和(1, 2)              → 3
    求和(1, 2, 3)           → 报错，多给了一个

那如果想让一个函数能接受任意多个数呢？

────────────────────────────────────────────────────────
【土办法：先看有多痛苦】
────────────────────────────────────────────────────────

    def 求和2(a, b):
        return a + b

    def 求和3(a, b, c):
        return a + b + c

    def 求和4(a, b, c, d):
        return a + b + c + d

    想要 5 个数？再写一个。10 个数？再写一个。

    这显然不行。参数个数不该是函数设计的一部分。

────────────────────────────────────────────────────────
【*args：把多余的参数打包收下】
────────────────────────────────────────────────────────

    def 求和(*数字):
        总 = 0
        for n in 数字:
            总 += n
        return 总

    调用：

        求和()                  → 0
        求和(1)                 → 1
        求和(1, 2)              → 3
        求和(1, 2, 3, 4, 5)     → 15
        求和(1, 2, 3, ..., 100) → 5050

    ── 星号的作用 ──

        参数名前面加一个 `*`，意思是：

            「从这儿开始，后面来的所有位置参数，
              统统打包，装进一个叫 数字 的东西里。」

    ── 数字 是什么 ──

        是一个「一串值」的东西（类型叫 tuple，元组）。
        L4 会详细讲，现在只需要知道两件事：

            ① 能 for 遍历
            ② 能 print 出来看

        试试：

            def 看看(*东西):
                print(东西)
                print(type(东西))

            看看(1, "a", True)
            → (1, 'a', True)
            → <class 'tuple'>

        看到括号和逗号，那就是「打包」的样子。

    ── 名字为什么常写 args ──

        args 是 arguments 的缩写，`*args` 是约定俗成的写法。
        你写 `*数字`、`*东西` 都行，功能完全一样。
        但看到 `*args` 别人就知道「这是收一堆位置参数」。

────────────────────────────────────────────────────────
【空的时候也没问题】
────────────────────────────────────────────────────────

    求和() 返回 0，因为 for 循环一次都没跑，总 还是初始值 0。

    这里有个经典错误：

        def 求最大值(*数字):
            最大 = 0                ← 如果所有数都是负数呢？
            for n in 数字:
                if n > 最大:
                    最大 = n
            return 最大

        求最大值(-5, -3, -8)     → 0

        错的！正确答案是 -3。

        因为 最大 初始化成 0，而 -5、-3、-8 都比 0 小，
        所以一个都没进去。

    ── 正确写法 ──

        def 求最大值(*数字):
            if not 数字:            ← 空的话没法求，得单独处理
                return None
            最大 = 数字[0]          ← 用第一个当起点
            for n in 数字:
                if n > 最大:
                    最大 = n
            return 最大

        求最大值(-5, -3, -8)     → -3 ✓
        求最大值()               → None

    （`数字[0]` 是取第一个，L4 讲。现在照着用。）

────────────────────────────────────────────────────────
【普通参数和 *args 一起用】
────────────────────────────────────────────────────────

    def 记录(级别, *内容):
        print(f"[{级别}]", *内容)

    调用：

        记录("信息", "程序启动")
        记录("警告", "磁盘", "空间", "不足")

    ── 发生什么 ──

        第一个实参 → 给 级别
        剩下的所有 → 打包给 内容

    所以：

        记录("信息", "程序启动")
            级别 = "信息"，内容 = ("程序启动",)

        记录("警告", "磁盘", "空间", "不足")
            级别 = "警告"，内容 = ("磁盘", "空间", "不足")

    ── 规则：*args 只能有一个，且它后面只能跟关键字参数 ──

        ✅ def f(a, *args)
        ✅ def f(a, *args, b=1)
        ❌ def f(*args, b)          b 会是必填的关键字参数，
                                    但写法上容易被误解，不推荐

        ❌ def f(*args, b, *more)   只能有一个 *args

────────────────────────────────────────────────────────
【调用时用 * 展开】
────────────────────────────────────────────────────────

    星号在定义时是「打包」，在调用时是「拆开」。

        def 求和(*数字):
            总 = 0
            for n in 数字:
                总 += n
            return 总

    直接传：

        求和(1, 2, 3)           → 6

    也可以把一串值拆开传：

        一组 = (1, 2, 3)
        求和(*一组)             → 6

    `*一组` 的意思是「把 一组 里面的东西一个个摊开，当作独立参数传」。

    等一下 —— 求和(1, 2, 3) 和 求和(*(1, 2, 3)) 有什么区别？

        没有区别。后者就是前者的写法变体。

    ── 什么时候真的需要 ──

        当你手里已经有一「包」值，而函数要的是散开的参数时。

        （这个场景等你学了列表会更常用。现在知道 `*` 有这两个方向就行：

            定义时 `*args`  → 打包（多 → 一）
            调用时 `*值`    → 拆开（一 → 多）

        ）

────────────────────────────────────────────────────────
【**kwargs：按名字收】
────────────────────────────────────────────────────────

    两个星号 `**`，收的是「关键字参数」。

        def 打印配置(**配置):
            for 名字 in 配置:
                print(名字, "=", 配置[名字])

    调用：

        打印配置(颜色="红", 大小=3, 是否粗体=True)

    输出：

        颜色 = 红
        大小 = 3
        是否粗体 = True

    ── 发生什么 ──

        所有 `名字=值` 形式的关键字参数，被收集进 配置 里。
        配置 是一个「按键查值」的东西（类型叫 dict，字典）。

    ── 注意调用时不用加 ** ──

        定义时写 `**配置`，调用时正常写 `打印配置(颜色="红")`，
        不用写 `打印配置(**{"颜色":"红"})`。

    ⚠️ 字典（dict）是 L4 的内容。
       这一节只让你知道有 `**kwargs` 这个东西存在，
       知道它长什么样、干什么用。
       真正的用法等 L4 学完字典再回来看。

────────────────────────────────────────────────────────
【四种参数在同一个函数里的顺序】
────────────────────────────────────────────────────────

    完整顺序是固定的：

        def f(普通参数, *args, 仅关键字参数, **kwargs):

    具体说：

        def f(a, b=2, *args, c, d=4, **kwargs):
            ...

    ── 排列规则 ──

        ① 普通位置参数（可以有默认值）
        ② *args            ← 收所有多余的位置参数
        ③ 仅关键字参数      ← 必须用 名字= 传，不能按位置
        ④ **kwargs         ← 收所有多余的关键字参数

    ── 什么是「仅关键字参数」 ──

        在 *args 后面的参数，只能按名字传。

            def f(a, *args, c):
                ...

            f(1, 2, 3, c=4)     ✅ c 用关键字
            f(1, 2, 3, 4)       ❌ 4 会被当成 args 的一部分，c 就缺了

        这个特性用得不多，但看到 `def f(a, *, b)` 要知道什么意思 ——
        那个单独的 `*` 表示「后面的全是仅关键字参数」。

────────────────────────────────────────────────────────
【实际用得到吗】
────────────────────────────────────────────────────────

    日常写业务代码，`*args` 用得不算多。但它在这些地方很常见：

        ① 写「包装」函数时
           想给 print 加个前缀，又不想管 print 有多少参数：

               def 我的打印(*内容, **选项):
                   print("[日志]", *内容, **选项)

           这样 我的打印("a", "b", sep="-") 也能用。

        ② 数学类的函数
           求和、求平均、求最大值 —— 个数本来就不定。

        ③ 框架和库
           各种事件回调、装饰器（以后会碰到）。

    ── 建议 ──

        自己写业务函数时，**能确定个数就别用 *args**。
        *args 的代价是：调用方传什么都能过，错了也不报错。

            def 求和(*数字):
                ...

            求和("a", "b")      ← 不报错！
                                   但 "a" + 0 会崩在循环里

        参数写明确了，错在调用处就被拦住了。
'''

