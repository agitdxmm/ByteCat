r'''
════════════════════════════════════════════════════════
  L3 · 第 2 课 · 用法 4        参数陷阱
════════════════════════════════════════════════════════

这一节全是坑。每一条都能让你盯着代码看半小时找不出错。

────────────────────────────────────────────────────────
【坑一：默认值在「定义时」就算好了】
────────────────────────────────────────────────────────

    看这段：

        默认值 = 10

        def f(x=默认值):
            return x

        默认值 = 99
        print(f())

    输出：10

    为什么不是 99？

    ── 因为 def 这一行执行的时候，Python 就把默认值算出来存好了 ──

        执行 def f(x=默认值) 时：
            看一眼 默认值 → 是 10 → 存进函数的「默认值档案」

        之后 默认值 改成 99，和函数里存的那份没关系。

    默认值是**拍照**，不是**实时直播**。

    ── 这对数字、字符串没影响 ──

        因为 10 永远是 10，你不会「改」一个数字，只会把变量指向别的数字。

    ── 但对「会变的东西」是灾难 ──

        这就是下一个坑。

────────────────────────────────────────────────────────
【坑二：可变默认值（Python 最经典的坑）】
────────────────────────────────────────────────────────

    ⚠️ 下面用到列表（`[]` 和 `.append()`）。
       列表是 L4 的内容，这里只需要知道两件事：
           ① `[]` 是一个「能装东西的容器」，一开始是空的
           ② `.append(x)` 往里面加一个 x

    看这个函数：

        def 加一个(列表=[]):
            列表.append("新东西")
            return 列表

    调用三次：

        print(加一个())      → ['新东西']
        print(加一个())      → ['新东西', '新东西']
        print(加一个())      → ['新东西', '新东西', '新东西']

    它记住了前几次的结果！

    ── 为什么会这样 ──

        结合坑一：默认值在**定义时**就算好了。
        那时的默认值是一个**空列表**，这个空列表被存进了函数。

        每次调用没给参数，用的都是**同一个**列表对象。
        append 改的是这个对象本身，所以越加越多。

    ── 「同一个」可以验证 ──

        def 看id(列表=[]):
            print(id(列表))

        看id()
        看id()
        看id()

    三次打印的 id 完全一样。说明就是同一个东西。

    ── 正确写法：用 None 当哨兵 ──

        def 加一个(列表=None):
            if 列表 is None:
                列表 = []
            列表.append("新东西")
            return 列表

    现在三次调用各自得到新列表，互不影响：

        ['新东西']
        ['新东西']
        ['新东西']

    ── 为什么 None 安全 ──

        因为 None 是个「死的值」，函数不会去改它。
        每次调用时发现是 None，就现场造一个新的列表。

        而 `[]` 是个「活的东西」，会被改。

    ── 规矩 ──

        **默认值永远不要写 []、{}、set() 这类会变的东西。**
        一律写 None，在函数体里判断。

        这条规则所有 Python 项目都适用，不是我们这套教材自己编的。

────────────────────────────────────────────────────────
【坑三：改参数可能改到外面】
────────────────────────────────────────────────────────

    L3 第 1 课讲过：参数是复制进去的。

        def 加十(x):
            x = x + 10
            return x

        n = 5
        加十(n)
        print(n)        → 5     外面没变

    这对数字、字符串成立。但对列表不成立：

        def 改列表(列表):
            列表.append("被改了")

        我的列表 = ["原来就有"]
        改列表(我的列表)
        print(我的列表)      → ['原来就有', '被改了']

    外面变了！

    ── 为什么 ──

        数字/字符串是「值」：复制一份给函数，改的是复制品。
        列表是「一个箱子」：复制的是「箱子的地址」，不是箱子里的东西。
        函数拿到地址，打开箱子往里塞东西，你看到的当然是变了。

    ── 这叫「可变对象」和「不可变对象」的区别 ──

        不可变：int、float、str、bool、None、tuple
                —— 函数里怎么改都不影响外面

        可变：  list、dict、set
                —— 函数里改了，外面就变了

    （除了 tuple，其他都在 L4 讲。）

    ── 怎么避免意外 ──

        ① 函数不要去改传进来的东西
           想改就先复制一份：

               def 加工(列表):
                   新列表 = 列表.copy()
                   新列表.append("加工过的")
                   return 新列表

        ② 函数名要说清楚它会不会改
               def 就地排序(列表)      ← 暗示会改原列表
               def 排序后返回(列表)     ← 暗示不改，返回新的

    ── 好消息 ──

        这一条在实践中反而好处理：
        **只要你写的函数不主动改参数，就不会出问题。**
        大多数函数都该是「只读参数，返回新结果」。

────────────────────────────────────────────────────────
【坑四：参数名遮住了内置函数】
────────────────────────────────────────────────────────

    这样写会出问题：

        def 求和(list):
            总 = 0
            for x in list:
                总 += x
            return 总

    参数名叫 list，就把内置的 `list` 函数遮住了。
    （内置的 list() 能把别的东西转成列表。）

    ── 但影响范围只在函数内部 ──

        函数外面 list 还是好的。所以这个坑不算致命。

    ── 更危险的是这个 ──

        在模块级别（不在任何函数里）写：

            sum = 0
            for i in range(10):
                sum = sum + i

        然后想用内置的 sum() 求和：

            sum([1, 2, 3])
            → TypeError: 'int' object is not callable

        因为 sum 这个名字已经被你覆盖成一个数字了。

    ── 规矩 ──

        不要用这些名字当变量名或参数名：

            list  dict  set  tuple  str  int  float  bool
            sum   max   min  len    abs  round  print  input
            type  range  sorted  reversed  any  all

        不确定是不是内置函数？
        在交互式环境里敲一下这个名字，看会不会显示 `<built-in ...>`。

────────────────────────────────────────────────────────
【坑五：参数太多，调用顺序记不住】
────────────────────────────────────────────────────────

        def 创建订单(用户, 商品, 数量, 单价, 折扣, 运费, 备注):
            ...

        创建订单("张三", "苹果", 10, 5.5, 0.9, 0, "")

    第七个参数是什么？要翻定义。

    ── 这不只是「难看」的问题 ──

        某天有人写：

            创建订单("张三", "苹果", 10, 0.9, 5.5, 0, "")

        数量和单价换了位置 —— **不报错**，但算出来的钱全错。

    ── 解法 ──

        ① 用关键字传（这一节第二课讲过）
        ② 拆分：把相关的参数归到一组
        ③ 减少参数个数：超过 5 个就该重新想设计

    ── 怎么拆 ──

            创建订单(用户, 商品, 数量, 单价)         ← 核心信息
            算优惠(金额, 折扣)                       ← 单独一个函数
            算运费(地址, 重量)                       ← 单独一个函数

        每个函数管一件事，参数自然就少了。

────────────────────────────────────────────────────────
【五条规矩汇总】
────────────────────────────────────────────────────────

    ┌──────────────────────────────────────────────────┐
    │ 1. 默认值用 None，不要用 []、{}                   │
    │                                                    │
    │ 2. 默认值是「定义时拍照」，不是「调用时实时取」     │
    │                                                    │
    │ 3. 函数不要改传进来的列表/字典                     │
    │                                                    │
    │ 4. 别用内置函数名当变量名或参数名                   │
    │                                                    │
    │ 5. 参数超过 5 个，重新想设计                       │
    └──────────────────────────────────────────────────┘

    这五条里，第 1 条最要紧 —— 它是唯一一个「写法看起来完全正常、
    但结果一定错」的坑。其他几条至少报错或者看得出来。
'''

