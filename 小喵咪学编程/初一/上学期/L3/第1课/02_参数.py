r"""
════════════════════════════════════════════════════════
  L3 · 第 1 课 · 用法 2        参数
════════════════════════════════════════════════════════

上一节的函数都是「死的」—— 打招呼() 永远打印「你好」，
想打印「再见」就得再写一个函数。

参数让函数变成「活的」：同一段逻辑，喂不同的数据，出不同的结果。

────────────────────────────────────────────────────────
【形状：括号里写名字】
────────────────────────────────────────────────────────

    def 打招呼(名字):
        print("你好，" + 名字)

    打招呼("小明")      → 你好，小明
    打招呼("小红")      → 你好，小红

    两个新概念：

        名字      ← 定义时括号里的叫「形参」（形式参数 / parameter）
        "小明"    ← 调用时括号里的叫「实参」（实际参数 / argument）

    一句话记住：
        形参是**占位**，实参是**真货**。
        调用时，Python 把实参的值塞进形参，然后执行函数体。

────────────────────────────────────────────────────────
【执行过程：到底发生了什么】
────────────────────────────────────────────────────────

        def 打招呼(名字):
            print("你好，" + 名字)

        打招呼("小明")

    一步步：

        ① 调用 打招呼("小明")
        ② Python 找到 打招呼 这个函数
        ③ 把 "小明" 赋给形参 名字        ← 相当于 名字 = "小明"
        ④ 执行函数体 → 因为 名字 是 "小明"，打印「你好，小明」
        ⑤ 函数结束，名字 这个变量消失

    所以「参数」的本质就是：**调用时自动帮你做的变量赋值。**

    这个理解很重要 —— 后面讲默认参数、关键字参数，
    全都是在这句话上做文章。

────────────────────────────────────────────────────────
【多个参数：按位置对应】
────────────────────────────────────────────────────────

    def 全名(姓, 名):
        print(姓 + 名)

    两个形参，用逗号隔开。

    调用时也得给两个：

        全名("张", "三")      → 张三
        全名("李", "四")      → 李四

    ── 对应规则：按位置，一个一个来 ──

        第一个实参 → 第一个形参
        第二个实参 → 第二个形参

    这叫**位置参数**（positional argument）。

    ── 传反了不会报错，但结果错了 ──

        全名("三", "张")      → 三张

    程序完全正常，输出是「三张」。
    这种错最难查 —— 没有报错，只有「结果不对」。

    所以：**参数顺序也是接口的一部分**，写函数时要和用的人说清楚。

────────────────────────────────────────────────────────
【数量必须对上】
────────────────────────────────────────────────────────

    形参 2 个，实参给 3 个：

        全名("张", "三", "丰")

        → TypeError: 全名() takes 2 positional arguments but 3 were given
           （全名() 接受 2 个位置参数，但给了 3 个）

    形参 2 个，实参给 1 个：

        全名("张")

        → TypeError: 全名() missing 1 required positional argument: '名'
           （全名() 缺少 1 个必需的位置参数：'名'）

    注意两个报错的关键词：

        too many / takes N but M were given   → 给多了
        missing N required                    → 给少了

    报错信息里会直接写出缺的参数名，很贴心，别怕读。

────────────────────────────────────────────────────────
【参数名和外面的变量名无关】
────────────────────────────────────────────────────────

    def 打招呼(名字):
        print("你好，" + 名字)

    名字 = "外面的小明"
    打招呼(名字)

    输出：你好，外面的小明

    —— 发生了什么 ——

        打招呼(名字)   中的 名字 是**外部的变量**，值是 "外面的小明"
        → 传进去的是这个值
        → 函数内部形参也叫 名字，但它是**另一个变量**

    两件事别混：

        调用处的 `名字`  → 外部变量，用来取值
        定义处的 `名字`  → 形参名，接收值

    它们恰好同名，纯属巧合。改成这样也行：

        def 打招呼(谁):
            print("你好，" + 谁)

        名字 = "外面的小明"
        打招呼(名字)      → 还是「你好，外面的小明」

    ── 结论 ──
       函数怎么命名参数，跟调用方怎么命名变量，互不影响。
       函数只需要关心：**第一个位置收什么、第二个位置收什么。**

────────────────────────────────────────────────────────
【参数是「复制」进去的】
────────────────────────────────────────────────────────

    def 改成加十(x):
        x = x + 10
        print("  函数里：x =", x)

    x = 5
    改成加十(x)
    print("  函数外：x =", x)

    输出：

        函数里：x = 15
        函数外：x = 5

    函数里把 x 改成 15 了，外面还是 5。

    ── 为什么 ──
       调用时是 `x(形参) = x(实参)`，把 5 复制了一份给形参。
       函数里改的是那份复制品，原件没动。

    （这条规则对数字、字符串成立。L4 讲列表时会有个例外，
      到时候专门说。）

────────────────────────────────────────────────────────
【参数让函数通用】
────────────────────────────────────────────────────────

    对比一下：

        ❌ 死函数
            def 打印五个星号():
                print("*" * 5)

            打印五个星号()      → *****
            打印五个星号()      → *****
            想要 8 个？没办法，得再写一个函数

        ✅ 活函数
            def 打印星号(个数):
                print("*" * 个数)

            打印星号(5)         → *****
            打印星号(8)         → ********
            打印星号(1)         → *

    一个函数，所有情况都能应付。

    **参数的数量，决定了函数能适应多少种情况。**

────────────────────────────────────────────────────────
【参数的顺序：怎么写、怎么读】
────────────────────────────────────────────────────────

    格式（PEP8 规定）：

        def 全名(姓, 名):        ← 逗号后面有一个空格
        def 画框(宽, 高, 字符):

    不要写成：

        def 全名(姓,名):          ← 太挤
        def 全名( 姓 , 名 ):      ← 括号里不用加空格

    参数多的时候换行写：

        def 画矩形(
            宽度,
            高度,
            边框字符,
            填充字符
        ):
            ...

    或者（短一点的话）：

        def 画矩形(宽度, 高度,
                   边框字符, 填充字符):

    ── 参数名字也很重要 ──

        ✅ def 画矩形(宽度, 高度)
        ❌ def 画矩形(a, b)        ← 调用的人不知道 a 是什么

    名字是给调用者看的说明书。

────────────────────────────────────────────────────────
【参数太多怎么办】
────────────────────────────────────────────────────────

    超过 4 个参数，调用时就容易记不住顺序：

        创建用户("张三", 18, "男", "北京", "13800138000", "学生")

    六个参数，谁在第几位？写的人要查，读的人更懵。

    这时候有几个方向（后面几节会讲到）：

        · 给参数默认值 → 常用的不传也行（第 2 课）
        · 用关键字传参 → 名字写出来，不怕顺序错（第 2 课）
        · 把相关的值打包成一个整体（L4 的字典、L6 的类）

    这一节先记住一句话：

        **参数超过 4 个，就该想想是不是拆成两个函数。**
"""

