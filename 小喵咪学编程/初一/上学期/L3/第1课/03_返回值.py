r"""
════════════════════════════════════════════════════════
  L3 · 第 1 课 · 用法 3        return 返回值
════════════════════════════════════════════════════════

前两节的函数都只会「打印」。这一节让函数能「交货」。

打印是给眼睛看的，return 是给程序用的。这是两件完全不同的事。

────────────────────────────────────────────────────────
【return 的两个作用】
────────────────────────────────────────────────────────

    def 加(a, b):
        return a + b

    作用一：**把值交回去**
    作用二：**立刻结束整个函数**

    调用它：

        x = 加(2, 3)
        print(x)          → 5

    `加(2, 3)` 这个表达式，整体就**等于 5**。

    所以你可以：

        print(加(2, 3))            → 5
        print(加(2, 3) * 2)        → 10
        print(加(加(1, 2), 3))     → 6

    return 让函数调用变成一个「值」，能放在任何能放值的地方。

────────────────────────────────────────────────────────
【没写 return 会怎样：返回 None】
────────────────────────────────────────────────────────

    def 只打印(a, b):
        print(a + b)

    x = 只打印(2, 3)
    print(x)

    输出：

        5
        None

    第一行 5 是函数里的 print 打的。
    第二行 None 是 x 的值 —— 因为函数没有 return，
    Python 就默认给你 None。

    ── None 是什么 ──
        「什么都没有」的那个值。类型是 NoneType。
        它不等于 0，不等于空字符串，就是一个专门表示「无」的值。

    ── 只写 return 不写值 ──

        def 打招呼():
            print("你好")
            return

        print(打招呼())      → 你好 / None

        光写 return 和完全不写，效果一样，都是返回 None。
        但光写 return 有个用处：**提前结束函数**（后面讲）。

────────────────────────────────────────────────────────
【return 之后，函数立刻结束】
────────────────────────────────────────────────────────

    def 演示():
        print("第一句")
        return 1
        print("第二句")       ← 永远执行不到

    输出只有：第一句

    return 一执行，函数当场收工，后面的代码全部作废。

    编辑器通常会提示 unreachable code，Python 不报错。

    ── 这条规则让「提前返回」成为可能 ──

        def 算折扣(价格, 会员):
            if 价格 < 0:
                return 0          ← 价格不合法，直接返回，后面不管
            if 会员:
                价格 = 价格 * 0.8
            return 价格

        第一行判断不合法就 return 掉了，
        后面的逻辑不用再套一层 if。

        这就是「卫语句」在函数里的用法 ——
        和 continue 的思路一样：先把不该继续的情况踢走。

────────────────────────────────────────────────────────
【一个函数可以有多个 return，但只执行一个】
────────────────────────────────────────────────────────

    def 判断(n):
        if n > 0:
            return "正数"
        elif n < 0:
            return "负数"
        else:
            return "零"

    三个 return，每次调用只会走其中一个。

    能不能写成这样？

        def 判断(n):
            if n > 0:
                return "正数"
            if n < 0:
                return "负数"
            return "零"

    能，而且更好。因为前两个 if 各自 return 了，
    能走到最后一行，说明既不是正数也不是负数，只能是零。
    不需要 elif 和 else，结构更平。

    ── 最后一个 return 一定要有 ──

        def 判断(n):
            if n > 0:
                return "正数"
            elif n < 0:
                return "负数"

        print(判断(0))        → None

        漏了「零」的情况，函数会返回 None。
        这种 bug 不会报错，只会让结果莫名其妙变成 None。
        **有 if 就要想到「都不满足时怎么办」。**

────────────────────────────────────────────────────────
【print 和 return 的区别（最重要的一节）】
────────────────────────────────────────────────────────

    先看两个函数：

        def 甲(a, b):
            print(a + b)

        def 乙(a, b):
            return a + b

    它们做的事完全不同：

        甲(2, 3)      → 屏幕上出现 5，函数调用这个「表达式」的值是 None
        乙(2, 3)      → 屏幕上什么都没有，函数调用这个「表达式」的值是 5

    实验一下就清楚了：

        x = 甲(2, 3)      → 屏幕 5，x 是 None
        y = 乙(2, 3)      → 屏幕空白，y 是 5

    ── 为什么会这样 ──

        print 是**输出到屏幕**，数据交给了显示器，程序自己拿不到。
        return 是**把值交给调用者**，数据还在程序里。

    ── 一个比喻 ──

        print   = 大喊一声「答案是 5！」，喊完就没了
        return  = 把写着 5 的纸条递给你

        想让程序继续用这个 5，得拿到纸条，光听着喊没用。

    ── 判断该用哪个 ──

        · 只是要显示给人看 → print
        · 结果还要参与后续计算 → return
        · 一个函数既有计算结果又要显示 → 先 return，在调用处 print

                def 面积(长, 宽):
                    return 长 * 宽

                print("面积是", 面积(3, 4))

        这个分工最干净：函数只算，显示交给外面。

    ── 最典型的新手错误 ──

        def 求和(a, b):
            print(a + b)

        总和 = 求和(1, 2) + 求和(3, 4)      ← 这里会崩

        报错：TypeError: unsupported operand type(s) for +: 'NoneType' and 'NoneType'
        （None 类型不支持加法）

        因为 求和(...) 的值是 None，None + None 没意义。

        改成 return 就对了。

────────────────────────────────────────────────────────
【返回多个值】
────────────────────────────────────────────────────────

    def 统计(a, b):
        return a + b, a * b

    一次返回两个：

        和, 积 = 统计(3, 4)
        print(和, 积)        → 7 12

    也可以整体接住：

        结果 = 统计(3, 4)
        print(结果)          → (7, 12)

    那个 `(7, 12)` 是一个**元组**（tuple），L4 会详细讲。
    现在只要知道：逗号分开写多个值，Python 会自动打包成一个整体，
    用的时候再拆开。

    ── 常见用途 ──

        需要从函数里带回两个结果时（比如「商和余数」「最大值和最小值」）。

        但注意：**返回超过 3 个值，就该考虑拆成两个函数了。**
        调用方记不住顺序，和参数太多是同一个问题。
"""

