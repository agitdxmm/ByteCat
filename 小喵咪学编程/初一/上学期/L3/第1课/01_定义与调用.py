r"""
════════════════════════════════════════════════════════
  L3 · 第 1 课 · 用法 1        def 定义与调用
════════════════════════════════════════════════════════

前两级所有的代码都是「从上往下一条条执行」。
这一级开始，代码可以被**打包**成一个个名字，想用的时候喊一声。

这就是函数。

────────────────────────────────────────────────────────
【函数的形状】
────────────────────────────────────────────────────────

    def 打招呼():
        print("你好")

    拆开看：

        def      ← 关键字，告诉 Python「我要定义一个函数」
        打招呼    ← 函数名，你自己起
        ()       ← 括号，里面放参数（这一节先空着）
        :        ← 冒号，别忘了
        print(...)  ← 缩进 4 空格，函数体

    调用它：

        打招呼()

    输出：你好

    ── 三个最容易错的地方 ──

        ① 忘了冒号
               def 打招呼()
               → SyntaxError: expected ':'

        ② 忘了缩进
               def 打招呼():
               print("你好")
               → IndentationError: expected an indented block

        ③ 调用时忘了括号
               打招呼        ← 这没调用！它只是一个「函数对象」
               打招呼()      ← 这才是调用

       第 ③ 个在交互式环境里最明显：
           输入 打招呼 会显示 <function 打招呼 at 0x...>
           输入 打招呼() 才会打印「你好」

────────────────────────────────────────────────────────
【定义 ≠ 执行】
────────────────────────────────────────────────────────

    这是初学者最大的误解。

        def 打招呼():
            print("你好")

        print("定义完了")

    输出只有：定义完了

    「你好」没有打印！

    因为 def 这一整块只是**登记**：Python 把函数体存起来，
    记住了「有个叫 打招呼 的东西，喊它就跑这几行」。
    至于里面写了什么，定义的时候一行都不跑。

    只有写出 `打招呼()`，函数体才被执行。

    ── 类比 ──
       def 像是写菜谱，写菜谱不会产生一道菜。
       调用才是真的开火。

────────────────────────────────────────────────────────
【一次定义，多次调用】
────────────────────────────────────────────────────────

        def 打招呼():
            print("你好")

        打招呼()
        打招呼()
        打招呼()

    输出三行「你好」。

    这才是函数的意义：**同一段代码只写一遍，能跑很多次。**

────────────────────────────────────────────────────────
【函数名的规则】
────────────────────────────────────────────────────────

    和变量名完全一样：

        ✅ 只能用字母、数字、下划线
        ✅ 不能以数字开头
        ✅ 不能是关键字（def、if、for 这些）
        ✅ 区分大小写（Hello 和 hello 是两个函数）
        ✅ 中文可以（但不建议正式项目里用）

    惯例：

        ✅ 小写 + 下划线：def calculate_total()
        ❌ 驼峰：def calculateTotal()   ← Java 风格，Python 不这么写
        ❌ 首字母大写：def Calculate()  ← 大写开头一般是类，L6 会讲

    名字要说明「做什么」：

        ✅ def 打印分隔线()
        ✅ def is_even(n)
        ❌ def f()
        ❌ def do_something()

────────────────────────────────────────────────────────
【为什么要有函数】
────────────────────────────────────────────────────────

    看这段没有函数的代码：

        print("=" * 40)
        print("学生成绩单")
        print("=" * 40)
        print("语文 92")
        print("数学 88")
        print("=" * 40)
        print("平均分 90.0")
        print("=" * 40)

    三条分隔线，一模一样的 `print("=" * 40)` 写了三遍。

    改成函数：

        def 分隔线():
            print("=" * 40)

        分隔线()
        print("学生成绩单")
        分隔线()
        print("语文 92")
        print("数学 88")
        分隔线()
        print("平均分 90.0")
        分隔线()

    ── 好处一：改一处，全改 ──

        想把 40 个 = 改成 30 个，或者换成 * 号？
        没函数：改 3 处，漏一处就难看。
        有函数：改 1 处。

    ── 好处二：名字就是注释 ──

        `分隔线()` 比 `print("=" * 40)` 好读。
        读代码的人不用数等号有几个，一眼知道在干嘛。

    ── 好处三：能拆开想 ──

        一个大问题拆成几个小函数，可以一个一个想清楚。
        这是函数最重要的作用 —— 不是为了少打字，是为了**少同时想几件事**。

    ── 判断标准：什么时候该抽成函数？ ──

        ① 同样（或几乎同样）的代码出现第 3 次
        ② 一段代码超过 20 行，中间有自然的分段
        ③ 你在注释里写「下面开始算 xxx」—— 这个注释就该变成函数名

────────────────────────────────────────────────────────
【内置函数也是函数】
────────────────────────────────────────────────────────

    print、type、int、str、input —— 它们全都是函数，
    只是 Python 提前写好了，不用你 def。

        type(print)
        → <class 'builtin_function_or_method'>

        type(打招呼)          ← 你自己写的
        → <class 'function'>

    所以你一直在用函数，只是现在开始自己造。

────────────────────────────────────────────────────────
【必须先定义，后调用】
────────────────────────────────────────────────────────

    这样写会报错：

        打招呼()          ← NameError!
        def 打招呼():
            print("你好")

    报错信息：

        NameError: name '打招呼' is not defined

    原因：Python 从上往下执行，走到 `打招呼()` 那一行时，
    这个名字还不存在。

    ── 但「在函数里调用」不受影响 ──

        def 甲():
            乙()              ← 这里调用乙，乙还没定义

        def 乙():
            print("我是乙")

        甲()                  ← 这时乙已经定义好了，能跑

    为什么可以：`乙()` 这一行在**甲被调用时**才执行，
    而甲被调用时，乙早就定义完了。

    ⚠️ 但这只对「定义顺序」有效。
       如果 甲() 写在 乙 的定义之前，照样 NameError。

    所以规矩还是那条：**被调用的函数，得在调用发生前定义好。**
    实际写代码时，习惯上把所有 def 放在文件开头，调用放在后面。

────────────────────────────────────────────────────────
【空函数：pass】
────────────────────────────────────────────────────────

    有时候想先把函数名占住，内容以后写：

        def 待实现():
            pass

    `pass` 是什么都不做的语句，专门用来占位。
    不写 pass 会报 IndentationError（因为函数体空了）。

    注意：空函数调用之后会得到 None —— 因为里面什么都没做，
    没有值可以给你。None 是第 3 节的内容，现在只要知道
    「print(待实现()) 会打印出 None」是正常现象，不是错误。

    这在搭框架时很有用：先把所有函数列出来，
    再一个个填内容，程序随时能跑。

────────────────────────────────────────────────────────
【函数可以套函数】
────────────────────────────────────────────────────────

        def 画边框():
            print("+" + "-" * 20 + "+")

        def 画标题(文字):
            ...

    （带参数的下一节讲。）

    现在只要记住一句话：**函数体里可以随便调用别的函数**，
    包括你自己刚写的。这是后面「组合函数解决大问题」的基础。
"""

