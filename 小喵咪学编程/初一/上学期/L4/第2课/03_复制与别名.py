r'''
════════════════════════════════════════════════════════
  L4 · 第 2 课 · 用法 3        复制与别名
════════════════════════════════════════════════════════

这一节讲一个几乎所有人都踩过的坑：

    **`b = a` 不是复制，是「起第二个名字」。**

理解这一点，很多莫名其妙的 bug 就解释得通了。

────────────────────────────────────────────────────────
【先看清楚：b = a 做了什么】
════════════════════════════════════════════════════════

        a = [1, 2, 3]
        b = a
        b.append(4)

        print(a)        → [1, 2, 3, 4]
        print(b)        → [1, 2, 3, 4]

    改 b，a 也变了！

    ── 为什么 ──

        画个图就清楚了：

            a ──┐
                ├──→ [1, 2, 3, 4]
            b ──┘

        列表在内存里只有**一个**。
        a 和 b 是两个名字，指向同一个列表。

        `b = a` 复制的是「指向」（地址），不是「内容」。

    ── 类比 ──

        一个人有两个外号（A 和 B）。
        叫 A 去剪头发，B 也变短了 —— 因为是同一个人。

    ── 这不是 Python 独有的 ──

        所有语言的「对象」都这样：

            Java：`List b = a;`     同一个对象
            JavaScript：`let b = a;` 同一个数组
            C：指针

        只有「值类型」（数字、字符串）才每次都是复制。

────────────────────────────────────────────────────────
【想要真的复制，有几种方法】
════════════════════════════════════════════════════════

    ── 方法一：a.copy() ──

        a = [1, 2, 3]
        b = a.copy()
        b.append(4)
        print(a)        → [1, 2, 3]      ← 没变
        print(b)        → [1, 2, 3, 4]

    ── 方法二：a[:] ──

        b = a[:]

        切片永远返回新列表，所以这是复制。上一节讲过。

    ── 方法三：list(a) ──

        b = list(a)

        list() 是内置函数，把「可迭代的东西」变成新列表。

    ── 方法四：切片的其他写法 ──

        b = a[0:len(a)]     能用但啰嗦
        b = a[::-1]         ❌ 这是「反转的副本」，顺序反了

    ── 三种主要方法对比 ──

        ┌──────────┬────────┬──────────────────────┐
        │ a.copy() │ 最清楚 │ 推荐                 │
        │ a[:]     │ 最短   │ 老代码里很常见       │
        │ list(a)  │ 通用   │ 能把别的类型转成列表 │
        └──────────┴────────┴──────────────────────┘

    三者效果完全一样（对列表而言）。

────────────────────────────────────────────────────────
【is 和 ==：判断「是不是同一个」】
════════════════════════════════════════════════════════

        a = [1, 2, 3]
        b = a
        c = a.copy()

        a == b      → True     内容相同
        a == c      → True     内容相同

        a is b      → True     **同一个对象**
        a is c      → False    不同对象，只是内容一样

    ── 区别 ──

        `==`  比较**内容**（值相等吗）
        `is`  比较**身份**（是不是同一个东西）

    ── `is` 什么时候该用 ──

        **只用来判断 None、True、False：**

            if x is None: ...
            if x is True: ...

        为什么？因为 None 在整个程序里只有一个实例，
        `is None` 比 `== None` 更快也更准确。

        其他情况一律用 `==`。

    ── 一个容易搞混的例子 ──

            a = [1, 2, 3]
            b = [1, 2, 3]

            a == b      → True
            a is b      → False

        两个不同的列表，内容一样。

        创建方式不同，身份就不同：

            a = [1, 2, 3]
            b = a                → is 是 True
            c = a.copy()         → is 是 False

    ── 为什么不要用 `is` 比较数字 ──

        这个 L3 讲过（小整数缓存），这里再提醒一次：

            1000 is 1000        → 可能是 False（看实现）
            a = 1000
            b = 1000
            a is b              → 通常是 False

        而在方法里算出来的 1000 和字面量 1000 可能不是一个对象。

        **数字、字符串一律用 ==，别用 is。**

────────────────────────────────────────────────────────
【浅拷贝的坑：嵌套列表】
════════════════════════════════════════════════════════

    上面说的三种「复制」都是**浅拷贝**。

    浅拷贝的意思是：**只复制最外面那一层。**

    ── 例子 ──

        a = [[1, 2], [3, 4]]
        b = a.copy()

        b[0].append(99)

        print(a)        → [[1, 2, 99], [3, 4]]      ← a 也变了！
        print(b)        → [[1, 2, 99], [3, 4]]

    ── 为什么 ──

        画图：

            a ──→ [  ● ,  ●  ]
                      │     │
                      ↓     ↓
                   [1,2]  [3,4]

            b ──→ [  ● ,  ●  ]     ← 外层是新列表
                      │     │
                      └──┬──┘      ← 但里面的列表还是**同一个**

        `a.copy()` 只复制了外层的那两个「指针」，
        它们指向的还是原来的两个内层列表。

        所以改 `b[0]`（内层列表），`a[0]` 也跟着变。

    ── 但如果是「整个换掉」就不会互相影响 ──

        a = [[1, 2], [3, 4]]
        b = a.copy()
        b[0] = [99, 99]         ← 换掉整个内层列表

        print(a)        → [[1, 2], [3, 4]]      ← 没变
        print(b)        → [[99, 99], [3, 4]]

        因为 `b[0] = ...` 改的是**外层列表的第 0 格**，
        而那格是 b 自己的。

    ── 理解的关键 ──

        区分两件事：
            · 改「外层列表的某个格子」（`b[0] = ...`）→ 不影响 a
            · 改「格子指向的那个内层列表」（`b[0].append(...)`）→ 影响 a

────────────────────────────────────────────────────────
【深拷贝：连里面也复制】
════════════════════════════════════════════════════════

    要彻底独立，用 `copy.deepcopy()`：

        import copy

        a = [[1, 2], [3, 4]]
        b = copy.deepcopy(a)
        b[0].append(99)

        print(a)        → [[1, 2], [3, 4]]      ← 完全没变
        print(b)        → [[1, 2, 99], [3, 4]]

    ── import 是什么 ──

        把 Python 自带的一个「工具箱」拿进来用。
        `copy` 这个工具箱里有 `copy()`（浅）和 `deepcopy()`（深）。

        import 是 L5 的内容，这里先知道「要用 deepcopy 得先 import」。

    ── 什么时候需要深拷贝 ──

        ① 嵌套列表/字典，要彻底独立
        ② 数据要从一个地方传到另一个地方，怕被改

        **大多数情况下不需要。** 只有「确实有多层嵌套」
        且「确实要完全独立」时才用。

        deepcopy 慢（要一层层递归复制），别滥用。

────────────────────────────────────────────────────────
【函数传参：也是传「指向」】
════════════════════════════════════════════════════════

    这是同一个道理的应用。

        def 加一个(列表):
            列表.append("新的")

        我的 = [1, 2]
        加一个(我的)
        print(我的)        → [1, 2, '新的']      ← 变了

    ── 为什么 ──

        传参数时传的是「指向」，不是「内容」。
        函数里的 `列表` 和外面的 `我的` 指向同一个列表。

    ── 但对数字、字符串没这个问题 ──

        def 加十(x):
            x = x + 10

        n = 5
        加十(n)
        print(n)        → 5      ← 没变

        因为 `x = x + 10` 是「让 x 指向一个新的数字 15」，
        不是「把 5 改成 15」（5 也改不了，数字是不可变的）。

    ── 所以「函数会不会改参数」取决于类型 ──

        可变类型（list、dict、set）  → 会改到外面
        不可变类型（int、str、tuple）→ 不会

    ── 怎么避免意外 ──

        **函数里不要修改传进来的列表。**

        想改就先复制一份：

            def 加一个(列表):
                新列表 = 列表.copy()
                新列表.append("新的")
                return 新列表

        L3 第 2 课第 4 节讲过这条，这里从「别名」的角度又看了一遍。

────────────────────────────────────────────────────────
【一张判断表】
════════════════════════════════════════════════════════

    ┌────────────────────────┬────────────────────────┐
    │ a = b                  │ 别名（同一个对象）      │
    │ a = b.copy()           │ 浅拷贝（外层独立）      │
    │ a = b[:]               │ 同上                    │
    │ a = list(b)            │ 同上                    │
    │ a = copy.deepcopy(b)   │ 深拷贝（完全独立）      │
    │ a = b + []             │ 浅拷贝（结果是新列表）  │
    └────────────────────────┴────────────────────────┘

    ── 一句话 ──

        **赋值不会复制，只是加了个名字。**
        想复制，得明说（copy / [:] / list）。
'''

