def 去首尾空格(s):
    """去掉字符串首尾的空格。"""
    开始 = 0
    while 开始 < len(s) and s[开始] == " ":
        开始 += 1
    结束 = len(s)
    while 结束 > 开始 and s[结束 - 1] == " ":
        结束 -= 1
    return s[开始:结束]


