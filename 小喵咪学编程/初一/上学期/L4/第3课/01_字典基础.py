r'''
════════════════════════════════════════════════════════
  L4 · 第 3 课 · 用法 1        字典基础
════════════════════════════════════════════════════════

列表靠「第几个」找东西。但有时候你根本不知道是第几个 ——
你只知道「它叫什么」。

比如：查「张三」的成绩。张三在第几个？不知道。
你只知道要按名字查。

这就是字典。

────────────────────────────────────────────────────────
【形状：键和值】
════════════════════════════════════════════════════════

        成绩 = {
            "张三": 92,
            "李四": 88,
            "王五": 95,
        }

    花括号 `{ }`，里面是「键: 值」的配对，用逗号隔开。

        "张三"  → 键（key）
        92      → 值（value）
        合起来叫「键值对」（key-value pair）

    ── 读法 ──

        「张三 对应 92」

    ── 和列表对比 ──

        列表：    ["张三", "李四", "王五"]
        靠索引：  列表[0] 是 "张三"

        字典：    {"张三": 92, ...}
        靠键：    字典["张三"] 是 92

    **列表的索引是「位置」，字典的键是「名字」。**

    ── 键可以是数字 ──

        月份天数 = {
            1: 31,
            2: 28,
            3: 31,
        }

        月份天数[1]      → 31

        看起来像列表，但语义不同：
        列表的 1 是「第二个」，字典的 1 是「键为 1 的那一项」。

────────────────────────────────────────────────────────
【访问：d[键]】
════════════════════════════════════════════════════════

        成绩 = {"张三": 92, "李四": 88}

        成绩["张三"]        → 92
        成绩["李四"]        → 88

    ── 键不存在会报 KeyError ──

        成绩["王五"]
        → KeyError: '王五'

        注意是 **KeyError**，不是 IndexError。
        名字不一样，说明「找不到这个键」，不是「位置越界」。

    ── 列表和字典的错误对照 ──

        ┌──────────────────┬────────────────┐
        │ 列表[越界的索引] │ IndexError     │
        │ 字典[不存在的键] │ KeyError       │
        │ 变量没定义       │ NameError      │
        └──────────────────┴────────────────┘

    三种「找不到」，三种错误。

────────────────────────────────────────────────────────
【get：安全访问】
════════════════════════════════════════════════════════

        成绩.get("张三")        → 92
        成绩.get("王五")        → None      ← 不报错！
        成绩.get("王五", 0)     → 0         ← 给个默认值

    ── get 和 [] 的区别 ──

        `d[键]`   键不存在 → KeyError
        `d.get(键)` 键不存在 → 返回 None（或你给的默认值）

    ── 什么时候用哪个 ──

        ┌────────────────────┬──────────────────────────┐
        │ 键一定存在         │ d[键]  更直接            │
        │ 键可能不存在       │ d.get(键, 默认值)        │
        │ 不存在就是错误     │ d[键]  让它早点报错      │
        └────────────────────┴──────────────────────────┘

    ── 一个实际例子：统计计数 ──

        统计每个字出现的次数：

            次数 = {}
            for 字 in "hello":
                if 字 in 次数:
                    次数[字] = 次数[字] + 1
                else:
                    次数[字] = 1

        用 get 可以省掉 if：

            次数 = {}
            for 字 in "hello":
                次数[字] = 次数.get(字, 0) + 1

        读法：「取出当前计数（没有就当 0），加 1，放回去」。

        **这是字典最经典的用法，一定要记住。**

────────────────────────────────────────────────────────
【修改和添加：都是赋值】
════════════════════════════════════════════════════════

    ── 键存在 = 修改 ──

        成绩 = {"张三": 92}
        成绩["张三"] = 100
        print(成绩)        → {'张三': 100}

    ── 键不存在 = 新增 ──

        成绩["王五"] = 95
        print(成绩)        → {'张三': 100, '王五': 95}

    **字典不区分「修改」和「新增」，都是 `d[键] = 值`。**

    ── 这和列表不一样 ──

        列表：`a[5] = x` 越界会报错（不能新开位置）
        字典：`d["新键"] = x` 直接新增，完全合法

    为什么？因为字典没有「位置连续」这个概念 ——
    它内部是散列存储的，加一个键不需要挪别的东西。

────────────────────────────────────────────────────────
【in：判断「有没有这个键」】
════════════════════════════════════════════════════════

        成绩 = {"张三": 92, "李四": 88}

        "张三" in 成绩          → True
        "王五" in 成绩          → False
        "王五" not in 成绩      → True

    ── 注意：in 判断的是「键」，不是「值」──

        92 in 成绩              → False      ← 92 是值，不是键

        想判断「有没有这个值」，得用：

        92 in 成绩.values()     → True

    （`values()` 是字典的方法，下一节讲。这里先知道 `in` 只查键。）

    ── 这个坑很常见 ──

        想查「92 分有没有人考到」，写了 `92 in 成绩`，
        结果永远是 False —— 因为 92 不是键。

────────────────────────────────────────────────────────
【字典的特点】
════════════════════════════════════════════════════════

    ── 一、键不能重复 ──

        成绩 = {"张三": 92, "张三": 88}
        print(成绩)        → {'张三': 88}

        后面那个覆盖前面那个。

        **注意：python 不会报错，会默默覆盖。**
        所以构造字典时要小心重复键。

    ── 二、键必须「不可变」──

        ✅ 字符串、数字、True/False、元组（不含可变内容）
        ❌ 列表、字典、集合

        为什么：字典内部靠「算一个哈希值」来快速定位，
        可变的东西哈希值会变，就没法定位了。

        写 `{[1,2]: "x"}` 会报：
            TypeError: unhashable type: 'list'

        （「unhashable」= 不能算哈希）

    ── 三、键值对没有顺序（概念上）──

        Python 3.7 之后，字典会**记住插入顺序**，
        遍历时按插入顺序输出。

        但**不要依赖这个顺序写业务逻辑** ——
        字典的语义是「按名字查」，不是「按顺序排」。

        要排序就用 `sorted(d.keys())`。

    ── 四、值可以是任何东西 ──

        数字、字符串、列表、甚至另一个字典：

            学生 = {
                "张三": {"语文": 92, "数学": 88},
                "李四": {"语文": 78, "数学": 90},
            }

            学生["张三"]["语文"]      → 92

        这种「嵌套字典」非常常用（第 4 节讲）。

────────────────────────────────────────────────────────
【什么时候用字典，什么时候用列表】
════════════════════════════════════════════════════════

    ── 用字典 ──

        ① 要靠「名字」查东西
           学生成绩、商品价格、配置项

        ② 数据是「成对的」
           键是标识，值是内容

        ③ 要计数
           每个元素出现几次

        ④ 要映射
           「省份 → 省会」「英文 → 中文」

    ── 用列表 ──

        ① 有顺序、顺序有意义
           排行榜、步骤、时间序列

        ② 会有重复元素
           字典的键不能重复

        ③ 需要按位置访问
           「第一个」「最后一个」

    ── 一个判断 ──

        **问：你能给每个元素起个名字吗？**
           能 → 字典（名字就是键）
           不能，只能说「第几个」→ 列表

        「张三 92 分」→ 名字是张三 → 字典
        「第一次 92 分、第二次 88 分」→ 只有顺序 → 列表

────────────────────────────────────────────────────────
【一个必须知道的细节：空字典】
════════════════════════════════════════════════════════

        d = {}          → 空字典
        s = set()       → 空集合（第 4 课讲）

    ⚠️ `{}` 是空字典，不是空集合！

    `{1, 2, 3}` 是集合（没有冒号），
    `{"a": 1}` 是字典（有冒号）。

    空的时候没有冒号可看，Python 规定 `{}` 是字典。
    想要空集合必须写 `set()`。

    （第 4 课会详细讲集合。）
'''

