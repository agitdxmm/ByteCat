r'''
════════════════════════════════════════════════════════
  L4 · 第 3 课 · 用法 2        字典的常用方法
════════════════════════════════════════════════════════

上一节会了「创建、访问、修改」。这一节把字典的方法讲全。

────────────────────────────────────────────────────────
【三个视图：keys / values / items】
════════════════════════════════════════════════════════

        成绩 = {"张三": 92, "李四": 88, "王五": 95}

        ── 所有键 ──
            成绩.keys()     → dict_keys(['张三', '李四', '王五'])

        ── 所有值 ──
            成绩.values()   → dict_values([92, 88, 95])

        ── 所有键值对 ──
            成绩.items()    → dict_items([('张三', 92), ('李四', 88), ('王五', 95)])

    ── 它们看起来像列表，但不是列表 ──

        类型是 `dict_keys` / `dict_values` / `dict_items`，
        不是 `list`。

        好处：**它们是「活的」** —— 字典变了，视图跟着变。

            k = 成绩.keys()
            成绩["赵六"] = 78
            print(k)        → dict_keys(['张三', '李四', '王五', '赵六'])
            ← 自动包含新键

        而如果转成列表，就固定了：

            k = list(成绩.keys())
            成绩["钱七"] = 60
            print(k)        → ['张三', '李四', '王五', '赵六']
            ← 没有钱七

    ── 什么时候要转成列表 ──

        需要排序、切片、按索引取的时候：

            sorted(成绩.keys())        按名字排序
            list(成绩.values())[0]     第一个值
            成绩.keys()[0]             ❌ 不支持索引！

    ── 最常用的是 items() ──

        遍历时同时拿到键和值：

            for 名, 分 in 成绩.items():
                print(名, 分)

        **这是遍历字典的标准写法，一定要记住。**

────────────────────────────────────────────────────────
【setdefault：不存在就设一个默认值】
════════════════════════════════════════════════════════

        d = {"a": 1}
        d.setdefault("a", 100)      → 1        （已存在，不覆盖）
        d.setdefault("b", 100)      → 100      （不存在，设进去）
        print(d)        → {'a': 1, 'b': 100}

    ── 和 get 的区别 ──

        `get(键, 默认)`        不存在 → 返回默认值，**但字典不变**
        `setdefault(键, 默认)` 不存在 → 设进去，**字典变了**

    ── 和 `d[键] = 值` 的区别 ──

        `d[键] = 值`            一定覆盖
        `setdefault`            只在不存在时才设

    ── 一个经典用法：分组 ──

        把一堆人按分数段分组：

            分组 = {}
            for 名, 分 in 成绩.items():
                段 = "优秀" if 分 >= 90 else "普通"
                分组.setdefault(段, []).append(名)

        结果：

            {"优秀": ["张三", "王五"], "普通": ["李四"]}

        `setdefault(段, [])` 的意思是：

            「如果这个段还没有列表，先建一个空列表放进去；
              然后返回这个列表（不管是不是新建的）。」

        然后 `.append(名)` 就往那个列表里加人。

        —— 这行代码有点绕，但非常常用。
           **不用写 if-else 就能分组。**

    ── 等价的不带 setdefault 的写法 ──

            if 段 not in 分组:
                分组[段] = []
            分组[段].append(名)

        三行 vs 一行。

────────────────────────────────────────────────────────
【update：批量合并】
════════════════════════════════════════════════════════

        d = {"a": 1, "b": 2}
        d.update({"b": 99, "c": 3})
        print(d)        → {'a': 1, 'b': 99, 'c': 3}

    ── 规则 ──

        键存在 → 覆盖
        键不存在 → 新增

    这一点和「取平均合并」那种业务逻辑不同 ——
    update 是无条件覆盖。

    ── update 也可以接参数 ──

            d.update(x=1, y=2)
            → {'a': 1, 'b': 99, 'c': 3, 'x': 1, 'y': 2}

        用关键字参数形式，但键只能是标识符（不能有空格、中文不行...）。

        —— 中文其实可以（`d.update(张三=92)`），但不推荐。

    ── update 是原地修改 ──

        返回 None，不生成新字典。

    ── 想生成新的，用字典解包 ──

            c = {**a, **b}      （L4 第 4 课会讲）

────────────────────────────────────────────────────────
【删除：pop / popitem / del / clear】
════════════════════════════════════════════════════════

    ── pop(键)：删掉并返回值 ──

        d = {"a": 1, "b": 2}
        x = d.pop("a")
        print(x)        → 1
        print(d)        → {'b': 2}

    ── pop 可以给默认值 ──

        d.pop("z")            → KeyError
        d.pop("z", 0)         → 0            ← 不报错

    ── popitem()：删掉「最后插入」的那一对 ──

        d = {"a": 1, "b": 2, "c": 3}
        x = d.popitem()
        print(x)        → ('c', 3)          返回一个元组
        print(d)        → {'a': 1, 'b': 2}

        注意：它删的是**最后插入的**，不是「键最大的」。
        （Python 3.7 之前是「随便删一个」，现在是有序的。）

    ── del：直接删 ──

        del d["b"]
        → 键不存在会 KeyError

    ── clear：清空 ──

        d.clear()
        → {}

    ── 四种删除的对比 ──

        ┌─────────────────┬────────────┬──────────────┐
        │ 要拿到值吗      │ 用         │ 键不存在时    │
        ├─────────────────┼────────────┼──────────────┤
        │ 要              │ pop        │ KeyError（可给默认值）│
        │ 不要            │ del        │ KeyError      │
        │ 要（最后一个）  │ popitem    │ KeyError      │
        └─────────────────┴────────────┴──────────────┘

────────────────────────────────────────────────────────
【copy：复制字典】
════════════════════════════════════════════════════════

        a = {"x": 1, "y": 2}
        b = a.copy()
        b["x"] = 99
        print(a)        → {'x': 1, 'y': 2}      ← 没变
        print(b)        → {'x': 99, 'y': 2}

    ── 和列表一样，这是浅拷贝 ──

        如果值是列表/字典，内层还是共享的。

        a = {"名单": [1, 2]}
        b = a.copy()
        b["名单"].append(3)
        print(a)        → {'名单': [1, 2, 3]}   ← a 也变了

        要彻底独立，用 `copy.deepcopy()`。

────────────────────────────────────────────────────────
【fromkeys：批量建字典】
════════════════════════════════════════════════════════

        dict.fromkeys(["a", "b", "c"], 0)
        → {'a': 0, 'b': 0, 'c': 0}

    给一组键，统一设成同一个默认值。

    ── 但有个陷阱 ──

        d = dict.fromkeys(["a", "b"], [])
        d["a"].append(1)
        print(d)        → {'a': [1], 'b': [1]}

    **两个键共用同一个列表！**

    因为 `[]` 只创建了一次，两个键都指向它。

    ── 正确写法：用推导式 ──

        d = {k: [] for k in ["a", "b"]}

    这样每个键得到**各自新建**的空列表。

    —— 这是 L3 第 2 课讲讲过的「可变默认值」的同一个坑，
       只是换了个地方出现。

────────────────────────────────────────────────────────
【方法速查表】
════════════════════════════════════════════════════════

    ┌──────────────────────┬──────────────────────────────┐
    │ d.keys()             │ 所有键（视图）               │
    │ d.values()           │ 所有值（视图）               │
    │ d.items()            │ 所有键值对（视图）           │
    │ d.get(k, 默认)       │ 取值，不存在返回默认，不改字典│
    │ d.setdefault(k, 默认)│ 取值，不存在就设进去         │
    │ d.update(别的)       │ 批量合并（覆盖）             │
    │ d.pop(k, 默认)       │ 删并返回                     │
    │ d.popitem()          │ 删最后一对，返回 (键, 值)    │
    │ d.clear()            │ 清空                         │
    │ d.copy()             │ 浅拷贝                       │
    │ dict.fromkeys(键, 值)│ 批量建（慎用，见上面的坑）   │
    └──────────────────────┴──────────────────────────────┘

    ── 返回值规律和列表一样 ──

        修改类方法（update、clear）返回 None
        pop 返回被删的值
        keys/values/items 返回视图（不是列表，也不是 None）
'''

