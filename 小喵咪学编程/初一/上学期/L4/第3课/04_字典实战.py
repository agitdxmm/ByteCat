def 找重复(列表):
    """返回第一个重复出现的元素，没有则返回 None。"""
    见过 = {}
    for i in range(len(列表)):
        项 = 列表[i]
        if 项 in 见过:
            return 项, 见过[项], i
        见过[项] = i
    return None


