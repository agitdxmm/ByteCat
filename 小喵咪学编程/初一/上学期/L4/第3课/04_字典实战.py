def 差异(旧, 新):
    """返回（新增的键, 删除的键, 修改的键）。"""
    新增 = [k for k in 新 if k not in 旧]
    删除 = [k for k in 旧 if k not in 新]
    修改 = [k for k in 新 if k in 旧 and 新[k] != 旧[k]]
    return 新增, 删除, 修改


