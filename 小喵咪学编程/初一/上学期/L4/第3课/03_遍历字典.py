r'''
════════════════════════════════════════════════════════
  L4 · 第 3 课 · 用法 3        遍历字典
════════════════════════════════════════════════════════

遍历列表就是「一个个看过去」。遍历字典稍微复杂一点 ——
每一项有「键」和「值」两个部分，你得先说清楚要哪个。

────────────────────────────────────────────────────────
【三种遍历方式】
════════════════════════════════════════════════════════

        成绩 = {"张三": 92, "李四": 88, "王五": 95}

    ── ① 直接遍历：拿到键 ──

        for 名 in 成绩:
            print(名, 成绩[名])

        「张三」「李四」「王五」

        注意：`for x in 字典` 遍历的是**键**，不是键值对。

    ── ② 只取值 ──

        for 分 in 成绩.values():
            print(分)

        92 88 95

    ── ③ 同时拿键和值（最常用）──

        for 名, 分 in 成绩.items():
            print(名, 分)

    ── 三种怎么选 ──

        ┌──────────────────┬───────────────────────┐
        │ 只需要值         │ for v in d.values()   │
        │ 需要键和值       │ for k, v in d.items() │
        │ 需要键，值用不上 │ for k in d            │
        └──────────────────┴───────────────────────┘

    **`for k in d` 然后 `d[k]` 是最差的方式** ——
    明明可以直接拿值，却要绕一圈查一次。

    （除非你只想要键，不需要值 —— 那时候 `for k in d` 是对的。）

────────────────────────────────────────────────────────
【遍历顺序】
════════════════════════════════════════════════════════

    Python 3.7 之后，字典**保留插入顺序**。

        成绩 = {}
        成绩["张三"] = 92
        成绩["李四"] = 88
        成绩["王五"] = 95

        for k in 成绩:
            print(k)

        → 张三、李四、王五      （和插入顺序一致）

    ── 但「保留插入顺序」不等于「有序」──

        如果你删除再重新加，位置会变：

            d = {"a": 1, "b": 2, "c": 3}
            del d["b"]
            d["b"] = 99
            print(list(d.keys()))    → ['a', 'c', 'b']

            ← b 跑到最后了

    ── 所以「要按顺序输出」应该显式排序 ──

        for 名 in sorted(成绩):
            print(名, 成绩[名])

        按名字的码点排。

        ── 按值排序 ──

        for 名, 分 in sorted(成绩.items(), key=lambda x: x[1]):
            print(名, 分)

        `x[1]` 是「取键值对的第二个」（也就是值）。

        `sorted(d.items())` 默认按第一个元素（键）排，
        所以要按值排必须给 key。

    ── 按值降序 ──

        sorted(成绩.items(), key=lambda x: x[1], reverse=True)

    ── 先按值降序，值相同按键排（多级排序）──

        sorted(成绩.items(), key=lambda x: (-x[1], x[0]))

    （`-x[1]` 让数值大的在前，`x[0]` 让键小的在前。
      这是 L4 第 2 课第 1 节讲过的技巧。）

────────────────────────────────────────────────────────
【坑：遍历时不能改字典大小】
════════════════════════════════════════════════════════

    这是字典特有的错误，列表那边没有（列表只是悄悄出错，
    字典会直接报错）。

    ── 边遍历边删 ──

        d = {"a": 1, "b": 2, "c": 3}
        for k in d:
            if d[k] < 3:
                del d[k]

        → RuntimeError: dictionary changed size during iteration
          （迭代期间字典大小改变了）

    ── 边遍历边加也一样 ──

        for k in d:
            d[k + "x"] = 0

        → RuntimeError

    ── 为什么列表不报错，字典报错 ──

        列表遍历靠「索引往前走」，
        你删了元素它只是跳过（所以我们说「漏删」，但不报错）。

        字典遍历靠「内部的哈希表位置」。
        你一增一删，内部结构可能整个重排，
        遍历器就不知道走到哪儿了 —— 只能报错。

        **这其实是好事：字典帮你早点发现错误。**

    ── 正确做法一：遍历副本 ──

        for k in list(d):
            if d[k] < 3:
                del d[k]

        `list(d)` 生成一个键的列表副本，
        遍历副本、删原字典，互不干扰。

    ── 正确做法二：先收集要删的键 ──

        要删的 = [k for k in d if d[k] < 3]
        for k in 要删的:
            del d[k]

        这样分两步，逻辑更清楚。

    ── 正确做法三：建新字典 ──

        d = {k: v for k, v in d.items() if v >= 3}

        推导式，最干净。

    ── 改「值」是允许的 ──

        for k in d:
            d[k] = d[k] * 2

        ✅ 能跑。

    **改值不影响字典的「大小」和「结构」，所以不报错。**

    —— 一句话：
       「改大小」（增删键）不行，「改内容」（改值）可以。

────────────────────────────────────────────────────────
【反向查找：按值找键】
════════════════════════════════════════════════════════

    字典只能「按键查值」，不能「按值查键」。

    所以「谁考了 92 分」这种问题，得自己遍历：

        def 谁考了(成绩, 分数):
            for 名, 分 in 成绩.items():
                if 分 == 分数:
                    return 名
            return None

    ── 多个匹配怎么办 ──

        上面的写法只返回第一个。

        想返回所有：

            def 谁考了全部(成绩, 分数):
                结果 = []
                for 名, 分 in 成绩.items():
                    if 分 == 分数:
                        结果.append(名)
                return 结果

                或一行：
                    return [名 for 名, 分 in 成绩.items() if 分 == 分数]

    ── 想「经常按值查」怎么办 ──

        把字典反过来建一份：

            反查表 = {分: 名 for 名, 分 in 成绩.items()}

        然后 `反查表[92]` 就能直接查。

        —— 但要注意：原来的值必须都不重复，
           否则后面的会覆盖前面的。

        **「用空间换时间」是这类问题的通用解法。**

────────────────────────────────────────────────────────
【遍历嵌套字典】
════════════════════════════════════════════════════════

        学生 = {
            "张三": {"语文": 92, "数学": 88},
            "李四": {"语文": 78, "数学": 90},
        }

    ── 两层循环 ──

        for 名, 各科 in 学生.items():
            print(名)
            for 科目, 分 in 各科.items():
                print(f"  {科目}：{分}")

    ── 外层是 item，内层也是 item ──

        注意外层的变量叫 `各科`，它本身是个字典。
        所以内层还能继续 `.items()`。

    ── 三层、四层也一样 ──

        for a, b in d.items():
            for c, e in b.items():
                for f, g in e.items():
                    ...

        超过三层就该考虑「换个数据结构」了，太容易绕晕。

────────────────────────────────────────────────────────
【一个实用函数：遍历时带序号】
════════════════════════════════════════════════════════

        for i, (名, 分) in enumerate(成绩.items(), 1):
            print(f"{i}. {名}：{分}")

    注意 `enumerate(成绩.items())` 每轮给出的是：

        (序号, (键, 值))

    所以要写 `for i, (名, 分) in ...` ——
    括号是为了「把里面的元组再拆开」。

    ── 不加括号会怎样 ──

        for i, 名, 分 in enumerate(成绩.items(), 1):
            ...

        这样也能跑！因为 Python 会尝试把三元组拆成三个变量。

        （enumerate 给的是 (序号, (键, 值))，
          而 (序号, (键, 值)) 展开就是三个值 ——
          但严格说这是「嵌套元组」，拆成三个是碰巧对。

          加括号的写法更明确，推荐。）
'''

