r'''
════════════════════════════════════════════════════════
  L4 · 第 1 课 · 用法 1        列表的创建与索引
════════════════════════════════════════════════════════

前三级的变量都是「一个名字装一个值」。

想存 10 个分数，难道要写 10 个变量？

   分数1 = 92
   分数2 = 88
   ...
   分数10 = 75

能跑，但完全没法用 —— 循环用不了，40 个分数就要 40 个变量。

这一级解决这个问题：**一个名字，装一串值。**

────────────────────────────────────────────────────────
【列表的形状】
────────────────────────────────────────────────────────

   分数 = [92, 88, 95, 78, 60]

    方括号 `[ ]` 是列表，里面用逗号分隔每个元素。

    ── 和字符串的相似之处 ──

        都能用 `len()` 求长度：

            len(分数)        → 5
            len("hello")     → 5

        都能用 `[n]` 取第 n 个：

            "hello"[0]       → 'h'
            分数[0]          → 92

        都能用 `in` 判断有没有：

            "e" in "hello"       → True
            92 in 分数            → True

    这不是巧合 —— 字符串和列表都属于「序列」，
    很多操作是共通的。（L5 讲字符串方法时会再提。）

────────────────────────────────────────────────────────
【索引：从 0 开始】
────────────────────────────────────────────────────────

    ┌───────┬─────┬─────┬─────┬─────┬─────┐
    │ 元素  │ 92  │ 88  │ 95  │ 78  │ 60  │
    ├───────┼─────┼─────┼─────┼─────┼─────┤
    │ 正索引│  0  │  1  │  2  │  3  │  4  │
    │ 负索引│ -5  │ -4  │ -3  │ -2  │ -1  │
    └───────┴─────┴─────┴─────┴─────┴─────┘

        - 5 个元素，正索引是 0~4，负索引是 -5~-1
        - 没有 5，也没有 -6

    ── 正索引 ──

        分数[0]      → 92     第一个
        分数[1]      → 88     第二个
        分数[4]      → 60     最后一个

    ── 负索引 ──

        分数[-1]     → 60     最后一个
        分数[-2]     → 78     倒数第二个
        分数[-5]     → 92     第一个

    ── 最常用的是 0 和 -1 ──

        `列表[0]`  拿第一个
        `列表[-1]` 拿最后一个（不用管长度是多少）

    ── 为什么从 0 开始 ──

        这是历史遗留（C 语言就这么干），但现在有个实际好处：

            索引 = 「偏移量」

            `分数[0]` 意思是「从开头往前挪 0 格」
            `分数[2]` 意思是「从开头挪 2 格」

        而 `len(列表)` 就是「元素总数」，也是「末尾之后的下一格位置」。
        所以 `for i in range(len(列表))` 正好遍历全部索引。

        习惯了就顺了。现在不用纠结为什么，记住规则就行。

────────────────────────────────────────────────────────
【越界：IndexError】
────────────────────────────────────────────────────────

    ┌──────────────────────────────────────────┐
    │ 分数[5]     → IndexError                 │
    │              list index out of range    │
    │                                          │
    │ 分数[-6]    → IndexError                 │
    └──────────────────────────────────────────┘

    5 个元素，索引只能是 0~4 或 -5~-1。

    越界报错的名字是 **IndexError**（下标错误）。

    ── 这是最常见的错误之一 ──

        循环时边界算错一点点，就踩到了。

            for i in range(len(分数) + 1):    ← 多了个 +1
                print(分数[i])

        i 到最后是 5，分数[5] 越界。

    ── 怎么避免 ──

        ① 记住 `range(len(x))` 就是 `0 ~ len(x)-1`
        ② 拿最后一个用 `x[-1]`，不要写 `x[len(x)]`
        ③ 不确定长度时先 `print(len(x))`

────────────────────────────────────────────────────────
【修改元素】
────────────────────────────────────────────────────────

    列表是「可变的」—— 能改。

        分数 = [92, 88, 95]
        分数[0] = 100
        print(分数)      → [100, 88, 95]

    直接赋值就行，和给变量赋值一样。

    ── 注意：不能改不存在的索引 ──

        分数 = [92, 88, 95]
        分数[3] = 70

        → IndexError: list assignment index out of range

        列表只有 3 个元素，索引 3 是第 4 个 —— 不存在。

    ── 想「加一个」不能用索引 ──

        分数[3] = 70      ← 错
        分数.append(70)   ← 对（下面几节讲）

    规则：**赋值只能修改已有的位置，不能新开位置。**

    ── 这是列表和字符串最大的区别 ──

        字符串不能改：

            s = "hello"
            s[0] = "H"
            → TypeError: 'str' object does not support item assignment

        列表能改：

            a = ["h", "e", "l", "l", "o"]
            a[0] = "H"
            → 成功

        这个区别很重要 —— 后面讲「函数改参数」「列表复制」
        都会用到它。

────────────────────────────────────────────────────────
【列表能装什么】
────────────────────────────────────────────────────────

    ── 可以装任何类型，也可以混装 ──

        [1, 2, 3]                    全是整数
        ["a", "b"]                   全是字符串
        [1, "a", True, 3.14]         混装
        [[1, 2], [3, 4]]             装列表（嵌套）
        []                           空列表

    ── 但建议「同类放一起」 ──

        装数字的列表，就全装数字：

            ✅ [92, 88, 95]
            ❌ [92, "缺考", 95]

        因为你会对它们做运算：

            for 分 in 分数:
                总 += 分           ← 遇到 "缺考" 就崩了

        要表示「缺考」，用 None：

            [92, None, 95]

        None 是「什么都没有」，至少它不会让加法崩掉
        （但 `总 += None` 还是崩... 所以要在循环里判断）。

    ── 空列表 [] ──

        很常用 —— 表示「现在还没有东西，一会儿往里加」。

            results = []
            for i in range(5):
                results.append(i * i)
            print(results)        → [0, 1, 4, 9, 16]

        这种「先建空列表，再循环填」的模式，
        是处理数据时最常见的写法。

────────────────────────────────────────────────────────
【为什么列表比多个变量好】
────────────────────────────────────────────────────────

    ── 一、能循环 ──

        三个变量：
            总分 = 分数1 + 分数2 + 分数3

        列表：
            总分 = 0
            for 分 in 分数:
                总分 += 分

        30 个分数？列表的代码**一个字都不用改**。

    ── 二、能传参 ──

        三个变量版，函数要写三个参数：

            def 算总分(甲, 乙, 丙): ...

        列表版，一个参数：

            def 算总分(分数): ...

        以后数据多了，函数签名不变。这是巨大的优势。

    ── 三、能排序、能筛选、能统计 ──

        这些操作对「一堆变量」根本没法做，
        对列表就是一行的事（后面几节讲）。

    ── 一句话 ──

        **列表把「有多少个」和「都是什么」分开了。**

        你不需要在写代码时知道有多少个数据，
        长度是运行时算出来的（`len()`）。

        这是从「写死」到「通用」的关键一步。
'''

