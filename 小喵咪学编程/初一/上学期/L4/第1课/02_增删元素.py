r'''
════════════════════════════════════════════════════════
  L4 · 第 1 课 · 用法 2        增删元素
════════════════════════════════════════════════════════

上一节讲了怎么「取」和「改」。这一节讲怎么「加」和「删」。

列表的长度是可变的 —— 这一点和字符串完全不同。

────────────────────────────────────────────────────────
【加：append（最常用）】
────────────────────────────────────────────────────────

        结果 = []
        结果.append(1)
        结果.append(2)
        结果.append(3)
        print(结果)      → [1, 2, 3]

    ── 特点 ──

        ① 加在**末尾**
        ② 一次加**一个**（如果你传一个列表进去，它会变成嵌套）
        ③ **在原地修改**，不返回新列表

    ── 返回值是 None ──

        这是个经典坑：

            a = [1, 2, 3]
            b = a.append(4)
            print(b)        → None
            print(a)        → [1, 2, 3, 4]

        `append` 改的是 a 自己，返回值是 None。
        所以 `b = a.append(4)` 里 b 是 None，不是列表。

        ── 规矩 ──
           **会「原地修改」的方法，几乎都返回 None。**
           （append、insert、extend、remove、sort、reverse、clear）

           要拿到结果，直接用原列表，别接返回值。

    ── 一次加一个 ──

        a = [1, 2]
        a.append([3, 4])
        print(a)        → [1, 2, [3, 4]]      ← 整个列表成了一个元素

        想加多个，用 extend 或者 +。

────────────────────────────────────────────────────────
【加：insert（指定位置）】
────────────────────────────────────────────────────────

        a = ["a", "c"]
        a.insert(1, "b")
        print(a)        → ['a', 'b', 'c']

    参数：`insert(位置, 元素)` —— 把元素插到「位置」这个索引之前。

    ── 位置超出范围不会报错 ──

        a = [1, 2, 3]
        a.insert(100, 9)
        print(a)        → [1, 2, 3, 9]      ← 直接放到末尾

        a.insert(-100, 0)
        print(a)        → [0, 1, 2, 3, 9]   ← 直接放到开头

    index 越界会报错，但 insert 的位置越界**不会**。
    它会「尽量满足你」：太大了就放末尾，太小了（负数）就放开头。

    ── insert 很慢 ──

        列表在内存里是一排连续的位置。
        往中间插一个元素，后面的全部要往后挪一格。

            [1, 2, 3, 4, 5]
            在索引 1 插入 9：
            [1, 9, 2, 3, 4, 5]
                  ↑ 后面 4 个元素都要挪

        数据量 100 万时，插在开头要挪 100 万次。

    **所以：往末尾加用 append，尽量别往开头插。**

────────────────────────────────────────────────────────
【加：extend 和 +】
────────────────────────────────────────────────────────

    ── extend：把另一个列表的元素一个个加进来 ──

        a = [1, 2]
        a.extend([3, 4])
        print(a)        → [1, 2, 3, 4]

        对比 append：

            a.append([3, 4])    → [1, 2, [3, 4]]     一个元素
            a.extend([3, 4])    → [1, 2, 3, 4]       两个元素

    ── + ：生成一个新列表 ──

        a = [1, 2]
        b = [3, 4]
        c = a + b
        print(c)        → [1, 2, 3, 4]
        print(a)        → [1, 2]          ← a 没变

        区别：
            extend 改的是 a 自己
            + 生成新的，a 不变

    ── * ：重复 ──

        [1, 2] * 3      → [1, 2, 1, 2, 1, 2]
        [0] * 5         → [0, 0, 0, 0, 0]

        常用法：**快速建一个定长的列表。**

            分数 = [0] * 10        ← 10 个 0

────────────────────────────────────────────────────────
【删：remove（按值删）】
────────────────────────────────────────────────────────

        a = ["苹果", "香蕉", "苹果"]
        a.remove("苹果")
        print(a)        → ['香蕉', '苹果']

    ── 三个要点 ──

        ① 按**值**删，不是按索引
        ② 只删**第一个**匹配的（上面还剩一个"苹果"）
        ③ 值不存在会报错：

               a.remove("橘子")
               → ValueError: list.remove(x): x not in list

    ── 删除前先判断 ──

           if "橘子" in a:
               a.remove("橘子")

    ── 想删所有匹配的怎么办 ──

        用循环（下一节讲）或者新建一个列表：
        （这里先记住「remove 只删一个」这个事实就行。）

────────────────────────────────────────────────────────
【删：pop 和 del（按索引删）】
────────────────────────────────────────────────────────

    ── pop：删掉指定位置，**并返回那个元素** ──

        a = [10, 20, 30]
        x = a.pop()
        print(x)        → 30
        print(a)        → [10, 20]

        `pop()` 不传参数时删**最后一个**。

        a = [10, 20, 30]
        x = a.pop(0)
        print(x)        → 10
        print(a)        → [20, 30]

        传索引就删那个位置。

    ── pop 是唯一「既修改又返回值」的列表方法 ──

        其他修改方法都返回 None，只有 pop 返回被删的元素。

        所以「拿出来用」的时候用 pop，「单纯删掉」用 del。

    ── 空列表 pop 会报错 ──

        [].pop()
        → IndexError: pop from empty list

    ── del：纯删除，不返回值 ──

        a = [10, 20, 30]
        del a[1]
        print(a)        → [10, 30]

        del 是语句不是函数，所以写法是 `del a[1]`，没有括号。

    ── del 还能删一段 ──

        a = [1, 2, 3, 4, 5]
        del a[1:3]
        print(a)        → [1, 4, 5]

        （切片，下一课讲。）

    ── pop 和 del 怎么选 ──

        ┌──────────────┬────────────────────────┐
        │ 要拿被删的值 │ 用 pop                 │
        │ 不要那个值   │ 用 del                 │
        └──────────────┴────────────────────────┘

────────────────────────────────────────────────────────
【清空：clear】
────────────────────────────────────────────────────────

        a = [1, 2, 3]
        a.clear()
        print(a)        → []

    ── 和 `a = []` 的区别 ──

        a.clear()   原地清空 —— 所有指向 a 的地方都看到空列表
        a = []      让 a 指向一个**新的**空列表 —— 原来那个列表还在

        区别在「有别名」的时候才明显：

            a = [1, 2, 3]
            b = a
            a.clear()
            print(b)        → []        b 也空了

            a = [1, 2, 3]
            b = a
            a = []
            print(b)        → [1, 2, 3]  b 还是原来的

        这个「别名」的坑，第 2 课会专门讲。

────────────────────────────────────────────────────────
【方法速查表】
────────────────────────────────────────────────────────

    ┌────────────────┬────────────────────────────────┐
    │ a.append(x)    │ 末尾加一个 x                    │
    │ a.insert(i, x) │ 在索引 i 前插入 x               │
    │ a.extend(b)    │ 把 b 的元素全加进来             │
    │ a.remove(x)    │ 删掉第一个值为 x 的             │
    │ a.pop()        │ 删最后一个，返回它              │
    │ a.pop(i)       │ 删索引 i，返回它                │
    │ del a[i]       │ 删索引 i，不返回                │
    │ a.clear()      │ 清空                            │
    │ a + b          │ 新列表（拼接）                  │
    │ a * n          │ 新列表（重复）                  │
    └────────────────┴────────────────────────────────┘

    ── 返回值 ──

        除了 pop，其他修改方法都返回 **None**。

    ── 原地 vs 新建 ──

        原地改：append、insert、extend、remove、pop、clear、sort、reverse
        新建：  a + b、a * n、sorted(a)、切片 a[1:3]

        判断方法：**看它是不是「方法」（a.xxx()）——
        列表的方法基本都原地改；用运算符或内置函数的基本都新建。**

    （唯一例外是 sort 和 sorted，名字不同，功能相同，
      第 2 课会讲。）
'''

