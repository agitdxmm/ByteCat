    def 成绩报告(分数表):
        """打印一份成绩统计。"""
        人数 = len(分数表)

        if 人数 == 0:
            print("  （没有数据）")
            return

        总 = 0
        最高 = 分数表[0]
        最高位置 = 1
        最低 = 分数表[0]
        最低位置 = 1
        及格数 = 0
        优秀数 = 0

        for i in range(人数):
            分 = 分数表[i]
            总 += 分

            if 分 > 最高:
                最高 = 分
                最高位置 = i + 1
            if 分 < 最低:
                最低 = 分
                最低位置 = i + 1
            if 分 >= 60:
                及格数 += 1
            if 分 >= 90:
                优秀数 += 1

        平均 = 总 / 人数

        print(f"  人数：     {人数}")
        print(f"  总分：     {总}")
        print(f"  平均分：   {平均:.1f}")
        print(f"  最高分：   {最高}（第 {最高位置} 个）")
        print(f"  最低分：   {最低}（第 {最低位置} 个）")
        print(f"  及格人数： {及格数}，及格率 {及格数 / 人数 * 100:.1f}%")
        print(f"  90 分以上：{优秀数}")


