r'''
════════════════════════════════════════════════════════
  L4 · 第 1 课 · 用法 4        遍历列表
════════════════════════════════════════════════════════

列表最常见的操作就是「一个个看过去」。

这一节把「怎么看」的几种方式讲全，以及一个几乎人人都会踩的坑。

────────────────────────────────────────────────────────
【方式一：for x in 列表】
════════════════════════════════════════════════════════

        for 分 in [92, 88, 95]:
            print(分)

    最简单，也最常用。

    ── 什么时候够用 ──

        只要「每个元素的值」，不需要知道它在第几个。

            算总和、找最大、判断有没有、筛出符合条件的

    ── 循环变量是每轮重新赋值的 ──

        for 分 in [92, 88, 95]:
            分 = 分 + 1          ← 改了没用
        print(分)                → 95

        下一轮开始时，分 会被重新赋成下一个元素，
        你在循环体里怎么改都不影响下一轮。

        （L2 第 4 课讲过这条。）

────────────────────────────────────────────────────────
【方式二：for i in range(len(列表))】
════════════════════════════════════════════════════════

        a = [92, 88, 95]
        for i in range(len(a)):
            print(f"第 {i} 个是 {a[i]}")

    ── 什么时候需要 ──

        ① 需要知道索引
        ② 要修改列表元素（`a[i] = ...`）
        ③ 要和「前后元素」比较

    ── 为什么要写 `range(len(a))` ──

        `range(n)` 生成 0 到 n-1，正好是全部合法索引。

        **`range(len(a))` 就是「0, 1, ..., len-1」**，
        不多不少。记住这个对应关系，能避开大部分越界错误。

    ── 一个常见错误 ──

        for i in range(len(a) + 1):     ← 多了一个 +1
            print(a[i])                 ← 最后 a[len(a)] 越界

────────────────────────────────────────────────────────
【方式三：enumerate（同时要索引和值）】
════════════════════════════════════════════════════════

        a = ["苹果", "香蕉", "橘子"]

        for i, 水果 in enumerate(a):
            print(i, 水果)

    输出：

        0 苹果
        1 香蕉
        2 橘子

    ── 它比方式二好在哪 ──

        方式二：`a[i]` 每次都要查一次
        方式三：直接拿到值，不用查

        代码也更短：

            # 方式二
            for i in range(len(a)):
                水果 = a[i]
                print(i, 水果)

            # 方式三
            for i, 水果 in enumerate(a):
                print(i, 水果)

    ── 从 1 开始编号 ──

        enumerate 有第二个参数：

            for i, 水果 in enumerate(a, 1):
                print(f"第 {i} 个：{水果}")

            第 1 个：苹果
            第 2 个：香蕉
            第 3 个：橘子

        省掉 `i + 1`。

    ── `i, 水果` 是什么 ──

        这里是「同时接两个值」（L1 第 2 课的多变量赋值）。
        enumerate 每轮给出一个「(索引, 值)」的组合，
        用两个变量分别接住。

        （严格说是元组解包，L4 第 4 课会讲元组。）

────────────────────────────────────────────────────────
【方式四：while + 索引】
════════════════════════════════════════════════════════

        a = [92, 88, 95]
        i = 0
        while i < len(a):
            print(a[i])
            i += 1

    ── 什么时候用 ──

        ① 需要在循环里「跳着走」（i += 2）
        ② 需要「有时前进有时不前进」
        ③ 需要提前 break 且逻辑复杂

    ── 大多数时候不需要 ──

        能用 for 就用 for，它自动管理 i，不会忘记 i += 1。

    ── while 遍历最危险的错误 ──

            i = 0
            while i < len(a):
                print(a[i])
                # 忘了 i += 1 → 死循环

────────────────────────────────────────────────────────
【反向遍历】
════════════════════════════════════════════════════════

    ── 方法一：range 倒着数 ──

        a = ["a", "b", "c"]
        for i in range(len(a) - 1, -1, -1):
            print(a[i])

        输出：c b a

        参数：`range(起点, 终点, 步长)`
             起点是 `len-1`（最后一个索引）
             终点是 -1（不包含，所以最后一个取到 0）
             步长 -1（倒着走）

        L2 第 4 课讲过：`range(5, 0)` 是空的，倒序必须写步长 -1。

    ── 方法二：先反转再遍历 ──

        for x in reversed(a):
            print(x)

        `reversed()` 返回一个「倒着走」的版本，不修改原列表。
        更简洁，推荐用它。

────────────────────────────────────────────────────────
【坑：遍历时修改列表】
════════════════════════════════════════════════════════

    这是 Python 最著名的坑之一，上一节提过，这里讲透。

    ── 错误示范 1：边遍历边删 ──

        a = [1, 1, 2]
        for x in a:
            if x == 1:
                a.remove(x)
        print(a)        → [1, 2]      ← 漏了一个

    原因：`for x in a` 内部维护一个索引，
    你 remove 之后后面的元素前移，索引却没退回来，
    于是跳过了一个元素。

    ── 错误示范 2：边遍历边加 ──

        a = [1, 2, 3]
        for x in a:
            a.append(x * 10)
        # 这是死循环！因为列表一直在变长

    实际会一直跑到内存耗尽才崩（或者你手动停）。

    ── 正确做法 1：遍历副本 ──

        a = [1, 1, 2]
        for x in a.copy():
            if x == 1:
                a.remove(x)
        print(a)        → [2]

        `a.copy()` 生成一个新列表，for 遍历的是副本，
        删除的是原列表 —— 两边互不干扰。

    ── 正确做法 2：建新列表 ──

        a = [1, 1, 2]
        结果 = []
        for x in a:
            if x != 1:
                结果.append(x)
        a = 结果

        或者（L4 第 2 课学的列表推导式）：

            a = [x for x in a if x != 1]

    ── 正确做法 3：倒着遍历 ──

        a = [1, 1, 2]
        for i in range(len(a) - 1, -1, -1):
            if a[i] == 1:
                del a[i]
        print(a)        → [2]

        倒着走，删除只影响「后面」（已经处理过的部分）。

    ── 三个做法怎么选 ──

        ┌──────────────┬──────────────────────────────┐
        │ 遍历副本     │ 最简单，内存多一份            │
        │ 建新列表     │ 最安全，原列表不动            │
        │ 倒着遍历     │ 省内存，但要想清楚为什么安全  │
        └──────────────┴──────────────────────────────┘

    **推荐「建新列表」。** 它最不容易出错。

────────────────────────────────────────────────────────
【zip：同时遍历两个列表】
════════════════════════════════════════════════════════

    有时候数据分在两个列表里：

        名字 = ["张三", "李四", "王五"]
        分数 = [92, 88, 95]

    想「张三 92、李四 88」这样配对输出。

    ── 笨办法：用索引 ──

        for i in range(len(名字)):
            print(名字[i], 分数[i])

        能跑，但要求两个列表一样长，而且代码啰嗦。

    ── zip：直接配对 ──

        for 名, 分 in zip(名字, 分数):
            print(名, 分)

        输出：
            张三 92
            李四 88
            王五 95

    ── zip 的特点 ──

        ① 按位置配对：第一个配第一个，第二个配第二个
        ② 长度不同时，**以短的为准**，多的被丢掉
        ③ 不修改原来的列表

    ── 长度不同会怎样 ──

        名字 = ["张三", "李四", "王五"]
        分数 = [92, 88]

        zip 只产出两组：
            张三 92
            李四 88

        第三个「王五」被默默丢掉了。

    **⚠ 这里要注意**：zip 不会告诉你「长度不匹配」。
    如果这是数据错误（比如少录了一个分数），
    你会悄悄丢掉数据。用之前最好先比较长度：

        if len(名字) != len(分数):
            print("数据条数不一致！")

────────────────────────────────────────────────────────
【四种方式怎么选】
════════════════════════════════════════════════════════

    ┌──────────────────┬────────────────────────────┐
    │ 只要值           │ for x in 列表              │
    │ 要索引 + 要改    │ for i in range(len())      │
    │ 要索引 + 不改    │ for i, x in enumerate()    │
    │ 要跳着走/乱走    │ while + i                  │
    │ 两个列表配对     │ for a, b in zip()          │
    └──────────────────┴────────────────────────────┘

    ── 一句话 ──

        **能用 `for x in 列表` 就别用索引。**
        索引是手段，不是目的。

        只有当「位置本身有意义」（要改、要比较前后、要显示第几个），
        才需要拿出索引。
'''

