r'''
════════════════════════════════════════════════════════
  L4 · 第 5 课 · 用法 2        数据处理实战
════════════════════════════════════════════════════════

上一节学「结构」，这一节学「流程」。

数据处理基本就是五步：**清洗 → 筛选 → 分组 → 聚合 → 输出**。

这一节用一个完整案例走一遍。

────────────────────────────────────────────────────────
【案例：一份销售记录】
════════════════════════════════════════════════════════

        销售 = [
            {"日期": "03-01", "销售员": "张三", "产品": "A", "数量": 3, "单价": 100},
            {"日期": "03-01", "销售员": "李四", "产品": "B", "数量": 2, "单价": 250},
            {"日期": "03-02", "销售员": "张三", "产品": "A", "数量": 5, "单价": 100},
            {"日期": "03-02", "销售员": "王五", "产品": "C", "数量": 1, "单价": 800},
            {"日期": "03-03", "销售员": "李四", "产品": "A", "数量": 4, "单价": 100},
            {"日期": "03-03", "销售员": "张三", "产品": "B", "数量": 1, "单价": 250},
            {"日期": "03-04", "销售员": "王五", "产品": "C", "数量": 2, "单价": 800},
            {"日期": "03-04", "销售员": "赵六", "产品": "A", "数量": 0, "单价": 100},
        ]

    每条记录：日期、销售员、产品、数量、单价。

    ── 第一步就是加一个「金额」字段 ──

        金额 = 数量 × 单价

        这个字段数据里没有，但每次都要算，所以干脆先加进去：

            for 单 in 销售:
                单["金额"] = 单["数量"] * 单["单价"]

        —— 这叫「派生字段」：由已有字段算出来的新字段。

────────────────────────────────────────────────────────
【第一步：清洗】
════════════════════════════════════════════════════════

    真实数据总是有毛病的。先检查：

        ① 数量为 0 或负数的（无效销售）
        ② 必填字段缺失的
        ③ 类型不对的（数量是字符串）

    ── 清洗的两种策略 ──

        **丢弃**：有问题就不要这条

            干净 = [单 for 单 in 销售 if 单["数量"] > 0]

        **修正**：有问题就改成合理值

            for 单 in 销售:
                if 单["数量"] < 0:
                    单["数量"] = 0

    ── 选哪个 ──

        · 数据错误是「录入失误」→ 修正（或者去问数据来源）
        · 数据错误是「不该存在的记录」→ 丢弃
        · 拿不准 → 丢弃，并记录丢了几条

    ── 一定要「记录丢了多少」──

        默默丢掉一半数据，最后算出来的结论是错的，
        而且没人知道错在哪。

            原数 = len(销售)
            干净 = [单 for 单 in 销售 if 单["数量"] > 0]
            丢弃 = 原数 - len(干净)
            if 丢弃 > 0:
                print(f"⚠ 丢弃了 {丢弃} 条无效记录")

────────────────────────────────────────────────────────
【第二步：筛选】
════════════════════════════════════════════════════════

    分析时通常只看一个子集：

        某段时间：   单["日期"] >= "03-02"
        某个销售员： 单["销售员"] == "张三"
        某个产品：   单["产品"] in {"A", "B"}
        某个金额：   单["金额"] >= 500

    ── 多个条件用 and ──

        结果 = [单 for 单 in 干净
                if 单["日期"] >= "03-02" and 单["销售员"] == "张三"]

    ── 为什么不直接改原数据 ──

        筛选是「看数据的另一个角度」，不是「改数据」。

        原来的数据要保留 —— 你可能还要从别的角度再看一遍。

        **筛选永远生成新列表，不删原数据。**

────────────────────────────────────────────────────────
【第三步：分组】
════════════════════════════════════════════════════════

    按某个字段分组：

        分组 = {}
        for 单 in 干净:
            组 = 单["销售员"]
            分组.setdefault(组, []).append(单)

    ── 「按什么分组」由问题决定 ──

        问「谁卖得多」    → 按销售员分组
        问「哪个产品好卖」→ 按产品分组
        问「哪天最忙」    → 按日期分组

        **同一个数据集，换个分组维度就是另一个分析。**

────────────────────────────────────────────────────────
【第四步：聚合】
════════════════════════════════════════════════════════

    对每组算指标：

        汇总 = {}
        for 组名, 记录们 in 分组.items():
            金额们 = [单["金额"] for 单 in 记录们]
            汇总[组名] = {
                "单数": len(记录们),
                "总额": sum(金额们),
                "平均": sum(金额们) / len(金额们),
                "最大": max(金额们),
            }

    ── 常用的聚合指标 ──

        计数    len()
        求和    sum()
        平均    sum() / len()
        最大    max()
        最小    min()
        去重数  len(set(...))

    ── 注意 max/min 的空列表问题 ──

        分组之后每组至少有 1 条（因为空组不会出现），
        所以 max 是安全的。

        但如果你手动建了空组，就要判断。

────────────────────────────────────────────────────────
【第五步：输出】
════════════════════════════════════════════════════════

    ── 排序 ──

        排好 = sorted(汇总.items(), key=lambda x: -x[1]["总额"])

    ── 打印表格 ──

        print(f"{'销售员':<8}{'单数':>6}{'总额':>10}{'平均':>10}")
        for 名, 数据 in 排好:
            print(f"{名:<8}{数据['单数']:>6}"
                  f"{数据['总额']:>10}{数据['平均']:>10.1f}")

    ── 取 Top N ──

        前3 = 排好[:3]

    ── 算占比 ──

        总额 = sum(d["总额"] for _, d in 排好)
        for 名, 数据 in 排好:
            print(f"{名}：{数据['总额'] / 总额 * 100:.1f}%")

────────────────────────────────────────────────────────
【一个完整函数：五步串起来】
════════════════════════════════════════════════════════

        def 分析(销售, 分组字段="销售员"):
            """按某个字段分组，返回汇总结果（已排序）。"""

            # ① 派生字段
            for 单 in 销售:
                单["金额"] = 单["数量"] * 单["单价"]

            # ② 清洗
            干净 = [单 for 单 in 销售 if 单["数量"] > 0]

            # ③ 分组
            分组 = {}
            for 单 in 干净:
                分组.setdefault(单[分组字段], []).append(单)

            # ④ 聚合
            汇总 = {}
            for 组名, 记录们 in 分组.items():
                金额们 = [单["金额"] for 单 in 记录们]
                汇总[组名] = {
                    "单数": len(记录们),
                    "总额": sum(金额们),
                    "平均": sum(金额们) / len(金额们),
                }

            # ⑤ 输出（排好序的列表）
            return sorted(汇总.items(), key=lambda x: -x[1]["总额"])

    ── 这个函数的「分组字段」是参数 ──

        传 "销售员" → 按人统计
        传 "产品"   → 按产品统计
        传 "日期"   → 按天统计

        **同一个函数，换一个参数就是另一个分析。**

        这比写三个函数好 —— 逻辑只有一份，改的时候只改一处。

    ── 但要小心一个坑 ──

        `for 单 in 销售: 单["金额"] = ...` 这句**修改了原数据**。

        如果调用两次分析（一次按销售员、一次按产品），
        第二次会再算一遍金额 —— 结果一样，只是白算。

        但如果是「累加」这种操作，就会出错。

        **要么确认「重复执行是安全的」（幂等），
        要么先 deepcopy。**

        这里加金额是幂等的（算多少次结果都一样），所以没事。

────────────────────────────────────────────────────────
【常见错误清单】
════════════════════════════════════════════════════════

    ❌ 错误一：边遍历边删

        for 单 in 销售:
            if 单["数量"] == 0:
                销售.remove(单)
        → 漏删（第 1 课讲过）

        正确：`销售 = [单 for 单 in 销售 if 单["数量"] > 0]`

    ❌ 错误二：忘了默认值，KeyError 满屏

        单["金额"]      可能不存在
        单.get("金额", 0)   安全

    ❌ 错误三：除以 0

        平均 = 总额 / 单数      单数为 0 时崩

    ❌ 错误四：修改了不该改的数据

        函数里 `单["金额"] = ...` 改了原数据，
        调用方以为「只是算了算，没动我的数据」。

    ❌ 错误五：字符串比较日期

        "03-09" > "03-10" 是 True（按字符比！）
        因为 "9" > "1"。

        日期用 "2026-03-09" 这种「补零 + 从大到小」的格式才能直接比。
        否则要先转成日期对象（需要 import datetime）。
'''

