    def 清洗(数据):
        """返回 (干净数据, 问题报告)。"""
        干净 = []
        报告 = []

        for i, 条 in enumerate(数据):
            位置 = f"第 {i + 1} 条"

            # 名字检查
            名 = 条.get("名字", "")
            if not isinstance(名, str) or 名.strip() == "":
                报告.append(f"{位置}：名字为空或类型不对，丢弃")
                continue

            # 年龄检查
            if "年龄" not in 条:
                报告.append(f"{位置}（{名}）：缺年龄，丢弃")
                continue

            年龄 = 条["年龄"]
            if not isinstance(年龄, int):
                # 尝试转换
                try:
                    年龄 = int(年龄)
                except (ValueError, TypeError):
                    报告.append(f"{位置}（{名}）：年龄「{条['年龄']}」转不了，丢弃")
                    continue

            if 年龄 < 1 or 年龄 > 150:
                报告.append(f"{位置}（{名}）：年龄 {年龄} 不合理，丢弃")
                continue

            # 分数检查
            分数 = 条.get("分数")
            if not isinstance(分数, (int, float)):
                报告.append(f"{位置}（{名}）：分数「{分数}」不是数字，丢弃")
                continue

            if 分数 < 0 or 分数 > 100:
                报告.append(f"{位置}（{名}）：分数 {分数} 超范围，丢弃")
                continue

            # 通过
            干净.append({
                "名字": 名.strip(),
                "年龄": 年龄,
                "分数": 分数,
            })

        return 干净, 报告


