    def 分组(记录们, 字段):
        """按字段分组。"""
        组 = {}
        for 单 in 记录们:
            组.setdefault(单[字段], []).append(单)
        return 组


    def 算指标(记录们):
        """返回一组记录的统计。"""
        金额们 = [单["金额"] for 单 in 记录们]
        数量们 = [单["数量"] for 单 in 记录们]
        return {
            "单数": len(记录们),
            "总额": sum(金额们),
            "数量": sum(数量们),
            "平均": sum(金额们) / len(金额们),
            "最大": max(金额们),
        }


    def 汇总(记录们, 字段):
        """分组 + 聚合 + 排序。"""
        组 = 分组(记录们, 字段)
        结果 = {}
        for 名, 单们 in 组.items():
            结果[名] = 算指标(单们)
