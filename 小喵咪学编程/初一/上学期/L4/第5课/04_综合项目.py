def 打印报告(表):
    if len(表) == 0:
        print("  没有数据")
        return

    print()
    分隔线("=")
    print("学生成绩报告".center(60))
    分隔线("=")

    # 排名表
    print(f"{'名次':<4}{'姓名':<8}", end="")
    for 科 in 科目:
        print(f"{科:>7}", end="")
    print(f"{'总分':>8}{'平均':>8}{'等级':>6}")
    分隔线("-")

    for i, 人 in enumerate(排名(表), 1):
        打印一行(人, i)

    分隔线("-")

    # 各科统计
    print("各科统计：")
    统计 = 各科统计(表)
    for 科 in 科目:
        数据 = 统计[科]
        print(f"  {科}：平均 {数据['平均']:>5.1f}　"
              f"最高 {数据['最高']:>3}　最低 {数据['最低']:>3}")

    分隔线("-")

    # 分组
    print("分数段分布：")


    def 分档(人):
        均 = 平均分(人)
        if 均 >= 90:
            return "优秀"
        if 均 >= 80:
            return "良好"
        if 均 >= 60:
            return "及格"
        return "不及格"


    组 = 分组(表, 分档)
    for 档 in ["优秀", "良好", "及格", "不及格"]:
        if 档 in 组:
            print(f"  {档}：{len(组[档])} 人　"
                  f"{[人['姓名'] for 人 in 组[档]]}")
        else:
            print(f"  {档}：0 人")

    分隔线("-")

    # 预警
    print("需要关注：")
    有预警 = False
    for 科 in 科目:
        低的 = 某一科低于(表, 科, 60)
        if len(低的) > 0:
            有预警 = True
            print(f"  {科} 不及格：", end="")
            print("、".join(人["姓名"] for 人 in 低的))
    if not 有预警:
        print("  （没有不及格的）")

    分隔线("=")


