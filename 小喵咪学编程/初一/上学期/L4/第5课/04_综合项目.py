            # 各科分数
            for 科 in 科目:
                if 科 not in 条:
                    问题.append(f"{位置}（{条.get('姓名', '?')}）：缺「{科}」")
                    有错 = True
                    continue

                分 = 条[科]
                if not isinstance(分, (int, float)) or isinstance(分, bool):
                    问题.append(f"{位置}（{名}）：{科} 的「{分}」不是数字")
