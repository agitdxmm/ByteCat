    def 单科排名(表, 科目名):
        """按某科成绩降序，返回 [(名次, 记录), ...]。"""
        排好 = sorted(表, key=lambda 人: -人[科目名])
        return [(i, 人) for i, 人 in enumerate(排好, 1)]


    def 进步最大(旧表, 新表):
        """返回 (姓名, 进步分数)。"""
        旧分 = {人["姓名"]: 总分(人) for 人 in 旧表}

        最多名 = None
        最多进步 = -9999

        for 人 in 新表:
            名 = 人["姓名"]
            if 名 not in 旧分:
                continue
            进步 = 总分(人) - 旧分[名]
            if 进步 > 最多进步:
                最多进步 = 进步
                最多名 = 名

        return 最多名, 最多进步


    def 各科及格率(表):
        """返回 {科目: 及格率(百分比)}。"""
        结果 = {}
        for 科 in 科目:
            及格数 = 0
            for 人 in 表:
                if 人[科] >= 60:
                    及格数 += 1
            结果[科] = 及格数 / len(表) * 100
        return 结果


    def 找同分(表):
        """找出总分相同的人。"""
        分组表 = {}
        for 人 in 表:
            分组表.setdefault(总分(人), []).append(人["姓名"])

        return {分: 名字们 for 分, 名字们 in 分组表.items() if len(名字们) > 1}


    def 导出为行(表):
        """转成 "姓名,分1,分2,分3" 的列表。"""
        行们 = []
        for 人 in 表:
            部分 = [人["姓名"]]
            for 科 in 科目:
                部分.append(str(人[科]))
            行们.append(",".join(部分))
        return 行们


