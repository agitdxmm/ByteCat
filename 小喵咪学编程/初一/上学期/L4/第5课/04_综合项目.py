# ── 计算层 ──


def 总分(学生):
    """返回三科总分。"""
    总 = 0
    for 科 in 科目:
        总 += 学生[科]
    return 总


def 平均分(学生):
    """返回三科平均。"""
    return 总分(学生) / len(科目)


def 排名(表):
    """返回按总分降序排好的新列表。"""
    return sorted(表, key=lambda 人: -总分(人))


def 各科统计(表):
    """返回每科的平均、最高、最低。"""
    结果 = {}
    for 科 in 科目:
        分们 = [人[科] for 人 in 表]
        结果[科] = {
            "平均": sum(分们) / len(分们),
            "最高": max(分们),
            "最低": min(分们),
        }
    return 结果


def 分组(表, 分档函数):
    """按分档函数分组，返回 {档名: [记录, ...]}。"""
    组 = {}
    for 人 in 表:
        档 = 分档函数(人)
        组.setdefault(档, []).append(人)
    return 组


def 筛选(表, 条件函数):
    """返回满足条件的记录（新列表）。"""
    return [人 for 人 in 表 if 条件函数(人)]


# ── 查询层 ──


def 按名字查(表, 名字):
    """返回那个学生的记录，找不到返回 None。"""
    for 人 in 表:
         if 人["姓名"] == 名字:
             return 人
    return None


def 某一科低于(表, 科, 分数线):
    """返回某科低于分数线的人。"""
    return 筛选(表, lambda 人: 人[科] < 分数线)


# ── 显示层 ──


def 分隔线(字符="-", 宽度=64):
    print(字符 * 宽度)


def 表头():
    print(f"{'姓名':<8}", end="")
    for 科 in 科目:
        print(f"{科:>7}", end="")
    print(f"{'总分':>8}{'平均':>8}{'等级':>6}")


def 打印一行(学生, 名次=None):
    if 名次 is not None:
        print(f"{名次:<4}", end="")
    print(f"{学生['姓名']:<8}", end="")
    for 科 in 科目:
        print(f"{学生[科]:>7}", end="")
    print(f"{总分(学生):>8}{平均分(学生):>8.1f}{等级(平均分(学生)):>6}")


def 等级(分):
    if 分 >= 90:
        return "A"
    if 分 >= 80:
        return "B"
    if 分 >= 70:
        return "C"
    if 分 >= 60:
        return "D"
    return "E"


