def 插入计数(列表):
    """统计「挪动」次数。"""
    次数 = 0
    for i in range(1, len(列表)):
        当前 = 列表[i]
        j = i - 1
        while j >= 0 and 列表[j] > 当前:
            列表[j + 1] = 列表[j]
            j -= 1
            次数 += 1
        列表[j + 1] = 当前
    return 次数


