print("① 冒泡排序")


def 冒泡(列表, 显示过程=False):
    """原地冒泡排序。"""
    n = len(列表)
    for i in range(n - 1):
        if 显示过程:
            print(f"    第 {i + 1} 轮开始：{列表}")
        for j in range(n - 1 - i):
            if 列表[j] > 列表[j + 1]:
                列表[j], 列表[j + 1] = 列表[j + 1], 列表[j]
    return 列表


数据 = [5, 2, 8, 1, 9, 3]
print("  原数据：", 数据)
print("  排序过程：")
结果 = 冒泡(数据.copy(), 显示过程=True)
print("  结果：", 结果)

print("\n② 带「提前结束」优化的冒泡")


def 冒泡优化(列表):
    n = len(列表)
    for i in range(n - 1):
        交换过 = False
        for j in range(n - 1 - i):
            if 列表[j] > 列表[j + 1]:
                列表[j], 列表[j + 1] = 列表[j + 1], 列表[j]
                交换过 = True
        if not 交换过:
            print(f"    第 {i + 1} 轮没有交换，提前结束")
            break
    return 列表


