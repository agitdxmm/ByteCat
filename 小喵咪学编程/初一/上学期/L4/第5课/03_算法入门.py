冒泡优化(已排序.copy())

print("\n③ 选择排序")


def 选择(列表):
    n = len(列表)
    交换次数 = 0
    for i in range(n - 1):
        最小位置 = i
        for j in range(i + 1, n):
            if 列表[j] < 列表[最小位置]:
                最小位置 = j
        if 最小位置 != i:
            列表[i], 列表[最小位置] = 列表[最小位置], 列表[i]
            交换次数 += 1
    return 列表, 交换次数


数据 = [5, 2, 8, 1, 9, 3]
结果, 次数 = 选择(数据.copy())
print("  原数据：", 数据)
print("  结果：  ", 结果)
