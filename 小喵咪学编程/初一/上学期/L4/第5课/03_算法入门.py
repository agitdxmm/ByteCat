def 找前K(数据, k):
    """返回最大的 k 个（降序）。"""
    if k <= 0:
        return []
    前k = []
    for x in 数据:
        # 还没满，直接加
        if len(前k) < k:
            前k.append(x)
            前k.sort(reverse=True)
        # 满了，看能不能挤进去
        elif x > 前k[-1]:
            前k[-1] = x
            前k.sort(reverse=True)
    return 前k


