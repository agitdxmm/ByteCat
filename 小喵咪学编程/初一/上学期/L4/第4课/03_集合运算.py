r'''
════════════════════════════════════════════════════════
  L4 · 第 4 课 · 用法 3        集合运算
════════════════════════════════════════════════════════

集合最大的本事是「运算」—— 交集、并集、差集。

这几件事用列表做要写循环，用集合一行就行。

────────────────────────────────────────────────────────
【四种基本运算】
════════════════════════════════════════════════════════

        A = {1, 2, 3, 4}
        B = {3, 4, 5, 6}

    ── 交集 ∩：两个都有的 ──

        A & B       → {3, 4}

    ── 并集 ∪：合起来（去重）──

        A | B       → {1, 2, 3, 4, 5, 6}

    ── 差集 −：在 A 里但不在 B 里 ──

        A - B       → {1, 2}
        B - A       → {5, 6}

        ⚠ **差集没有交换律**，A - B 和 B - A 不一样。

    ── 对称差 △：只在一个里（不在两个里都有）──

        A ^ B       → {1, 2, 5, 6}

        就是「(A - B) 加上 (B - A)」，
        也叫「异或」—— 要么在 A，要么在 B，不能都在。

    ── 一张图 ──

        A = {1, 2, 3, 4}     B = {3, 4, 5, 6}

              A ∩ B
             ┌──┬──┐
         1 2 │3 4│ 5 6
             └──┴──┘
              ↑
           公共部分

        A | B = 全部六个
        A & B = 中间两个
        A - B = 左边两个
        A ^ B = 左边 + 右边（不含中间）

────────────────────────────────────────────────────────
【方法写法（等价）】
════════════════════════════════════════════════════════

    每种运算都有对应的方法：

        A.intersection(B)             同 A & B
        A.union(B)                    同 A | B
        A.difference(B)               同 A - B
        A.symmetric_difference(B)     同 A ^ B

    ── 为什么要记两套 ──

        运算符写法短，方法写法**能接任何可迭代对象**：

            A & [3, 4]           ❌ TypeError（列表不是集合）
            A.intersection([3, 4])   ✅ 能跑，返回 {3, 4}

        所以和列表、元组、字典的键做运算时，必须用方法。

    ── 还有一个区别 ──

        运算符**必须两边都是集合**。
        方法只要求「参数可迭代」。

        日常用哪个：
            · 两个集合 → 运算符（短）
            · 一边是列表 → 方法

────────────────────────────────────────────────────────
【判断关系：子集 / 超集 / 不相交】
════════════════════════════════════════════════════════

        A = {1, 2, 3}
        B = {1, 2, 3, 4, 5}

    ── 子集 ⊆ ──

        A <= B          → True      A 的每个元素都在 B 里
        A < B           → True      A 是 B 的「真子集」（B 还有多的）

        A.issubset(B)   → True      方法写法

    ── 超集 ⊇ ──

        B >= A          → True      B 包含 A 的所有元素
        B > A           → True      B 还有 A 没有的

        B.issuperset(A) → True

    ── 不相交 ──

        A.isdisjoint({7, 8})    → True    两个集合没有任何公共元素

        没有运算符写法，只能调方法。

    ── 一个实用的例子：权限检查 ──

        class 用户权限 = {"读", "写"}
        需要权限 = {"读"}

        if 需要 <= 用户权限:
            print("允许")

        —— 「需要的是不是用户拥有的子集」，这句话就是权限判断。

    ── 自己和自己 ──

        A <= A      → True     （每个集合都是自己的子集）
        A < A       → False    （不是真子集）

    ── 空集 ──

        set() <= 任何集合    → True     （空集是所有人的子集）
        set() < A            → True     （A 不为空的话）

────────────────────────────────────────────────────────
【原地运算：改自己】
════════════════════════════════════════════════════════

    上面那些运算都**返回新集合**，原来的不变。

    想直接改原集合，用 `=` 版本：

        A = {1, 2, 3, 4}
        A &= {3, 4}         → A 变成 {3, 4}（原地）
        A |= {5}            → A 变成 {3, 4, 5}
        A -= {3}            → A 变成 {4, 5}
        A ^= {4, 6}         → A 变成 {5, 6}

    ── 对应的方法 ──

        A.intersection_update(B)
        A.update(B)                  ← 注意：update 就是「并集原地运算」
        A.difference_update(B)
        A.symmetric_difference_update(B)

    ⚠ 集合的 `update` 是「并集」，不是「覆盖」。
       字典的 `update` 是「覆盖」。**同名不同义，别混。**

    ── 返回值的规律 ──

        运算符（`&`、`|`、`-`、`^`）      → 新集合
        增强赋值（`&=`、`|=`、`-=`、`^=`）→ 改原集合，返回 None
        方法（intersection 等）           → 新集合
        带 _update 的方法                 → 改原集合

    —— 和列表的 `+` vs `+=`、`sort` vs `sorted` 是同一个套路：
       **「新建」还是「原地」，要看清楚。**

────────────────────────────────────────────────────────
【复杂例子：找出「只出现过一次」的元素】
════════════════════════════════════════════════════════

    需求：一个列表里，哪些元素只出现了一次？

        a = [1, 2, 2, 3, 4, 4, 5]

    分析：
        · 出现过的所有值 = set(a) = {1,2,3,4,5}
        · 出现不止一次的值 = 需要找
        · 「只出现一次」= 所有值 - 重复的值

    ── 写法一：用字典计数 ──

        次数 = {}
        for x in a:
            次数[x] = 次数.get(x, 0) + 1

        只一次 = [x for x, n in 次数.items() if n == 1]
        → [1, 3, 5]

    ── 写法二：用集合 ──

        看过 = set()
        重复 = set()
        for x in a:
            if x in 看过:
                重复.add(x)
            else:
                看过.add(x)

        只一次 = 看过 - 重复
        → {1, 3, 5}

    ── 两种对比 ──

        字典法：还要数具体次数（2 次和 5 次都是「重复」）
        集合法：只区分「见过/重复」，更省内存

    **如果你只关心「一次还是多次」，集合法更直接。**
    **如果要具体次数，字典法。**

────────────────────────────────────────────────────────
【一个反直觉的地方：集合运算的结果顺序】
════════════════════════════════════════════════════════

        {3, 1, 2} & {2, 3, 9}       → {2, 3}（顺序不一定）

    结果还是集合，还是无序。

    如果结果要给用户看，记得 `sorted()`：

        sorted({3, 1, 2} & {2, 3, 9})     → [2, 3]

────────────────────────────────────────────────────────
【集合运算的复杂度】
════════════════════════════════════════════════════════

    集合运算非常快：

        A & B      约 O(min(len(A), len(B)))
        A | B      约 O(len(A) + len(B))
        判断 in    约 O(1)

    对比用列表做同样的事：

        交集（两层循环）：O(n × m)
        判断 in：O(n)

    数据量 10000 时：
        列表交集：约 1 亿次操作
        集合交集：约 1 万次操作

    **差 1 万倍。**

    所以：只要涉及「两个集合的关系」，就用集合，别用列表硬写。
'''

