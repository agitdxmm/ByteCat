def 只出现一次(列表):
    """返回只出现过一次的元素（集合）。"""
    看过 = set()
    重复 = set()
    for x in 列表:
        if x in 看过:
            重复.add(x)
        else:
            看过.add(x)
    return 看过 - 重复


