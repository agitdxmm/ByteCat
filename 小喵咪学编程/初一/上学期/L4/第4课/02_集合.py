r'''
════════════════════════════════════════════════════════
  L4 · 第 4 课 · 用法 2        集合
════════════════════════════════════════════════════════

列表有顺序、可以重复。字典有键值对。

集合（set）是第三种：**没有顺序、不能重复。**

它解决两个问题：去重、快速判断「有没有」。

────────────────────────────────────────────────────────
【形状】
════════════════════════════════════════════════════════

        水果 = {"苹果", "香蕉", "橘子"}

    花括号、逗号，和字典长得像，但没有冒号。

    ── 区分 ──

        {"a": 1}        字典（有冒号）
        {"a", "b"}      集合（没冒号）
        {}              空字典！不是空集合
        set()           空集合

    ⚠️ `{}` 永远是空字典。想要空集合必须写 `set()`。

────────────────────────────────────────────────────────
【特点一：不能重复】
════════════════════════════════════════════════════════

        a = {1, 2, 2, 3, 3, 3}
        print(a)        → {1, 2, 3}

    重复的自动去掉。

    ── 这就是「去重」最常用的写法 ──

        分数 = [85, 92, 85, 78, 92, 100]
        不重复的 = set(分数)
        print(不重复的)      → {85, 92, 78, 100}

        想要列表的话再转回来：
            list(set(分数))  → [85, 92, 78, 100]（顺序可能变）

    ⚠️ **转成集合再转回来，顺序会丢。**

        list(set([3, 1, 2]))    可能得到 [1, 2, 3] 或 [3, 1, 2]
        因为集合本身无序。

        要保顺序去重，得用别的办法：

            见过 = set()
            结果 = []
            for x in 分数:
                if x not in 见过:
                    见过.add(x)
                    结果.append(x)

        （或者用字典：`list(dict.fromkeys(分数))` —— 字典保序，
          fromkeys 会去重。这个技巧很实用。）

────────────────────────────────────────────────────────
【特点二：没有顺序】
════════════════════════════════════════════════════════

        水果 = {"苹果", "香蕉", "橘子"}
        print(水果)

    输出的顺序**可能每次不一样**（对字符串集合来说）。

    （对整数集合，CPython 常常看起来是「从小到大」，
      但那是内部实现的结果，**不要依赖它**。）

    ── 所以不能做的事 ──

        ❌ 水果[0]              集合不支持索引
        ❌ 水果[1:2]            不支持切片
        ❌ 水果.sort()          没这个方法
        ❌ 水果.append(...)     没这个方法

    ── 能做的事 ──

        ✅ 遍历（但顺序不定）
        ✅ in 判断
        ✅ len()
        ✅ 加、删
        ✅ 集合运算（下一节）

    ── 要「有序的集合」怎么办 ──

        用 `sorted(集合)`，得到排好序的列表。

────────────────────────────────────────────────────────
【增加元素】
════════════════════════════════════════════════════════

    ── add：加一个 ──

        s = {1, 2}
        s.add(3)
        print(s)        → {1, 2, 3}

        加已有的元素不报错，也不变：

        s.add(3)        → 还是 {1, 2, 3}

        （这一点和列表的 append 不同 —— append 会真的加重复。）

    ── update：加一堆 ──

        s = {1, 2}
        s.update([3, 4, 5])
        print(s)        → {1, 2, 3, 4, 5}

        重复的自动跳过。

    （注意：集合的 update 和字典的 update 名字一样，
      但行为不同 —— 集合的 update 是「合并进去」。）

────────────────────────────────────────────────────────
【删除元素】
════════════════════════════════════════════════════════

    ── remove：删指定元素，不存在会报错 ──

        s = {1, 2, 3}
        s.remove(2)
        print(s)        → {1, 3}

        s.remove(99)
        → KeyError: 99

    ── discard：删指定元素，不存在不报错 ──

        s.discard(99)   → 什么都不发生

    **remove 和 discard 的区别只有这一个：删不存在的元素报不报错。**

    ── pop：随便删一个 ──

        s = {1, 2, 3}
        x = s.pop()
        print(x)        → 可能是 1、2、3 中任意一个
        print(s)

        「随便」不是玩笑 —— 集合无序，所以你不知道会删掉哪个。

        **别用 pop 做业务逻辑**，除非你真的不在乎删哪个。

    ── clear：清空 ──

        s.clear()

────────────────────────────────────────────────────────
【in：判断有没有（这是集合的强项）】
════════════════════════════════════════════════════════

        s = {1, 2, 3}
        2 in s          → True
        99 in s         → False

    ── 为什么说是强项 ──

        集合判断 `in` 是**一步到位**的（内部用哈希表），
        不管集合里有 10 个还是 1000 万个元素，都是一次操作。

        列表判断 `in` 要**遍历**，元素越多越慢。

    ── 实测对比 ──

        在一个有 100 万个元素的列表里判断 1000 次：
            列表：约 0.5 秒
            集合：约 0.0001 秒

    ── 所以 ──

        **如果一段代码频繁做「在不在里面」的判断，
        而且数据量很大，就该用集合（或字典）。**

        典型场景：
            · 判断用户输入是不是敏感词
            · 判断 IP 是不是在黑名单
            · 判断某个 ID 是不是处理过

    ── 但注意 ──

        数据量小（几十个）的时候，列表和集合没差别。
        别为了「可能快」把什么都塞进集合 ——
        集合没有顺序，用起来不如列表方便。

────────────────────────────────────────────────────────
【元素必须「可哈希」】
════════════════════════════════════════════════════════

        可以放：数字、字符串、元组、True/False、None
        不能放：列表、字典、集合

        举例：

            {1, "a", (2, 3)}           ✅
            {[1, 2]}                   ❌ TypeError: unhashable type: 'list'

    ── 和字典的键是同一个规则 ──

        字典的键、集合的元素，都必须是「不可变」的。
        因为内部靠哈希值定位，可变的东西哈希值不稳定。

    ── 想放「一组坐标」怎么办 ──

        用元组，不用列表：

            {(0, 0), (3, 4), (1, 1)}      ✅
            {[0, 0], [3, 4]}              ❌

────────────────────────────────────────────────────────
【遍历集合】
════════════════════════════════════════════════════════

        for x in {3, 1, 2}:
            print(x)

    能跑，但**顺序不确定**。

    ── 想按顺序遍历 ──

        for x in sorted(集合, reverse=True):
            print(x)

    ── 想带序号遍历 ──

        for i, x in enumerate(sorted(集合), 1):
            print(f"{i}. {x}")

────────────────────────────────────────────────────────
【一个常见误解：「集合没顺序」到底什么意思】
════════════════════════════════════════════════════════

    有人会做这个实验：

        a = {3, 1, 2}
        print(a)        → {1, 2, 3}

        b = {3, 1, 2}
        print(b)        → {1, 2, 3}

    两次都一样，看起来「有顺序啊」。

    ── 但这不是保证 ──

        对整数小集合，CPython 的哈希函数让它们恰好按大小排列。
        换成字符串就乱了：

            {"z", "a", "m"}      可能输出 {'m', 'z', 'a'}

        而且在不同的 Python 版本、不同的运行环境，
        顺序可能不同。

    **「碰巧有序」和「保证有序」是两回事。**

    依赖「碰巧」的代码，换个环境就崩。

    ── 所以 ──

        任何时候需要顺序，都显式用 `sorted()`。
        不要指望集合的遍历顺序。
'''

