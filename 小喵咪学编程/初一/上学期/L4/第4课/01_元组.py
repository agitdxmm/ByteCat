r'''
════════════════════════════════════════════════════════
  L4 · 第 4 课 · 用法 1        元组
════════════════════════════════════════════════════════

前面已经默默用过很多次元组了：

    return a + b, a * b         L3 第 1 课的「返回多个值」
    for 名, 分 in 成绩.items()  L4 第 3 课的 items()
    (i, j) = (0, 1)             坐标

这一节把它讲清楚。

────────────────────────────────────────────────────────
【元组的形状】
════════════════════════════════════════════════════════

        坐标 = (3, 4)
        颜色 = (255, 128, 0)
        单人 = (92,)              ← 注意那个逗号
        空 = ()

    圆括号，逗号分隔。和列表几乎一样，除了——

    ── 元组不能改 ──

        坐标[0] = 10
        → TypeError: 'tuple' object does not support item assignment

    「不可变」的意思是：

        · 不能改某个元素
        · 不能 append / remove / pop
        · 不能 sort / reverse
        · 没有任何「修改类」的方法

    ── 能做的操作 ──

        · 索引：坐标[0]
        · 切片：坐标[0:1]
        · len()
        · in
        · count() / index()
        · 遍历
        · 拼接 a + b、重复 a * 3（生成新的元组）

    **除了「改」，其他和列表一样。**

────────────────────────────────────────────────────────
【为什么要「不能改」】
════════════════════════════════════════════════════════

    这可能让人困惑：不能改有什么好处？

    ── 好处一：安全 ──

        坐标 (3, 4) 传进一个函数，
        你不用担心函数偷偷把它改成 (999, 999)。

        （列表就有这个风险，L3 第 2 课第 4 节讲过。）

    ── 好处二：能当字典的键 ──

        L4 第 3 课讲过：字典的键必须是「不可变」的。

            {(1, 2): "起点", (3, 4): "终点"}      ✅ 元组可以
            {[1, 2]: "起点"}                      ❌ 列表不行

        为什么：字典内部靠「哈希值」定位。
        可变的东西哈希值会变，就没法定位了。

        （错误信息：TypeError: unhashable type: 'list'）

    ── 好处三：语义清楚 ──

        `(3, 4)` 一眼就知道是「一对坐标，不会变」。
        `[3, 4]` 让人以为「这是个可以增删的列表」。

        **用不可变的类型表达「不该变的数据」，是给读代码的人一个信号。**

    ── 好处四：快一点（但别在意）──

        元组比列表占内存少、创建快。
        但绝大多数场景差别可以忽略，别为了性能选元组。

────────────────────────────────────────────────────────
【最容易错的：单元素元组】
════════════════════════════════════════════════════════

        a = (5)         → 5，是个整数
        b = (5,)        → (5,)，才是元组
        c = 5,          → (5,)，也行

    **括号不是关键，逗号才是。**

    ── 为什么会这样 ──

        `(5)` 在 Python 眼里就是「一个加了括号的 5」，
        括号只是改变优先级，不是元组的标志。

        真正决定「是不是元组」的是**逗号**：

            5,            → (5,)
            5, 6          → (5, 6)
            (5, 6)        → (5, 6)
            (5, 6,)       → (5, 6)

    ── 这个坑很实际 ──

        def f():
            return 5,         ← 返回元组 (5,)

        def g():
            return 5          ← 返回整数 5

        少个逗号，返回的东西完全不同。

        而且 `len(f())` 是 1，`len(g())` 会报 TypeError。

────────────────────────────────────────────────────────
【解包：把元组拆成变量】
════════════════════════════════════════════════════════

    这是元组最有用的特性。

        a, b = (1, 2)
        print(a)        → 1
        print(b)        → 2

    ── 左边变量的个数必须和右边一致 ──

        a, b = (1, 2, 3)
        → ValueError: too many values to unpack (expected 2)

        a, b, c = (1, 2)
        → ValueError: not enough values to unpack (expected 3, got 2)

    ── 用 * 收「剩下的」──

        a, *其余 = (1, 2, 3, 4)
        → a = 1，其余 = [2, 3, 4]

        *开头, 最后一个 = (1, 2, 3)
        → 开头 = [1, 2]，最后一个 = 3

    （`*` 收的永远是**列表**，不是元组。）

    ── 交换变量就是用解包 ──

        a, b = b, a

        右边的 `b, a` 先打包成元组 `(b, a)`，
        然后解包赋给 `a, b`。

        所以不需要临时变量。

    ── 遍历时解包 ──

        for 名, 分 in 成绩.items():
            ...

        `items()` 每轮给出 `(键, 值)` 这个元组，
        `for 名, 分` 就是当场拆开。

        **这就是为什么 items() 能这么写。**

────────────────────────────────────────────────────────
【元组和列表的互相转换】
════════════════════════════════════════════════════════

        list((1, 2, 3))     → [1, 2, 3]
        tuple([1, 2, 3])    → (1, 2, 3)

    ── 什么时候需要转 ──

        元组要排序？先转列表：

            sorted((3, 1, 2))         → [1, 2, 3]     （sorted 直接能给）
            list((3, 1, 2)).sort()    → 排好了，但结果在列表里

        列表要当字典的键？先转元组：

            坐标 = [3, 4]
            地图 = {}
            地图[tuple(坐标)] = "起点"      ✅
            地图[坐标] = "起点"             ❌ unhashable

    ── 转成什么，由你的需求决定 ──

        要改 → 列表
        要当键/要保持不变 → 元组

────────────────────────────────────────────────────────
【命名元组（进阶，知道就行）】
════════════════════════════════════════════════════════

    坐标[0] 和 坐标[1]，看不出哪个是 x 哪个是 y。

    可以给它们起名字：

        from collections import namedtuple

        点 = namedtuple("点", ["x", "y"])
        p = 点(3, 4)
        print(p.x)         → 3
        print(p.y)         → 4

    这就是「命名元组」，读起来清楚多了。

    ── 但它要 import ──

        `from collections import namedtuple` 是导入语句，
        L5 会讲 import 是什么。

        现在先知道有这个功能，遇到时能认出来就行。

    ── 更简单的替代：用字典 ──

        p = {"x": 3, "y": 4}
        print(p["x"])

        字典能起名字，而且能改。缺点是占内存多、不能当「不可变的值」用。

    **数据只有两三个字段、要“不可变” → 命名元组
      字段多、要能改 → 字典**

────────────────────────────────────────────────────────
【什么时候用元组，什么时候用列表】
════════════════════════════════════════════════════════

    ── 用元组 ──

        ① 数据天然固定
           坐标 (x, y)、RGB 颜色、一年 12 个月

        ② 要作为字典的键
           `{(1,2): "起点"}`

        ③ 函数返回多个值
           `return 商, 余数`

        ④ 不打算改的「一堆值」
           比如常量表

    ── 用列表 ──

        ① 要增删改
           待办清单、购物车

        ② 元素个数不定
           读到多少条就是多少条

        ③ 要排序、要去重、要各种操作

    ── 一句话 ──

        **元组是「值」，列表是「容器」。**

        坐标是个「值」，它本身不应该变；
        购物车是个「容器」，随时可能加东西。

    ── 一个实际判断 ──

        如果你写了一段代码，里面全是 `a[0]`、`a[1]`、`a[2]`，
        而且从来没改过它 —— 那它可能本来就该是元组
        （或者该换成字典/命名元组，让字段有名字）。
'''

