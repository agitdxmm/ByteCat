r'''
════════════════════════════════════════════════════════
  L4 · 第 4 课 · 用法 4        四种结构对比
════════════════════════════════════════════════════════

L4 学了四种「装东西」的结构：

    列表 list    [1, 2, 3]
    元组 tuple   (1, 2, 3)
    字典 dict    {"a": 1}
    集合 set     {1, 2, 3}

这一节把它们摆在一起，搞清楚「什么时候用哪个」。

────────────────────────────────────────────────────────
【总表】
════════════════════════════════════════════════════════

    ┌────────┬────────┬────────┬────────┬────────┐
    │        │ 列表   │ 元组   │ 字典   │ 集合   │
    ├────────┼────────┼────────┼────────┼────────┤
    │ 写法   │ [ ]    │ ( )    │ {k:v}  │ { }    │
    │ 有序   │ ✔      │ ✔      │ ✔(插入)│ ✘      │
    │ 可重复 │ ✔      │ ✔      │ 键不可 │ ✘      │
    │ 可修改 │ ✔      │ ✘      │ ✔      │ ✔      │
    │ 能索引 │ ✔      │ ✔      │ ✘      │ ✘      │
    │ 按名查 │ ✘      │ ✘      │ ✔      │ ✘      │
    │ 快速in │ ✘      │ ✘      │ ✔(键)  │ ✔      │
    │ 能当键 │ ✘      │ ✔      │ ✘      │ ✘      │
    └────────┴────────┴────────┴────────┴────────┘

    ── 逐行解释 ──

        有序：元素有固定的顺序，能用索引取
        可重复：同一个值能出现多次
        可修改：能加、删、改
        能索引：能用 [0] 这种
        按名查：能用「名字」直接找到值
        快速 in：判断「有没有」是不是一步到位
        能当键：能不能用来当字典的键

────────────────────────────────────────────────────────
【一句话概括每个】
════════════════════════════════════════════════════════

    列表：**一堆有顺序、会变的东西**
          待办清单、成绩列表、购物车

    元组：**一整个不该变的东西**
          坐标、颜色、日期+温度、多个返回值

    字典：**按名字查的东西**
          姓名→成绩、省份→省会、配置项

    集合：**只关心「有没有」的东西**
          去重、权限、黑名单、两个名单的对比

────────────────────────────────────────────────────────
【选择流程】
════════════════════════════════════════════════════════

    拿到一个问题，按顺序问：

        ① 需要「按名字找」吗？
           需要 → 字典
           不需要 → 下一步

        ② 只需要知道「有没有」，不在乎顺序和个数吗？
           是的 → 集合
           不是 → 下一步

        ③ 会增删改吗？
           会 → 列表
           不会 → 下一步

        ④ 是一整个数据（几个字段绑在一起）吗？
           是 → 元组
           不是 → 列表（默认选它最灵活）

    ── 最后一步的说明 ──

        「拿不准就用列表」是个合理的默认。

        列表最灵活（能改、能排序、能切片），
        虽然可能不是最优，但基本都能用。

        先用列表把功能做出来，
        等发现「这里查得太慢了」或者「这里不该被改」，
        再换成集合或元组。

    **过早优化是万恶之源。** 先让它对，再让它好。

────────────────────────────────────────────────────────
【互相转换】
════════════════════════════════════════════════════════

    ── 列表 ↔ 元组 ──

        tuple([1, 2, 3])      → (1, 2, 3)
        list((1, 2, 3))       → [1, 2, 3]

    ── 列表/元组 → 集合（去重）──

        set([1, 2, 2, 3])     → {1, 2, 3}
        set((1, 2, 2))        → {1, 2}

    ── 集合 → 列表（能排序了）──

        sorted({3, 1, 2})     → [1, 2, 3]
        list({3, 1, 2})       → 顺序不定

    ── 列表 → 字典 ──

        dict([("a", 1), ("b", 2)])      → {'a': 1, 'b': 2}
        dict(zip(["a", "b"], [1, 2]))   → {'a': 1, 'b': 2}

    ── 字典 → 列表 ──

        list(d)                → 键的列表
        list(d.keys())         → 同上
        list(d.values())       → 值的列表
        list(d.items())        → (键, 值) 元组的列表

    ── 字典的键 → 集合 ──

        set(d.keys())          → 键的集合（可以快速判断）

    ── 一个常用套路 ──

        列表去重但保留顺序：

            list(dict.fromkeys(原列表))

        原理：`dict.fromkeys` 建一个「键来自列表、值都是 None」的字典，
        字典的键不重复，而且保留插入顺序。

        最后一转列表，就得到「去重 + 保序」的结果。

────────────────────────────────────────────────────────
【同一个问题的四种解法】
════════════════════════════════════════════════════════

    需求：存 5 个学生的成绩，能查某个人的分数。

    ── 列表 ──

        数据 = [("张三", 92), ("李四", 88), ("王五", 95)]

        def 查分(数据, 名字):
            for 名, 分 in 数据:
                if 名 == 名字:
                    return 分
            return None

        查一次要遍历。3 个人无所谓，1000 个人就慢了。

    ── 元组 ──

        数据 = (("张三", 92), ("李四", 88), ("王五", 95))

        查法和列表一样，好处是「不会被意外修改」。

    ── 字典 ⭐ ──

        数据 = {"张三": 92, "李四": 88, "王五": 95}
        数据["李四"]        → 88

        一步到位。

    ── 集合 ──

        集合不能存「名字→分数」的对应关系，只能用来看「谁在名单里」。

        数据 = {"张三", "李四", "王五"}
        "李四" in 数据      → True

    —— 结论：**「按名字查」的需求，字典是唯一正确的选择。**

       其他三种要么慢（列表/元组），要么做不到（集合）。

────────────────────────────────────────────────────────
【一个真实场景的拆解】
════════════════════════════════════════════════════════

    需求：做一个「班级管理系统」。

        ① 存所有学生
           → 列表（人数会变）

        ② 每个学生的信息
           → 字典（有名字、分数等字段）

        ③ 每个学生的各科成绩
           → 字典（科目→分数）

        ④ 所有科目名的集合
           → 集合（去重，判断「有没有这门课」）

        组合起来：

            班级 = [
                {
                    "名字": "张三",
                    "成绩": {"语文": 92, "数学": 88},
                },
                {
                    "名字": "李四",
                    "成绩": {"语文": 78, "数学": 90},
                },
            ]

        再加一个：

            全部科目 = set()
            for 学生 in 班级:
                全部科目 |= set(学生["成绩"].keys())

        现在「全部科目」是 {'语文', '数学'}。

    ── 这个结构为什么这么设计 ──

        · 外层列表：学生会有增减
        · 每个学生是字典：字段有名字，加字段不用改代码
        · 成绩是字典：按科目查分数
        · 科目集合：快速判断「有没有这门课」、求交集（共同科目）

    **每种结构都在解决它最擅长的那部分问题。**

────────────────────────────────────────────────────────
【性能上的差异（知道大概就行）】
════════════════════════════════════════════════════════

    操作                    列表      字典/集合
    ─────────────────────────────────────────────
    x in 容器（n 个元素）   O(n)      O(1)
    按下标取                 O(1)      不支持
    按名字取                不支持     O(1)
    末尾追加                 O(1)      不适用
    中间插入                 O(n)      不适用
    删除指定值               O(n)      O(1)（集合）
    排序                     O(n log n) 不适用

    ── 关键的那一行 ──

        **`in` 判断：列表 O(n)，字典/集合 O(1)**

        意思就是：100 万个元素时，
        列表要检查最多 100 万次，字典一步到位。

        这就是为什么「判断有没有」要用集合。

    ── 但也别神化 ──

        100 个元素以内，列表和集合的速度差别你根本感觉不到。
        这时候「代码好读」比「快 0.0001 秒」重要得多。

        **数据量小的时候，选你最顺手的那个。**

────────────────────────────────────────────────────────
【几个常见误区】
════════════════════════════════════════════════════════

    ❌ 误区一：「集合能替代列表」

       集合没有顺序、不能索引、不能有重复。
        大多数「列表的活」它干不了。

        它只在「去重」和「快速判断有没有」这两个场景有用。

    ❌ 误区二：「元组比列表快，所以都用元组」

        元组确实快一点点（创建和访问）。
        但如果你需要增删改，元组根本做不到。

        **选类型看需求，不看性能。**

    ❌ 误区三：「字典的键必须是有意义的字符串」

        数字、元组、True/False 都能当键。

            {1: "周一", 2: "周二"}          数字当键
            {(0,0): "起点"}                元组当键

    ❌ 误区四：「嵌套越深越好」

        三层以上的嵌套（字典里有列表，列表里有字典，字典里还有列表）
        读起来非常痛苦。

            data["班级"]["学生"][0]["成绩"]["语文"]

        这种代码写的时候爽，改的时候想哭。

        超过三层就该考虑「拆成几个函数分别处理」。

    ❌ 误区五：「一定要用最『高级』的结构」

        有人的字典只有三个固定键，却非要写成：

            {"a": 1, "b": 2, "c": 3}

        其实用元组 `(1, 2, 3)` 加解包更清楚：

            a, b, c = (1, 2, 3)

        **结构越简单越好。**
'''

