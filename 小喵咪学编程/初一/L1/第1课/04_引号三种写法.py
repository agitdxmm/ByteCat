r"""
════════════════════════════════════════════════════════
  L1 · 第 1 课 · 用法 4   引号的三种写法
════════════════════════════════════════════════════════

【这个用法干什么】
    把一段文字包起来，同时处理「文字本身就有引号」的情况。

【三种引号】

    "双引号"      最常用
    '单引号'      和双引号完全等价，只是长得不同
    '''三引号'''  可以跨行，也可以当多行注释用

【铁律：外双内单，外单内双】

    文字里有双引号  →  外面用单引号
    文字里有单引号  →  外面用双引号
    两种都有        →  用三引号

    写 "他说："你好"" —— 不行。
    Python 从第一个 " 开始，到「你好」前面那个 " 就认为字符串结束了，
    后面剩下的 你好"" 全是语法垃圾，直接 SyntaxError。

【三引号的特殊能力】
    能直接跨行写，不用 \n。

【今天最容易犯的错】
    中文引号 “ ” 和英文引号 " " 长得像，但不是同一个字符。
    Python 只认英文的。中文引号一律报：

        SyntaxError: invalid character '“' (U+201C)

    你之前已经撞过一次了 —— U+FF08 那个全角括号，一个道理。
"""

