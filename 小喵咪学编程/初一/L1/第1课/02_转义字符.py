r"""
════════════════════════════════════════════════════════
  L1 · 第 1 课 · 用法 2   转义字符（反斜杠）
════════════════════════════════════════════════════════

【这个用法干什么】
    在字符串里插入「看不见的字符」，或者插入本来打不出来的符号。

【原理】
    字符串里的反斜杠 \ 是一个开关。
    它说：我后面这个字符不是普通字符，请按特殊含义处理。

    所以 —— 反斜杠后面跟着谁，就决定了变成什么。

【四个必会的】

    \n     换行        New line
    \t     制表符      Tab，用来对齐
    \\     反斜杠本身  想打印一个 \ 就得写两个
    \"     双引号本身  想在 " " 里面再放 "

【为什么 \ 要写成 \\ 】
    因为 \ 是开关。你写一个 \，Python 会以为你要转义下一个字符。
    想让它老老实实当一个反斜杠，就得再拿一个 \ 把它的开关身份废掉。

【和上一课那个 U+202E 的关系】
    你玩过的 "\u202e" 也是转义 —— \u 后面跟 4 位十六进制，
    表示一个 Unicode 码点。
    转义序列的共同点：源码里好多个字符，进到字符串里只剩 1 个。
"""

