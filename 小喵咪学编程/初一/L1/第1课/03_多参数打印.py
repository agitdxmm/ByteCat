r"""
════════════════════════════════════════════════════════
  L1 · 第 1 课 · 用法 3   print 的多参数
════════════════════════════════════════════════════════

【这个用法干什么】
    一次打印多个东西，并且控制它们之间怎么隔开、结尾怎么收。

【三个位置】
    1. 逗号    print("a", "b")     给 print 塞多个东西
    2. sep=    中间用什么隔开       默认是一个空格
    3. end=    结尾放什么           默认是换行 \n

【写法】
    print(东西1, 东西2, ..., sep="隔开符", end="结尾符")

    sep 和 end 是「关键字参数」——名字必须写全，不能省。

【默认行为】
    print("a", "b")        输出  a b
    print("a", "b")        输出  a b 然后换行

    sep 默认 " "（空格），end 默认 "\n"（换行）。
    你以为 print 只会加换行，其实它先加空格再加换行。
"""

# ─────────────────────────────────────────
#  示例
# ─────────────────────────────────────────

print("2026", "11", "07")

print("2026", "11", "07", sep="-")

print("2026", "11", "07", sep="/")

print("加载中", end="")
print("...完成")

print("A", "B", "C", sep="", end=" | ")
print("D", "E", "F")


