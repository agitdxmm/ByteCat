r"""
════════════════════════════════════════════════════════
  L1 · 第 1 课 · 用法 1      print 输出
════════════════════════════════════════════════════════

这一节把 print 讲完 —— 不是讲一种写法，是讲它所有的写法。

────────────────────────────────────────────────────────
【基本形状】
────────────────────────────────────────────────────────

    print(东西1, 东西2, ..., sep="隔开符", end="结尾符")

    括号里能放三种数量的东西：

        一个        print("你好")
        多个        print("a", "b", "c")
        零个        print()              ← 打印一个空行

────────────────────────────────────────────────────────
【两个可选参数】
────────────────────────────────────────────────────────

    sep   多个东西之间用什么隔开      默认 " "  一个空格
    end   打印完之后末尾放什么        默认 "\n" 一个换行

    写法是 名字=值，名字必须写全，不能省成 print(a, b, "-")。

────────────────────────────────────────────────────────
【最重要的一句：print 不会自动换行】
────────────────────────────────────────────────────────

    很多人以为「print 的使命就是换行」。不是。

    它只是在末尾默认放了一个 "\n"。把 end 改掉，换行就消失：

        print("A", end="")
        print("B")              →  AB

    所谓「不换行」，本质上只是「末尾那个字符不是 \n 而已」。

────────────────────────────────────────────────────────
【顺序：先拼内容，再补结尾】
────────────────────────────────────────────────────────

    print("a", "b", "c", sep="-", end="!")

    执行顺序：
        1. 把三个东西按 sep 拼起来    →  a-b-c
        2. 在后面接上 end             →  a-b-c!
        3. 送到屏幕

    所以 sep 管「中间」，end 管「末尾」，两者互不干涉。

────────────────────────────────────────────────────────
【顺带一件事：print 会给你一个东西】
────────────────────────────────────────────────────────

    x = print("hi")

    屏幕上出 hi，然后 x 变成 None。
    print 有返回值，值是 None（表示「没有值」）。
    REPL 里敲 print("hi") 会看到 hi 和 None 两行，就是这个原因。
    现在不用管，知道有这回事就行。
"""

