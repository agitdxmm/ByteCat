def 整数开方(n):
    左, 右 = 0, n
    答案 = 0
    while 左 <= 右:
        中 = (左 + 右) // 2
        if 中 * 中 <= n:
            答案 = 中
            左 = 中 + 1
        else:
            右 = 中 - 1
    return 答案


