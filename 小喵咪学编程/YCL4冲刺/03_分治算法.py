def 快排计数(a):
    """返回 (排序结果, 比较次数)。"""
    次数 = [0]

    def 排(arr):
        if len(arr) <= 1:
            return arr
        基准 = arr[0]
        小 = []
        等 = []
        大 = []
        for x in arr[1:]:
            次数[0] += 1
            if x < 基准:
                小.append(x)
            elif x > 基准:
                大.append(x)
            else:
                等.append(x)
        return 排(小) + [基准] + 等 + 排(大)

    结果 = 排(a)
    return 结果, 次数[0]


