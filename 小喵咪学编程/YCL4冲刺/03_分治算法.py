def 分治最大(a):
    if len(a) == 1:
        return a[0]
    中 = len(a) // 2
    左最大 = 分治最大(a[:中])
    右最大 = 分治最大(a[中:])
    return 左最大 if 左最大 > 右最大 else 右最大


