    def 合并(左, 右):
        结果 = []
        i = 0
        j = 0

        while i < len(左) and j < len(右):
            if 左[i] <= 右[j]:
                结果.append(左[i])
                i = i + 1
            else:
                结果.append(右[j])
                j = j + 1

        # 剩下的那段，用 while 搬（题目不许用 extend）
        while i < len(左):
            结果.append(左[i])
            i = i + 1

        while j < len(右):
            结果.append(右[j])
            j = j + 1

        return 结果


    def 归并排序(a):
        if len(a) <= 1:
            return a
        中 = len(a) // 2
        return 合并(归并排序(a[:中]), 归并排序(a[中:]))


