def 计数冒泡(a):
    arr = list(a)
    c = 0
    n = len(arr)
    for i in range(n):
        for j in range(n - 1 - i):
            c += 1
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
    return c


