r'''
════════════════════════════════════════════════════════
  YCL4 · 冲刺 · 第 1 讲        lambda 与函数进阶
════════════════════════════════════════════════════════

这一讲补的是考纲里「函数概念」漏掉的东西。

L3 学完你应该会：定义函数、传参、返回值、作用域、递归。
还差一块：【匿名函数 lambda】。

教材里 lambda 出现过很多次（`sorted(key=lambda x: x[1])`），
但从来没正经讲过它是什么。这一讲讲透。

────────────────────────────────────────────────────────
【lambda 是什么】
────────────────────────────────────────────────────────

一句话：**没有名字的函数，只写一行。**

    def 加倍(x):
        return x * 2

    加倍 = lambda x: x * 2

这两个完全等价。左边三行，右边一行。

拆开看右边的结构：

    加倍  =  lambda  x  :  x * 2
    ↑        ↑       ↑   ↑
    名字     关键字  参数  表达式（自动 return）

三个要点：

    ① lambda 后面跟参数，跟 def 一样（可以多个，可以带默认值）
    ② 冒号后面是**一个表达式**，不是语句块
    ③ 这个表达式的值，就是函数的返回值 —— 不用写 return

    ── 为什么叫「匿名」 ──

        因为它本来就不需要名字。上面写 `加倍 = lambda ...`
        是为了演示等价，实际用的时候通常直接塞进别的地方：

            sorted(数据, key=lambda x: x[1])

        这里那个 lambda 从头到尾没名字，用完就扔。

────────────────────────────────────────────────────────
【什么时候用它：三个现场】
────────────────────────────────────────────────────────

■ 现场一：排序时指定「按什么排」

    L4 第 2 课学过：

        学生 = [["张三", 85], ["李四", 92], ["王五", 78]]
        print(sorted(学生, key=lambda x: x[1]))

    `key` 收的是一个函数。sorted 会把每个元素丢进这个函数，
    拿返回值来比大小。所以 `x[1]` 就是「取第二项当比较依据」。

    不用 lambda 也行：

        def 取分数(x):
            return x[1]

        print(sorted(学生, key=取分数))

    效果一模一样。lambda 只是省了「起名字 + 写 def + 写 return」这几步。

    ── 多级排序：返回元组就行 ──

        分数从高到低，同分按名字从 A 到 Z：

            sorted(学生, key=lambda x: (-x[1], x[0]))

        `-x[1]` 把分数取负，负得越少（越接近 0）排越前，
        等于分数越高排越前。这是「单个数降序」的常用写法。

■ 现场二：找最大最小，但不是按元素本身

        scores = {"张三": 92, "李四": 88, "王五": 95}

        print(max(scores, key=lambda k: scores[k]))     → 王五

    字典直接 max() 比的是键（字符串），不是分数。
    加个 key 就变成「比 scores[k] 的值」。

■ 现场三：filter 和 map

    filter(条件函数, 可迭代对象)  → 留下返回 True 的
    map(变换函数, 可迭代对象)    → 每个元素都变换一次

        nums = [1, -2, 3, -4, 5]

        list(filter(lambda x: x > 0, nums))      → [1, 3, 5]
        list(map(lambda x: x * 10, nums))        → [10, -20, 30, -40, 50]

    ⚠ **必须套 list()**。
      因为 Python 3 里 filter / map 返回的是「迭代器」，
      不是列表。直接 print 会看到 `<filter object at 0x...>`。

      —— 这一点单选题爱考。

────────────────────────────────────────────────────────
【lambda 不能写什么】
────────────────────────────────────────────────────────

这个必须记清楚，判断题专门挖这种坑。

| 想写的 | lambda 能不能 | 说明 |
|---|---|---|
| `return` | ❌ 不能 | lambda 自动返回，写 return 直接 SyntaxError |
| 多条语句 | ❌ 不能 | 冒号后面只能有一个表达式 |
| `if ... else` 语句 | ❌ 不能 | 但**三元表达式**可以：`lambda x: 'A' if x>90 else 'B'` |
| `for` 循环 | ❌ 不能 | 但推导式可以塞进去：`lambda n: [i*i for i in range(n)]` |
| 调别的函数 | ✅ 可以 | `lambda x: len(x.strip())` |
| 嵌套 lambda | ✅ 可以 | `lambda x: lambda y: x+y`（别这么写，没人看得懂） |

    ── 记住这条分界线 ──

        **「表达式」可以有，。「语句」不可以。**

        表达式 = 算出一个值的东西（`x * 2`、`a if b else c`、`len(s)`）
        语句 = 做事的东西（`return`、`for`、`if...:`、`print`）

        —— 等等，print 是函数调用，算表达式。
           `lambda x: print(x)` 是合法的，它会返回 None。
           合法但没用 —— 你要打印用 def 就行了。

────────────────────────────────────────────────────────
【顺带：函数作为返回值（考纲「函数概念」也会考）】
────────────────────────────────────────────────────────

L3 第 5 课讲过「函数作为参数」。反过来也成立：

    def 造乘法器(n):
        return lambda x: x * n

    翻倍 = 造乘法器(2)
    翻十倍 = 造乘法器(10)

    print(翻倍(5))        → 10
    print(翻十倍(5))      → 50

这一招叫「闭包」：内层函数记住了外层函数的变量 n。

为什么两个函数互不干扰？因为每次调用 造乘法器，都会创建一个新的 n。

    ── 一个必须知道的坑：循环里创建 lambda ──

        funcs = []
        for i in range(3):
            funcs.append(lambda: i)

        print([f() for f in funcs])     → [2, 2, 2]  不是 [0, 1, 2]！

    因为 lambda 里的 i 是「变量名」，不是「当时的值」。
    循环结束后 i 停在 2，三个函数看到的都是同一个 i。

    修法：给 lambda 加个默认参数，让它当场把值存下来。

        funcs.append(lambda i=i: i)     → [0, 1, 2]

    这个坑在真实项目里很常见，考研题也爱考。

────────────────────────────────────────────────────────
【最后：lambda 该不该用】
────────────────────────────────────────────────────────

    该用：
        ✅ 一行能写完、只用一次、逻辑一眼看懂
        ✅ sorted / max / filter 的 key 参数

    不该用：
        ❌ 超过一行，或者要塞 if 三元
        ❌ 同样的逻辑要在多处用（那就该 def 一个名字）
        ❌ 起了名字之后又赋值给变量，然后到处传来传去

    一句话：**lambda 是便利贴，不是正式文档。**
    写个 key 挺好；把整个程序的逻辑写成嵌套 lambda，那是给自己挖坑。
'''


